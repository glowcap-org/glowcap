"""The benchmark report's source classification and process measurement rules."""

import os
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

import compile as consumer_compile
import measure


class MeasurementTest(unittest.TestCase):
    def test_compile_probe_changes_only_the_top_crate_command(self):
        raw = consumer_compile.build_command("raw", "one")
        generated = consumer_compile.build_command("generated", "two")
        self.assertEqual(raw[raw.index("--features") + 1], "raw-client")
        self.assertEqual(generated[generated.index("--features") + 1], "generated-client")
        self.assertIn("--no-default-features", raw)
        self.assertEqual(raw[raw.index("--") + 1 :], ["--cfg", 'interface_cost_probe="one"'])

    def test_arm_cpu_fields_do_not_require_x86_model_name_or_publish_serial(self):
        self.assertEqual(
            measure.cpu_details("CPU implementer : 0x41\nCPU part : 0xd40\nSerial : private\n"),
            {"CPU implementer": "0x41", "CPU part": "0xd40"},
        )
        self.assertEqual(measure.cpu_details("processor : 0\n"), {})

    def test_inventory_keeps_generated_and_outside_qualification_separate(self):
        with tempfile.TemporaryDirectory() as directory:
            previous = Path.cwd()
            os.chdir(directory)
            try:
                files = {
                    "tools/interface/sample.zig": 'const text = "test { }";\ntest "braces {" {\n const x = "}";\n}\n',
                    "apps/tasks/rust/interface.rs": "// Generated by `zig build gen-interface-fixtures` from fixture.\nconst X: u8 = 1;\n",
                    "test/interface/runner.rs": "fn main() {}\n",
                    "interop/goblins_interop/interface_client.rs": "fn main() {}\n",
                    "conformance/goblins-peer/racket/interface-creation-client.rkt": "#lang racket\n",
                    "bench/interface/src/main.rs": "fn main() {}\n",
                }
                for name, text in files.items():
                    path = Path(name)
                    path.parent.mkdir(parents=True, exist_ok=True)
                    path.write_text(text)
                with patch.object(measure, "command", return_value="\n".join(files)):
                    inventory = measure.inventory()
                self.assertEqual(inventory["compiler"][0]["implementation_nonblank"], 1)
                self.assertEqual(inventory["compiler"][0]["embedded_test_nonblank"], 3)
                self.assertEqual(len(inventory["generated_output"]), 1)
                self.assertEqual(len(inventory["handwritten_qualification"]), 3)
                self.assertEqual(len(inventory["benchmark_infrastructure"]), 1)
            finally:
                os.chdir(previous)

    def test_generator_measures_one_child_and_rejects_its_failure(self):
        with tempfile.TemporaryDirectory() as directory:
            executable = Path(directory) / "generator"
            executable.write_text("#!/bin/sh\nexit 0\n")
            executable.chmod(0o700)
            measurement = measure.run_generator(str(executable))
            self.assertGreater(measurement["elapsed_ns"], 0)
            self.assertGreater(measurement["peak_rss_upper_bound_bytes"], 0)
            executable.write_text("#!/bin/sh\nexit 7\n")
            with self.assertRaises(RuntimeError):
                measure.run_generator(str(executable))

    def test_records_keep_negative_live_deltas_and_frame_categories(self):
        rows = measure.records(
            "interface_alloc client=raw rust_live_delta=-8\ninterface_wire_arm arm=client:op:gc-answers count=2\n"
        )
        self.assertEqual(rows[0]["rust_live_delta"], -8)
        self.assertEqual(rows[1]["arm"], "client:op:gc-answers")


if __name__ == "__main__":
    unittest.main()
