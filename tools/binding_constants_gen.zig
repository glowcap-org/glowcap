//! Generates each binding's private ABI-constant module from one reflected
//! table, so a value is mirrored exactly once and cannot drift.
//!
//! The integer and big-integer constant families the Rust, Python, and Racket
//! bindings mirror from `pancake_ocapn.h` / `pancake_driver.h` used to be
//! hand-copied three times, guarded only by a prose "mirrors" comment. Here
//! the value comes from the `c_abi` / `c_abi_driver` declaration itself
//! (`c.PANCAKE_*` / `cd.PANCAKE_*`), so a C-side value change regenerates a
//! different file and `zig build gen-binding-constants-check` (part of
//! `check`) rejects the stale copy. The one reflected table is the source of
//! truth; every binding renders from it, so no two can disagree.
//!
//! Adding a binding is one emitter function plus one `outputs` row: a new
//! emitter reads `stem` and `value` and applies its own language's casing, so
//! it never touches this table. The only per-language names carried here are
//! the few whose established spelling is not the mechanical casing of `stem`
//! (Racket's reference sub-kind names), and those ride an optional column, not
//! a per-language table.
//!
//! Scope: integer and big-integer families reflected from the C ABI. The
//! `TRANSPORT_*` / `HINT_*` string symbols mirror `model.transport` (a
//! different authority) and stay hand-kept in each binding's constant module,
//! guarded by `meta-check` name-presence; this generator does not emit them.

const std = @import("std");
const c = @import("c_abi");
const cd = @import("c_abi_driver");

pub const Output = struct {
    path: []const u8,
    generate: *const fn (std.mem.Allocator) anyerror![]u8,
};

pub const outputs = [_]Output{
    .{ .path = "bindings/rust/src/abi_constants_gen.rs", .generate = generateRust },
    .{ .path = "bindings/python/pancake/_constants_gen.py", .generate = generatePython },
    .{ .path = "bindings/racket/private/constants-gen.rkt", .generate = generateRacket },
};

/// The Rust storage type for a reflected constant. Python and Racket are
/// untyped, so this steers only the Rust emitter: a return code is `c_int`,
/// an enum kind is `c_uint`, and a size or count is `usize`.
const RustTy = enum {
    int,
    uint,
    usize,

    fn spelling(self: RustTy) []const u8 {
        return switch (self) {
            .int => "c_int",
            .uint => "c_uint",
            .usize => "usize",
        };
    }
};

/// One reflected integer constant. `stem` is the canonical SCREAMING_SNAKE
/// name Rust and Python emit verbatim and Racket kebab-cases. `rkt` overrides
/// the Racket name only where the binding's established spelling is not the
/// mechanical kebab of `stem`. `value` is taken from the C ABI declaration, so
/// it cannot be hand-typed and drift.
const Const = struct {
    stem: []const u8,
    value: i64,
    rust_ty: RustTy,
    rkt: ?[]const u8 = null,
};

fn con(comptime stem: []const u8, value: anytype, rust_ty: RustTy, rkt: ?[]const u8) Const {
    return .{ .stem = stem, .value = @intCast(value), .rust_ty = rust_ty, .rkt = rkt };
}

