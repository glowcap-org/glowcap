//! Test constants come from independently authored messages, never from the
//! interface description or the lowering under test.
const std = @import("std");
const description = @import("description.zig");
const literal = @import("literal.zig").write;

pub fn generate(a: std.mem.Allocator) ![]u8 {
    var arena = std.heap.ArenaAllocator.init(a);
    defer arena.deinit();
    const root = try description.read(arena.allocator(), @embedFile("messages"));
    const creation = try root.get("create");
    if (creation.kind != .list or creation.children.len == 0 or creation.children[0].kind != .symbol) return error.InvalidDescription;
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(a);
    try out.appendSlice(a, "// Generated by `zig build gen-interface-fixtures` from test/interface/messages.syrup.\nuse glowcap::Argument;\npub const CREATION_VERB: &str = ");
    try literal(&out, a, creation.children[0].bytes);
    try out.appendSlice(a, ";\npub fn creation_arguments() -> Vec<Argument> {\n\tvec![\n");
    for (creation.children[1..]) |arg| {
        try out.appendSlice(a, "\t\t");
        switch (arg.kind) {
            .integer => try out.print(a, "Argument::Integer({d})", .{arg.integer}),
            .string => {
                try out.appendSlice(a, "Argument::String(");
                try literal(&out, a, arg.bytes);
                try out.appendSlice(a, ".into())");
            },
            else => return error.UnsupportedProjection,
        }
        try out.appendSlice(a, ",\n");
    }
    try out.appendSlice(a, "\t]\n}\n");
    const prepared = try root.get("prepared");
    if (prepared.kind != .list or prepared.children.len != 4 or prepared.children[0].kind != .symbol or prepared.children[1].kind != .integer or prepared.children[2].kind != .string) return error.InvalidDescription;
    try out.appendSlice(a, "pub const PREPARED_VERB: &str = ");
    try literal(&out, a, prepared.children[0].bytes);
    try out.print(a, ";\npub const PREPARED_SEQUENCE: i64 = {d};\npub const PREPARED_OPERATION: &str = ", .{prepared.children[1].integer});
    try literal(&out, a, prepared.children[2].bytes);
    try out.appendSlice(a, ";\n");
    const invocation = try root.get("handoff-call");
    if (invocation.kind != .list or invocation.children.len != 1 or invocation.children[0].kind != .string) return error.InvalidDescription;
    try out.appendSlice(a, "// Ordinary and Goblins consumers use different subsets of these fixtures.\n#[allow(dead_code)]\npub const HANDOFF_NAME: &str = ");
    try literal(&out, a, invocation.children[0].bytes);
    try out.appendSlice(a, ";\n");
    const reply = try root.get("handoff-result");
    if (reply.kind != .string) return error.InvalidDescription;
    try out.appendSlice(a, "#[allow(dead_code)]\npub const HANDOFF_RESULT: &str = ");
    try literal(&out, a, reply.bytes);
    try out.appendSlice(a, ";\n");
    try emitPresence(&out, a, root, true);
    return out.toOwnedSlice(a);
}

pub fn generateTypeScript(a: std.mem.Allocator) ![]u8 {
    var arena = std.heap.ArenaAllocator.init(a);
    defer arena.deinit();
    const root = try description.read(arena.allocator(), @embedFile("messages"));
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(a);
    try out.appendSlice(a, "// Generated by `zig build gen-interface-fixtures` from test/interface/messages.syrup.\nimport type { Argument } from \"@glowcap/runtime\";\n");
    try emitPresence(&out, a, root, false);
    return out.toOwnedSlice(a);
}

fn emitPresence(out: *std.ArrayList(u8), a: std.mem.Allocator, root: description.Node, rust: bool) !void {
    const cases = try root.get("presence");
    if (cases.kind != .dictionary) return error.InvalidDescription;
    try out.appendSlice(a, if (rust)
        "\n#[allow(dead_code)]\npub fn presence_arguments(name: &str) -> Vec<Argument> {\n\tmatch name {\n"
    else
        "\nexport const presenceArguments: Readonly<Record<string, readonly Argument[]>> = {\n");
    var i: usize = 0;
    while (i < cases.children.len) : (i += 2) {
        const name = try cases.children[i].string();
        const arguments = cases.children[i + 1];
        if (arguments.kind != .list) return error.InvalidDescription;
        try out.appendSlice(a, if (rust) "\t\t" else "\t");
        try literal(out, a, name);
        try out.appendSlice(a, if (rust) " => vec![" else ": [");
        for (arguments.children, 0..) |argument, index| {
            if (index != 0) try out.appendSlice(a, ", ");
            if (argument.kind == .string) {
                try literal(out, a, argument.bytes);
                if (rust) try out.appendSlice(a, ".into()");
            } else {
                _ = try argument.fields("void", 0);
                try out.appendSlice(a, if (rust) "Argument::Void" else "null");
            }
        }
        try out.appendSlice(a, "],\n");
    }
    try out.appendSlice(a, if (rust) "\t\t_ => panic!(\"unknown presence expectation\"),\n\t}\n}\n" else "};\n");
}
