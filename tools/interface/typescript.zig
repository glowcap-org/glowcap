//! Narrow TypeScript promise-shape probe over the shared checked call model.
const std = @import("std");
const calls = @import("calls.zig");
const literal = @import("literal.zig").write;

pub fn emit(a: std.mem.Allocator, methods: []const calls.Named) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(a);
    try out.appendSlice(a, "// Generated by `zig build gen-interface-fixtures` from test/interface/contracts.syrup.\n");
    try out.appendSlice(a, @embedFile("templates/pending.ts.in"));
    for (methods) |method| {
        const call = method.call;
        try out.print(a, "\nexport function {s}(\n\tsession: Session,\n\ttarget: Ref | RemotePromise,\n", .{method.api});
        for (call.parameters, 0..) |kind, i| {
            if (kind == .nothing) return error.UnsupportedProjection;
            try out.print(a, "\targ{d}: {s},\n", .{ i, typeName(kind) });
        }
        if (call.tell) {
            try out.appendSlice(a, "): Promise<void> {\n\treturn session.tell(target, ");
        } else {
            try out.print(a, "): Pending<{s}> {{\n\tconst raw = session.send(target, ", .{typeName(call.result)});
        }
        try literal(&out, a, call.wire_name);
        try out.appendSlice(a, ", [");
        for (call.parameters, 0..) |_, i| {
            if (i != 0) try out.appendSlice(a, ", ");
            try out.print(a, "arg{d}", .{i});
        }
        try out.appendSlice(a, "]);\n");
        if (!call.tell) try out.print(a, "\treturn new Pending(raw, {s});\n", .{switch (call.result) {
            .target => "capability",
            .text => "text",
            .nothing => "nothing",
            else => return error.UnsupportedProjection,
        }});
        try out.appendSlice(a, "}\n");
    }
    return out.toOwnedSlice(a);
}

fn typeName(kind: calls.Kind) []const u8 {
    return switch (kind) {
        .target => "Ref",
        .pending_target => "Ref | RemotePromise",
        .text => "string",
        .nothing => "void",
        .value => "Argument",
    };
}
