//! Rust ordinary-call projection for the independently hosted callback fixture.
const std = @import("std");
const calls = @import("calls.zig");
const literal = @import("literal.zig").write;

pub fn emit(a: std.mem.Allocator, methods: []const calls.Named) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(a);
    try out.appendSlice(a, "// Generated by `zig build gen-interface-fixtures` from test/interface/contracts.syrup.\n");
    try out.appendSlice(a, @embedFile("templates/support.rs"));
    try out.appendSlice(a, @embedFile("templates/references.rs"));
    for (methods) |method| try emitCall(&out, a, method.call, method.api);
    return out.toOwnedSlice(a);
}

fn emitCall(out: *std.ArrayList(u8), a: std.mem.Allocator, call: calls.Call, api: []const u8) !void {
    var has_references = false;
    for (call.parameters) |parameter| if (parameter == .target or parameter == .pending_target) {
        has_references = true;
    };
    try out.print(a, "\npub fn {s}{s}(session: &Session, target: impl AsSendTarget", .{ api, if (has_references) "<'a>" else "" });
    for (call.parameters, 0..) |parameter, i| try out.print(a, ", arg{d}: {s}", .{ i, parameterType(parameter) });
    if (call.tell) {
        try out.appendSlice(a, ") -> Result<(), Error> {\n\tsession.tell(target, ");
    } else {
        try out.print(a, ") -> Pending<{s}> {{\n\tlet raw = session.send(target, ", .{resultType(call.result)});
    }
    try literal(out, a, call.wire_name);
    try out.appendSlice(a, ", &[");
    for (call.parameters, 0..) |parameter, i| {
        if (i != 0) try out.appendSlice(a, ", ");
        try out.print(a, "arg{d}{s}", .{ i, switch (parameter) {
            .target, .pending_target => ".into().argument()",
            .text => ".into()",
            .value => "",
            .nothing => return error.UnsupportedProjection,
        } });
    }
    if (call.tell) {
        try out.appendSlice(a, "]).map_err(Error::Runtime)\n}\n");
    } else {
        try out.print(a, "]);\n\tPending::new(raw, {s})\n}}\n", .{switch (call.result) {
            .target => "capability",
            .text => "text",
            .nothing => "nothing",
            .value => "Ok",
            .pending_target => return error.UnsupportedProjection,
        }});
    }
}

fn parameterType(kind: calls.Kind) []const u8 {
    return switch (kind) {
        .target, .pending_target => "impl Into<Reference<'a>>",
        .text => "&str",
        .value => "Argument",
        .nothing => "()",
    };
}

fn resultType(kind: calls.Kind) []const u8 {
    return switch (kind) {
        .target, .pending_target => "Ref",
        .text => "String",
        .value => "Argument",
        .nothing => "()",
    };
}
