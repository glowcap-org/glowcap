//! Narration in first-party comments obeys the same lifetime rule as static docs.
const std = @import("std");
const util = @import("../util.zig");
const narration = @import("static_docs.zig");

pub fn check(io: std.Io, gpa: std.mem.Allocator, root: std.Io.Dir, violations: *std.ArrayList([]const u8)) !void {
    var walker = try root.walkSelectively(gpa);
    defer walker.deinit();
    while (try walker.next(io)) |entry| {
        if (entry.kind == .directory) {
            if (util.sourceTreeDirectory(entry.path) and !in(entry.basename, &.{ "upstream", "vendor", "third_party" })) try walker.enter(io, entry);
            continue;
        }
        if (entry.kind != .file) continue;
        const ext = std.fs.path.extension(entry.path);
        const hash = in(ext, &.{ ".py", ".sh", ".bash" });
        const scheme = in(ext, &.{ ".rkt", ".scm" });
        if (!hash and !scheme and !in(ext, &.{ ".zig", ".rs", ".c", ".h", ".ts", ".tsx", ".js", ".mjs", ".jsx", ".css" })) continue;
        const text = try root.readFileAlloc(io, entry.path, gpa, .limited(16 << 20));
        defer gpa.free(text);
        const header = text[0..@min(text.len, 400)];
        if (std.mem.indexOf(u8, header, "Generated from") != null or std.mem.indexOf(u8, header, "Generated by") != null or std.mem.indexOf(u8, header, "GENERATED by") != null) continue;
        var scanner: Comments = .{ .rust = std.mem.eql(u8, ext, ".rs") };
        var lines = std.mem.splitScalar(u8, text, '\n');
        var number: usize = 0;
        while (lines.next()) |line| {
            number += 1;
            scanner.at = 0;
            while (scanner.comment(line, if (hash) '#' else if (scheme) ';' else null)) |comment| {
                try narration.checkNarration(gpa, violations, entry.path, number, comment);
            }
        }
    }
}
fn in(ext: []const u8, set: []const []const u8) bool {
    for (set) |candidate| if (std.mem.eql(u8, ext, candidate)) return true;
    return false;
}

const Comments = struct {
    rust: bool = false,
    block: bool = false,
    quote: ?u8 = null,
    triple: bool = false,
    raw_hashes: ?usize = null,
    at: usize = 0,

    /// Continue lexical state across lines, returning each comment in turn.
    fn comment(self: *Comments, line: []const u8, single: ?u8) ?[]const u8 {
        if (std.mem.startsWith(u8, std.mem.trimStart(u8, line, " \t"), "\\\\")) return null;
        while (self.at < line.len) {
            const i = self.at;
            self.at += 1;
            if (self.block) {
                if (std.mem.indexOfPos(u8, line, i, "*/")) |end| {
                    self.block = false;
                    self.at = end + 2;
                    return line[i..end];
                }
                self.at = line.len;
                return line[i..];
            }
            const c = line[i];
            if (self.quote) |q| {
                if (c == '\\' and self.raw_hashes == null) {
                    self.at = @min(line.len, i + 2);
                    continue;
                }
                if (c != q) continue;
                if (self.triple) {
                    if (i + 2 >= line.len or line[i + 1] != q or line[i + 2] != q) continue;
                    self.at = i + 3;
                }
                if (self.raw_hashes) |n| {
                    if (i + 1 + n > line.len) continue;
                    var matches = true;
                    for (line[i + 1 .. i + 1 + n]) |hash| if (hash != '#') {
                        matches = false;
                    };
                    if (!matches) continue;
                    self.at = i + 1 + n;
                }
                self.quote = null;
                self.triple = false;
                self.raw_hashes = null;
                continue;
            }
            // Rust lifetime labels are not character literals.
            if (self.rust and c == '\'' and i + 1 < line.len and (std.ascii.isAlphabetic(line[i + 1]) or line[i + 1] == '_') and (i + 2 == line.len or line[i + 2] != '\'')) continue;
            if (single == null and c == 'r') {
                var end = i + 1;
                while (end < line.len and line[end] == '#') : (end += 1) {}
                if (end < line.len and line[end] == '"') {
                    self.raw_hashes = end - i - 1;
                    self.quote = '"';
                    self.at = end + 1;
                    continue;
                }
            }
            if (single == ';' and c == '\'') continue;
            if (c == '"' or c == '\'' or c == '`') {
                self.quote = c;
                if (single == '#' and i + 2 < line.len and line[i + 1] == c and line[i + 2] == c) {
                    self.triple = true;
                    self.at = i + 3;
                }
                continue;
            }
            if (single) |marker| {
                if (c == marker) {
                    self.at = line.len;
                    return line[i..];
                }
            } else if (c == '/' and i + 1 < line.len) {
                if (line[i + 1] == '/') {
                    self.at = line.len;
                    return line[i..];
                }
                if (line[i + 1] == '*') {
                    self.block = true;
                    self.at = i + 2;
                }
            }
        }
        return null;
    }
    fn first(self: *Comments, line: []const u8, single: ?u8) ?[]const u8 {
        self.at = 0;
        return self.comment(line, single);
    }
};

test "comment scanning preserves multiline strings and Rust lifetime syntax" {
    var scanner: Comments = .{ .rust = true };
    try std.testing.expect(scanner.first("const s = \"https://earlier/\";", null) == null);
    try std.testing.expectEqualStrings("// previously", scanner.first("fn f<'a>() {} // previously", null).?);
    try std.testing.expectEqualStrings(" formerly ", scanner.first("/* formerly */ /* earlier */", null).?);
    try std.testing.expectEqualStrings(" earlier ", scanner.comment("/* formerly */ /* earlier */", null).?);
    try std.testing.expect(scanner.first("const template = `", null) == null);
    try std.testing.expect(scanner.first("// previously", null) == null);
    try std.testing.expectEqualStrings("// yet", scanner.first("`; // yet", null).?);
    try std.testing.expect(scanner.first("s = \"\"\"", '#') == null);
    try std.testing.expect(scanner.first("# formerly", '#') == null);
    try std.testing.expectEqualStrings("# yet", scanner.first("\"\"\" # yet", '#').?);
    try std.testing.expect(scanner.first("let raw = r#\"", null) == null);
    try std.testing.expect(scanner.first("// formerly \"", null) == null);
    try std.testing.expectEqualStrings("// yet", scanner.first("\"#; // yet", null).?);
    try std.testing.expect(scanner.first("\\\\// yet", null) == null);
}
