//! Which files a source check reads: the traversal policy that keeps generated
//! and vendored trees out, sorted and cached file inventories, package-subject
//! reads, and the concatenated build-step sources.

const std = @import("std");
const violation_log = @import("violation_log.zig");

/// Concatenate every file in `dir_path` whose name `keep` accepts, sorted.
/// Null when the directory is missing. Any other failure is returned.
pub fn concatDirFiles(
    io: std.Io,
    gpa: std.mem.Allocator,
    root: std.Io.Dir,
    dir_path: []const u8,
    keep: *const fn (name: []const u8) bool,
) !?[]u8 {
    var names: std.ArrayList([]const u8) = .empty;
    defer {
        for (names.items) |n| gpa.free(n);
        names.deinit(gpa);
    }
    var dir = root.openDir(io, dir_path, .{ .iterate = true }) catch |err| switch (err) {
        error.FileNotFound => return null,
        else => return err,
    };
    defer dir.close(io);
    var it = dir.iterate();
    while (true) {
        const entry = (try it.next(io)) orelse break;
        if (entry.kind == .directory) continue;
        if (!keep(entry.name)) continue;
        const owned_name = try gpa.dupe(u8, entry.name);
        errdefer gpa.free(owned_name);
        try names.append(gpa, owned_name);
    }
    std.mem.sort([]const u8, names.items, {}, struct {
        fn less(_: void, a: []const u8, b: []const u8) bool {
            return std.mem.lessThan(u8, a, b);
        }
    }.less);

    var buf: std.ArrayList(u8) = .empty;
    errdefer buf.deinit(gpa);
    for (names.items) |name| {
        const path = try std.fmt.allocPrint(gpa, "{s}/{s}", .{ dir_path, name });
        defer gpa.free(path);
        const body = try root.readFileAlloc(io, path, gpa, .limited(1 << 20));
        defer gpa.free(body);
        try buf.appendSlice(gpa, body);
        try buf.append(gpa, '\n');
    }
    return try buf.toOwnedSlice(gpa);
}

/// Generated and vendored directories no source contract may enter: build
/// output, installed packages, and the pinned `upstream` submodules or
/// `vendor` and `third_party` checkouts that belong to someone else.
///
/// This is a traversal policy, not a result filter. Rejecting one of these
/// paths after `walk()` has already enumerated it still makes every static
/// check pay for a Cargo target or JavaScript dependency tree. Keep the
/// directory decision here so broad `apps` and `bindings` checks cannot drift
/// into generated state independently.
pub fn sourceTreeDirectory(path: []const u8) bool {
    var parts = std.mem.splitScalar(u8, path, '/');
    while (parts.next()) |part| {
        if (std.mem.eql(u8, part, "node_modules") or
            std.mem.eql(u8, part, "target") or
            std.mem.eql(u8, part, "zig-out") or
            std.mem.eql(u8, part, "zig-pkg") or
            std.mem.eql(u8, part, ".zig-cache") or
            std.mem.eql(u8, part, ".venv") or
            std.mem.eql(u8, part, "__pycache__") or
            std.mem.eql(u8, part, "compiled") or
            std.mem.eql(u8, part, ".vite") or
            std.mem.eql(u8, part, ".deno") or
            std.mem.eql(u8, part, ".git") or
            std.mem.eql(u8, part, ".local") or
            std.mem.eql(u8, part, "upstream") or
            std.mem.eql(u8, part, "vendor") or
            std.mem.eql(u8, part, "third_party")) return false;
    }
    // The visualizer bundle is generated by its build and is not source, and
    // so is the Rooms page `site-rooms-page` exports beside the site's assets.
    if (std.mem.eql(u8, path, "apps/ocapnviz/dist") or
        std.mem.startsWith(u8, path, "apps/ocapnviz/dist/") or
        std.mem.eql(u8, path, "site/assets/rooms") or
        std.mem.startsWith(u8, path, "site/assets/rooms/")) return false;
    return true;
}

test "generated trees beside source are not entered" {
    try std.testing.expect(sourceTreeDirectory("site/assets"));
    try std.testing.expect(sourceTreeDirectory("apps/ocapnviz/src"));
    try std.testing.expect(!sourceTreeDirectory("site/assets/rooms/app"));
    try std.testing.expect(!sourceTreeDirectory("apps/ocapnviz/dist/assets"));
    try std.testing.expect(!sourceTreeDirectory("apps/rooms/rust/target"));
}

/// Whether `path` names a TypeScript module, `.ts` or `.tsx`.
pub fn isTypeScriptPath(path: []const u8) bool {
    return std.mem.endsWith(u8, path, ".ts") or std.mem.endsWith(u8, path, ".tsx");
}

/// Enter a selective walk directory only when it belongs to source state.
/// `root_path` is the repository-relative directory the walker was opened on.
pub fn enterSourceDirectory(
    io: std.Io,
    gpa: std.mem.Allocator,
    walker: *std.Io.Dir.SelectiveWalker,
    root_path: []const u8,
    entry: std.Io.Dir.Walker.Entry,
) !void {
    const repo_path = try std.fmt.allocPrint(gpa, "{s}/{s}", .{ root_path, entry.path });
    defer gpa.free(repo_path);
    if (sourceTreeDirectory(repo_path)) try walker.enter(io, entry);
}

/// One immutable repository-relative file inventory per source tree.
/// Callers retain their own suffix and exclusion policy over the returned
/// paths. The map and every path use `arena` and live for that allocator's
/// lifetime.
pub fn cachedSourceTreeFiles(
    io: std.Io,
    arena: std.mem.Allocator,
    root: std.Io.Dir,
    root_path: []const u8,
    inventories: *std.StringHashMapUnmanaged([]const []const u8),
) ![]const []const u8 {
    if (inventories.get(root_path)) |files| return files;

    var files: std.ArrayList([]const u8) = .empty;
    var dir = try root.openDir(io, root_path, .{ .iterate = true });
    defer dir.close(io);
    var walker = try dir.walkSelectively(arena);
    defer walker.deinit();
    while (try walker.next(io)) |walk_entry| {
        if (walk_entry.kind == .directory) {
            try enterSourceDirectory(io, arena, &walker, root_path, walk_entry);
            continue;
        }
        if (walk_entry.kind != .file) continue;
        try files.append(arena, try std.fmt.allocPrint(arena, "{s}/{s}", .{ root_path, walk_entry.path }));
    }
    const owned = try files.toOwnedSlice(arena);
    try inventories.put(arena, root_path, owned);
    return owned;
}

/// Every file beneath `root_path` that `keep` accepts, as repository-relative
/// paths in sorted order, or null when `root_path` is not a directory in this
/// tree. Any other failure to open, walk, or enter a directory is an error the
/// caller reports.
///
/// One authority for what counts as a file a check reads. The walk itself is
/// the part three checks were each spelling out, and they had already come to
/// disagree about vendored trees, which is the ordinary way duplicated
/// traversal rots. Sorted because violation output a reader compares between
/// runs should not depend on what order a filesystem hands its entries back.
///
/// The caller owns the list and every path in it, and reads each file itself:
/// the read limit and the sentence a failure gets belong to the check, not
/// here.
pub fn collectSourceFiles(
    io: std.Io,
    gpa: std.mem.Allocator,
    root: std.Io.Dir,
    root_path: []const u8,
    keep: *const fn (path: []const u8) bool,
) !?[][]u8 {
    var dir = root.openDir(io, root_path, .{ .iterate = true }) catch |err| switch (err) {
        error.FileNotFound, error.NotDir => return null,
        else => return err,
    };
    defer dir.close(io);
    var walker = try dir.walkSelectively(gpa);
    defer walker.deinit();
    var found: std.ArrayList([]u8) = .empty;
    errdefer {
        for (found.items) |path| gpa.free(path);
        found.deinit(gpa);
    }
    while (try walker.next(io)) |entry| {
        if (entry.kind == .directory) {
            try enterSourceDirectory(io, gpa, &walker, root_path, entry);
            continue;
        }
        if (entry.kind != .file or !keep(entry.path)) continue;
        try found.append(gpa, try std.fmt.allocPrint(gpa, "{s}/{s}", .{ root_path, entry.path }));
    }
    std.mem.sort([]u8, found.items, {}, struct {
        fn less(_: void, a: []u8, b: []u8) bool {
            return std.mem.lessThan(u8, a, b);
        }
    }.less);
    return try found.toOwnedSlice(gpa);
}

/// The most bytes a check reads from one source file. `file_length` holds every
/// first-party source far below it, so a larger file is a read failure.
pub const source_read_limit = 4 << 20;

/// Call `visit(ctx, path, contents)` for every file beneath `root_path` that
/// `keep` accepts, in sorted order, skipping generated and vendored trees. `path` is
/// repository-relative and `contents` is read whole within
/// `source_read_limit`, owned by this function, and freed after the call, so a
/// visitor that keeps text copies it. A visitor may blank bytes in place.
///
/// A missing tree, and a file that cannot be read, each append one violation
/// naming the check by `label` (and, for the read, the exact error), and the
/// walk goes on with the next file. Any other walk failure is this function's
/// error. A check that needs to stop early, keep the
/// contents, or send a failure somewhere else walks the tree itself.
pub fn visitSourceFiles(
    io: std.Io,
    gpa: std.mem.Allocator,
    root: std.Io.Dir,
    violations: *std.ArrayList([]const u8),
    label: []const u8,
    root_path: []const u8,
    keep: *const fn (path: []const u8) bool,
    ctx: anytype,
    visit: *const fn (@TypeOf(ctx), path: []const u8, contents: []u8) std.mem.Allocator.Error!void,
) !void {
    const files = (try collectSourceFiles(io, gpa, root, root_path, keep)) orelse {
        try violation_log.appendViolation(gpa, violations, "{s}: no such directory for the {s} check", .{ root_path, label });
        return;
    };
    defer {
        for (files) |path| gpa.free(path);
        gpa.free(files);
    }
    for (files) |path| {
        const contents = root.readFileAlloc(io, path, gpa, .limited(source_read_limit)) catch |err| {
            try violation_log.appendViolation(gpa, violations, "{s}: cannot be read for the {s} check ({s})", .{ path, label, @errorName(err) });
            continue;
        };
        defer gpa.free(contents);
        try visit(ctx, path, contents);
    }
}

/// Whether `path` is a Zig source file.
pub fn isZigPath(path: []const u8) bool {
    return std.mem.endsWith(u8, path, ".zig");
}

test "visitSourceFiles reads each kept file once and names a missing tree" {
    const gpa = std.testing.allocator;
    const io = std.testing.io;
    var tmp = std.testing.tmpDir(.{ .iterate = true });
    defer tmp.cleanup();
    try tmp.dir.createDirPath(io, "src/target");
    try tmp.dir.writeFile(io, .{ .sub_path = "src/b.zig", .data = "bb" });
    try tmp.dir.writeFile(io, .{ .sub_path = "src/a.zig", .data = "a" });
    try tmp.dir.writeFile(io, .{ .sub_path = "src/note.md", .data = "md" });
    try tmp.dir.writeFile(io, .{ .sub_path = "src/target/gen.zig", .data = "gen" });

    var violations: std.ArrayList([]const u8) = .empty;
    defer {
        for (violations.items) |v| gpa.free(v);
        violations.deinit(gpa);
    }
    const Seen = struct {
        gpa: std.mem.Allocator,
        log: std.ArrayList(u8) = .empty,
        fn visit(self: *@This(), path: []const u8, contents: []u8) std.mem.Allocator.Error!void {
            try self.log.print(self.gpa, "{s}={d};", .{ path, contents.len });
        }
    };
    var seen: Seen = .{ .gpa = gpa };
    defer seen.log.deinit(gpa);
    try visitSourceFiles(io, gpa, tmp.dir, &violations, "probe", "src", &isZigPath, &seen, Seen.visit);
    try std.testing.expectEqualStrings("src/a.zig=1;src/b.zig=2;", seen.log.items);
    try std.testing.expectEqual(@as(usize, 0), violations.items.len);

    try visitSourceFiles(io, gpa, tmp.dir, &violations, "probe", "absent", &isZigPath, &seen, Seen.visit);
    try std.testing.expectEqual(@as(usize, 1), violations.items.len);
    try std.testing.expectEqualStrings("absent: no such directory for the probe check", violations.items[0]);
}

test "collectSourceFiles never enters generated trees" {
    const gpa = std.testing.allocator;
    const io = std.testing.io;
    var tmp = std.testing.tmpDir(.{ .iterate = true });
    defer tmp.cleanup();
    try tmp.dir.createDirPath(io, "apps/pkg/src");
    try tmp.dir.createDirPath(io, "apps/pkg/target/deep");
    try tmp.dir.createDirPath(io, "apps/pkg/node_modules/deep");
    try tmp.dir.createDirPath(io, "apps/pkg/__pycache__/deep");
    try tmp.dir.createDirPath(io, "apps/pkg/compiled/deep");
    try tmp.dir.createDirPath(io, "apps/pkg/upstream/deep");
    try tmp.dir.writeFile(io, .{ .sub_path = "apps/pkg/src/kept.ts", .data = "kept" });
    try tmp.dir.writeFile(io, .{ .sub_path = "apps/pkg/target/deep/generated.ts", .data = "generated" });
    try tmp.dir.writeFile(io, .{ .sub_path = "apps/pkg/node_modules/deep/vendor.ts", .data = "vendor" });
    try tmp.dir.writeFile(io, .{ .sub_path = "apps/pkg/__pycache__/deep/bytecode.ts", .data = "generated" });
    try tmp.dir.writeFile(io, .{ .sub_path = "apps/pkg/compiled/deep/bytecode.ts", .data = "generated" });
    try tmp.dir.writeFile(io, .{ .sub_path = "apps/pkg/upstream/deep/pinned.ts", .data = "vendor" });

    const keepTs = struct {
        fn keep(path: []const u8) bool {
            return std.mem.endsWith(u8, path, ".ts");
        }
    }.keep;
    const files = (try collectSourceFiles(io, gpa, tmp.dir, "apps", keepTs)) orelse
        return error.TestUnexpectedResult;
    defer {
        for (files) |path| gpa.free(path);
        gpa.free(files);
    }
    try std.testing.expectEqual(@as(usize, 1), files.len);
    try std.testing.expectEqualStrings("apps/pkg/src/kept.ts", files[0]);
}

/// Read one source file, or concatenate every regular file beneath a package
/// directory when `path` ends in `/`. Directory subjects keep ownership bans
/// valid after a module becomes a package: a new leaf cannot evade a rule
/// written for the single file.
pub fn readSourceSubject(
    io: std.Io,
    gpa: std.mem.Allocator,
    root: std.Io.Dir,
    path: []const u8,
) !?[]u8 {
    if (!std.mem.endsWith(u8, path, "/")) {
        return root.readFileAlloc(io, path, gpa, .limited(source_read_limit)) catch |err| switch (err) {
            error.FileNotFound => null,
            else => err,
        };
    }
    const dir_path = path[0 .. path.len - 1];
    var dir = root.openDir(io, dir_path, .{ .iterate = true }) catch |err| switch (err) {
        error.FileNotFound => return null,
        else => return err,
    };
    defer dir.close(io);
    var walker = try dir.walk(gpa);
    defer walker.deinit();
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    while (try walker.next(io)) |entry| {
        if (entry.kind != .file) continue;
        const body = try dir.readFileAlloc(io, entry.path, gpa, .limited(source_read_limit));
        defer gpa.free(body);
        try out.appendSlice(gpa, body);
        try out.append(gpa, '\n');
    }
    return try out.toOwnedSlice(gpa);
}

test "readSourceSubject includes every nested package leaf" {
    const gpa = std.testing.allocator;
    var tmp = std.testing.tmpDir(.{ .iterate = true });
    defer tmp.cleanup();
    const io = std.testing.io;
    try tmp.dir.createDirPath(io, "pkg/nested");
    try tmp.dir.writeFile(io, .{ .sub_path = "pkg/root.py", .data = "root-marker" });
    try tmp.dir.writeFile(io, .{ .sub_path = "pkg/nested/leaf.py", .data = "leaf-marker" });
    const subject = (try readSourceSubject(io, gpa, tmp.dir, "pkg/")) orelse
        return error.TestUnexpectedResult;
    defer gpa.free(subject);
    try std.testing.expect(std.mem.indexOf(u8, subject, "root-marker") != null);
    try std.testing.expect(std.mem.indexOf(u8, subject, "leaf-marker") != null);
}

/// The sources that register build steps: the root `build.zig` plus every
/// composed step-registration module beneath `tools/build/`, concatenated into
/// one owned buffer so a textual step scan sees the whole graph the root
/// composes. The recursive walk matters because a subject that outgrows one
/// file becomes a package, nesting must not make its steps invisible to the
/// documentation and check-membership ratchets. Callers free the result.
pub fn readBuildStepSources(
    io: std.Io,
    gpa: std.mem.Allocator,
    root: std.Io.Dir,
) ![]u8 {
    var buf: std.ArrayList(u8) = .empty;
    errdefer buf.deinit(gpa);
    const root_src = try root.readFileAlloc(io, "build.zig", gpa, .limited(1 << 21));
    defer gpa.free(root_src);
    try buf.appendSlice(gpa, root_src);
    var dir = try root.openDir(io, "tools/build", .{ .iterate = true });
    defer dir.close(io);
    var walker = try dir.walk(gpa);
    defer walker.deinit();
    while (try walker.next(io)) |entry| {
        if (entry.kind != .file or !std.mem.endsWith(u8, entry.path, ".zig")) continue;
        const src = try dir.readFileAlloc(io, entry.path, gpa, .limited(1 << 21));
        defer gpa.free(src);
        try buf.append(gpa, '\n');
        try buf.appendSlice(gpa, src);
    }
    return buf.toOwnedSlice(gpa);
}
