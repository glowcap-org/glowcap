//! Generates `bindings/ts/stack/internal/abi.ts` — the TypeScript mirror of the
//! `libpancake_ocapn` ABI — from the Zig source of truth.
//!
//! JavaScript FFI has no struct types, so the TypeScript binding reads C structs
//! through byte offsets. Every other binding declares fields symbolically
//! (ctypes, `define-cstruct`, `#[repr(C)]`); TypeScript alone would have to keep
//! hand-derived numbers, the one mirror a reviewer could not trust. This tool
//! removes that class: constant values come from the `c_abi` declarations and
//! layout numbers from `@sizeOf`/`@offsetOf`, so a struct or constant change in
//! Zig regenerates the TypeScript mirror instead of silently invalidating it.
//! `zig build gen-ts-abi-check` (part of `check`) holds the committed file
//! against a fresh generation, the same discipline as the C headers.

const std = @import("std");
const c = @import("c_abi");

pub const header_path = "bindings/ts/stack/internal/abi.ts";

const preamble =
    \\// GENERATED by `zig build gen-ts-abi` from src/c_abi/ocapn — do not edit.
    \\// `zig build gen-ts-abi-check` (part of `check`) fails when this is stale.
    \\//
    \\// The TypeScript mirror of the libpancake_ocapn ABI: constant values from
    \\// the Zig declarations, struct sizes and field offsets from
    \\// @sizeOf/@offsetOf. JavaScript FFI has no struct types, so the binding
    \\// reads C structs through these offsets; generating them is what makes the
    \\// one offset-based mirror as trustworthy as a symbolic one.
    \\
    \\
;

/// One generated constant: the TypeScript name and the `c_abi` declaration it
/// mirrors. Referencing the declaration makes a C-side rename a compile error
/// here rather than a stale mirror.
const Const = struct {
    ts: []const u8,
    value: i64,
};

fn k(comptime ts: []const u8, comptime decl: []const u8) Const {
    return .{ .ts = ts, .value = @intCast(@field(c, decl)) };
}

/// One generated `bigint` constant, for the values wider than JavaScript's safe
/// integer range: emitted with the `n` suffix so the mirror stays exact.
const BigConst = struct {
    ts: []const u8,
    value: u64,
};

fn kb(comptime ts: []const u8, comptime decl: []const u8) BigConst {
    return .{ .ts = ts, .value = @field(c, decl) };
}

