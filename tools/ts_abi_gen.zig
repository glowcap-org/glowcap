/// One generated struct layout: the TS constant prefix and the extern struct.
/// Every field is emitted as `<PREFIX>_<FIELD>_OFF` plus a `<PREFIX>_SIZE`.
fn emitLayout(
    out: *std.ArrayList(u8),
    gpa: std.mem.Allocator,
    comptime prefix: []const u8,
    comptime T: type,
    comptime note: []const u8,
) !void {
    try out.print(gpa, "// {s}\n", .{note});
    try out.print(gpa, "export const {s}_SIZE = {d};\n", .{ prefix, @sizeOf(T) });
    inline for (@typeInfo(T).@"struct".fields) |field| {
        // C snake_case field names become the same name upper-cased, so the
        // TypeScript reader names the field it is reading.
        comptime var upper: [field.name.len]u8 = undefined;
        comptime for (field.name, 0..) |ch, i| {
            upper[i] = std.ascii.toUpper(ch);
        };
        try out.print(gpa, "export const {s}_{s}_OFF = {d};\n", .{ prefix, upper, @offsetOf(T, field.name) });
    }
    try out.appendSlice(gpa, "\n");
}

pub fn generate(gpa: std.mem.Allocator) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);

    try out.appendSlice(gpa, preamble);
    try out.appendSlice(gpa, "// ── Constants (values mirror src/c_abi declarations) ─────────────────────\n\n");
    inline for (constants) |entry| {
        try out.print(gpa, "export const {s} = {d};\n", .{ entry.ts, entry.value });
    }
    inline for (big_constants) |entry| {
        try out.print(gpa, "export const {s} = {d}n;\n", .{ entry.ts, entry.value });
    }
    try out.appendSlice(gpa, "\n// ── Struct layouts (@sizeOf/@offsetOf on the extern structs) ─────────────\n\n");

    try emitLayout(&out, gpa, "REF", c.PancakeReference, "PancakeReference");
    try emitLayout(&out, gpa, "ARG", c.PancakeArgument, "PancakeArgument");
    try emitLayout(&out, gpa, "FRAME", c.PancakeFrame, "PancakeFrame (borrowed)");
    try emitLayout(&out, gpa, "MANAGED_FRAME", c.PancakeManagedFrame, "PancakeManagedFrame (owned, self-releasing)");
    try emitLayout(&out, gpa, "EVENT", c.PancakeEvent, "PancakeEvent (opaque poll)");
    try emitLayout(&out, gpa, "DELIVER", c.PancakeDeliver, "PancakeDeliver");
    try emitLayout(&out, gpa, "HANDOFF_GIVE", c.PancakeHandoffGive, "PancakeHandoffGive");
    try emitLayout(&out, gpa, "RESOLVE", c.PancakeResolve, "PancakeResolve");
    try emitLayout(&out, gpa, "ANY_EVENT", c.PancakeAnyEvent, "PancakeAnyEvent (pancake_peer_next_event)");
    try emitLayout(&out, gpa, "NODE_ACTION", c.PancakeNodeAction, "PancakeNodeAction (the serve step, ADR-0067)");
    try emitLayout(&out, gpa, "ENLIVEN_START", c.PancakeEnlivenStart, "PancakeEnlivenStart (ADR-0012)");
    try emitLayout(&out, gpa, "LAST_ABORT", c.PancakeLastAbort, "PancakeLastAbort");
    try emitLayout(&out, gpa, "ALLOCATOR", c.PancakeAllocator, "PancakeAllocator (pancake_context_new_with_allocator)");

    return out.toOwnedSlice(gpa);
}
