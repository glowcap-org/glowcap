//! Write the site's brand-mark bundle with the generated-file header the
//! tree's checks recognise.
//!
//! `zig build site` bundles `site/brand_mark.ts` with `deno bundle`, which
//! writes no header of its own. A bundle sitting in `site/assets` without one
//! reads as source to everything that walks the tree: the file-length
//! ratchet would ask for it to be split by subject, and a reader might edit
//! it. This tool puts the header in front and writes the file Zine ships.
//!
//! Usage: site-brand-mark <bundle> <output>

const std = @import("std");

const header =
    \\// GENERATED by `zig build site` from site/brand_mark.ts and the rooms
    \\// shader mark under apps/rooms/web/ui/. Do not edit; edit the sources.
    \\
;

pub fn main(init: std.process.Init) !void {
    const gpa = init.arena.allocator();
    var threaded = std.Io.Threaded.init(gpa, .{});
    defer threaded.deinit();
    const io = threaded.io();

    var args = std.process.Args.Iterator.init(init.minimal.args);
    _ = args.next();
    const bundle_path = args.next() orelse return usage();
    const output_path = args.next() orelse return usage();
    if (args.next() != null) return usage();

    const bundle = std.Io.Dir.cwd().readFileAlloc(io, bundle_path, gpa, .limited(16 << 20)) catch |err| {
        std.debug.print("site-brand-mark: unable to read the bundle `{s}`: {t}\n", .{ bundle_path, err });
        std.process.exit(1);
    };
    const data = try std.mem.concat(gpa, u8, &.{ header, bundle });
    std.Io.Dir.cwd().writeFile(io, .{ .sub_path = output_path, .data = data }) catch |err| {
        std.debug.print("site-brand-mark: unable to write `{s}`: {t}\n", .{ output_path, err });
        std.process.exit(1);
    };
}

fn usage() noreturn {
    std.debug.print("usage: site-brand-mark <bundle> <output>\n", .{});
    std.process.exit(2);
}
