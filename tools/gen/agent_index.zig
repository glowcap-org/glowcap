//! Write the index tables in `.agents/README.md` from the files they list.
//!
//! Each rule, skill and persona says what it is for in its own frontmatter
//! `description`, the field its harness routes on and the OKF index field. A
//! hook says it in its first comment line. The index shows the first sentence
//! of each, so a file's purpose has one home and the index cannot drift from
//! the directories. `check` fails when the index is stale or a file has no
//! description.
//!
//! Usage: gen-agent-index write|check

const std = @import("std");

const readme_path = ".agents/README.md";
const begin_marker = "<!-- agent-index GENERATED by `zig build gen-agent-index` from each file's description; edits are overwritten -->\n";
const end_marker = "<!-- /agent-index -->\n";

const Row = struct { name: []const u8, link: []const u8, purpose: []const u8 };

fn lessThan(_: void, a: Row, b: Row) bool {
    return std.mem.lessThan(u8, a.name, b.name);
}

pub fn main(init: std.process.Init) !void {
    const gpa = init.arena.allocator();
    var threaded = std.Io.Threaded.init(gpa, .{});
    defer threaded.deinit();
    const io = threaded.io();

    var args = std.process.Args.Iterator.init(init.minimal.args);
    _ = args.next();
    const mode = args.next() orelse return usage();
    const check = if (std.mem.eql(u8, mode, "check")) true else if (std.mem.eql(u8, mode, "write")) false else return usage();

    const cwd = std.Io.Dir.cwd();
    var failed = false;
    var out: std.ArrayList(u8) = .empty;
    try out.appendSlice(gpa, begin_marker);
    const sections = [_]struct { title: []const u8, column: []const u8, dir: []const u8, kind: Kind }{
        .{ .title = "Rules", .column = "Rule", .dir = ".agents/rules", .kind = .rule },
        .{ .title = "Skills", .column = "Skill", .dir = ".agents/skills", .kind = .skill },
        .{ .title = "Personas", .column = "Persona", .dir = ".agents/personas", .kind = .persona },
        .{ .title = "Hooks", .column = "Hook", .dir = ".agents/hooks", .kind = .hook },
    };
    for (sections, 0..) |section, i| {
        const rows = try collect(io, gpa, cwd, section.dir, section.kind, &failed);
        std.mem.sort(Row, rows, {}, lessThan);
        if (i > 0) try out.append(gpa, '\n');
        try out.print(gpa, "## {s}\n\n| {s} | Purpose |\n| --- | --- |\n", .{ section.title, section.column });
        for (rows) |row| {
            try out.print(gpa, "| [{s}]({s}) | ", .{ row.name, row.link });
            for (row.purpose) |c| {
                if (c == '|') try out.append(gpa, '\\');
                try out.append(gpa, c);
            }
            try out.appendSlice(gpa, " |\n");
        }
    }
    try out.appendSlice(gpa, end_marker);
    if (failed) std.process.exit(1);

    const readme = try cwd.readFileAlloc(io, readme_path, gpa, .limited(1 << 20));
    const begin = std.mem.indexOf(u8, readme, begin_marker) orelse return missingMarkers();
    const end = std.mem.indexOfPos(u8, readme, begin, end_marker) orelse return missingMarkers();
    const rendered = try std.mem.concat(gpa, u8, &.{ readme[0..begin], out.items, readme[end + end_marker.len ..] });
    if (std.mem.eql(u8, rendered, readme)) return;
    if (check) {
        std.debug.print("gen-agent-index: {s} is stale. Run `zig build gen-agent-index` and commit it.\n", .{readme_path});
        std.process.exit(1);
    }
    try cwd.writeFile(io, .{ .sub_path = readme_path, .data = rendered });
}

fn usage() void {
    std.debug.print("usage: gen-agent-index write|check\n", .{});
    std.process.exit(2);
}

fn missingMarkers() void {
    std.debug.print("gen-agent-index: {s} has no agent-index markers to write between\n", .{readme_path});
    std.process.exit(1);
}

const Kind = enum { rule, skill, persona, hook };

/// One row per rule file, skill directory, persona file or hook script.
fn collect(io: std.Io, gpa: std.mem.Allocator, cwd: std.Io.Dir, path: []const u8, kind: Kind, failed: *bool) ![]Row {
    var dir = try cwd.openDir(io, path, .{ .iterate = true });
    defer dir.close(io);
    var rows: std.ArrayList(Row) = .empty;
    var walker = try dir.walk(gpa);
    defer walker.deinit();
    while (try walker.next(io)) |entry| {
        if (std.mem.indexOfScalar(u8, entry.path, '/') != null) continue;
        const name, const file = switch (kind) {
            .skill => if (entry.kind == .directory) .{ entry.path, try std.fmt.allocPrint(gpa, "{s}/SKILL.md", .{entry.path}) } else continue,
            .rule, .persona => if (entry.kind == .file and std.mem.endsWith(u8, entry.path, ".md") and !std.mem.eql(u8, entry.path, "README.md"))
                .{ entry.path[0 .. entry.path.len - ".md".len], entry.path }
            else
                continue,
            .hook => if (entry.kind == .file and std.mem.endsWith(u8, entry.path, ".sh")) .{ entry.path[0 .. entry.path.len - ".sh".len], entry.path } else continue,
        };
        const full = try std.fs.path.join(gpa, &.{ path, file });
        const text = try cwd.readFileAlloc(io, full, gpa, .limited(1 << 20));
        const purpose = (if (kind == .hook) hookPurpose(text) else description(gpa, text)) orelse {
            std.debug.print("gen-agent-index: {s} says nothing about its purpose; give it a {s}\n", .{ full, if (kind == .hook) "first comment line" else "frontmatter `description`" });
            failed.* = true;
            continue;
        };
        try rows.append(gpa, .{
            .name = try gpa.dupe(u8, name),
            .link = try std.fmt.allocPrint(gpa, "{s}/{s}", .{ path[".agents/".len..], file }),
            .purpose = firstSentence(purpose),
        });
    }
    return rows.items;
}

/// The frontmatter `description`: a plain or double-quoted scalar, or a
/// folded block (`>-`) joined into one line.
fn description(gpa: std.mem.Allocator, text: []const u8) ?[]const u8 {
    if (!std.mem.startsWith(u8, text, "---\n")) return null;
    const end = std.mem.indexOf(u8, text[3..], "\n---\n") orelse return null;
    var lines = std.mem.splitScalar(u8, text[4 .. 3 + end + 1], '\n');
    while (lines.next()) |line| {
        if (!std.mem.startsWith(u8, line, "description:")) continue;
        const value = std.mem.trim(u8, line["description:".len..], " ");
        if (value.len >= 2 and value[0] == '"' and value[value.len - 1] == '"') return value[1 .. value.len - 1];
        if (!std.mem.eql(u8, value, ">-") and !std.mem.eql(u8, value, ">")) return if (value.len > 0) value else null;
        var folded: std.ArrayList(u8) = .empty;
        while (lines.next()) |more| {
            if (!std.mem.startsWith(u8, more, "  ")) break;
            if (folded.items.len > 0) folded.append(gpa, ' ') catch return null;
            folded.appendSlice(gpa, std.mem.trim(u8, more, " ")) catch return null;
        }
        return if (folded.items.len > 0) folded.items else null;
    }
    return null;
}

/// The first comment line after the shebang, without a `glowcap: ` lead.
fn hookPurpose(text: []const u8) ?[]const u8 {
    var lines = std.mem.splitScalar(u8, text, '\n');
    while (lines.next()) |line| {
        if (std.mem.startsWith(u8, line, "#!")) continue;
        if (!std.mem.startsWith(u8, line, "# ")) return null;
        const body = line[2..];
        return if (std.mem.startsWith(u8, body, "glowcap: ")) body["glowcap: ".len..] else body;
    }
    return null;
}

fn firstSentence(text: []const u8) []const u8 {
    const end = std.mem.indexOf(u8, text, ". ") orelse return text;
    return text[0 .. end + 1];
}

test "descriptions read plain, quoted and folded" {
    const gpa = std.testing.allocator;
    var arena = std.heap.ArenaAllocator.init(gpa);
    defer arena.deinit();
    const a = arena.allocator();
    try std.testing.expectEqualStrings("Tests.", description(a, "---\ndescription: Tests.\n---\n").?);
    try std.testing.expectEqualStrings("Quoted: yes.", description(a, "---\ndescription: \"Quoted: yes.\"\n---\n").?);
    try std.testing.expectEqualStrings("Use when a. Then b.", description(a, "---\nname: x\ndescription: >-\n  Use when a.\n  Then b.\nother: y\n---\n").?);
    try std.testing.expect(description(a, "# No frontmatter\n") == null);
    try std.testing.expectEqualStrings("Use when a.", firstSentence("Use when a. Then b."));
    try std.testing.expectEqualStrings("format a file.", hookPurpose("#!/bin/sh\n# glowcap: format a file.\n").?);
}
