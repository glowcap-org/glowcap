fn areaFor(path: []const u8, name: []const u8) ?Area {
    if (std.mem.eql(u8, path, "build.zig.zon")) return if (std.mem.eql(u8, name, "vaxis")) .cli else .library;
    if (std.mem.startsWith(u8, path, "transports/") or std.mem.startsWith(u8, path, "tools/deps/")) return .transports;
    if (std.mem.startsWith(u8, path, "bindings/proofs/") or std.mem.indexOf(u8, path, "/relay/Cargo.toml") != null or
        std.mem.eql(u8, path, "bindings/ts/deno.json")) return .validation;
    if (std.mem.startsWith(u8, path, "bindings/")) return .bindings;
    if (std.mem.startsWith(u8, path, "apps/rooms/")) return .rooms;
    if (std.mem.startsWith(u8, path, "apps/")) return .apps;
    if (std.mem.startsWith(u8, path, "site/") or std.mem.startsWith(u8, path, "ui/")) return .presentation;
    if (std.mem.startsWith(u8, path, "conformance/") or std.mem.eql(u8, path, ".gitmodules")) return .references;
    if (std.mem.startsWith(u8, path, ".devcontainer/")) return .environment;
    for ([_][]const u8{ "tools/", "ci/", "bench/", "test/" }) |prefix| {
        if (std.mem.startsWith(u8, path, prefix)) return .validation;
    }
    if (std.mem.eql(u8, path, "deno.json")) return .validation;
    return null;
}

/// Directories that hold no first-party manifest.
const skipped_dirs = [_][]const u8{ ".git", ".local", ".zig-cache", "zig-out", "zig-pkg", "node_modules", "target", ".venv", "upstream", "third_party" };

const Decl = struct { name: []const u8, line: usize };
const Entry = struct { name: []const u8, purpose: []const u8, line: usize };

pub fn main(init: std.process.Init) !void {
    const gpa = init.arena.allocator();
    var threaded = std.Io.Threaded.init(gpa, .{});
    defer threaded.deinit();
    const io = threaded.io();

    var args = std.process.Args.Iterator.init(init.minimal.args);
    _ = args.next();
    const mode = args.next() orelse return usage();
    const check = if (std.mem.eql(u8, mode, "check")) true else if (std.mem.eql(u8, mode, "write")) false else return usage();

    const cwd = std.Io.Dir.cwd();
    const manifests = try findManifests(io, gpa, cwd);

    var out: std.ArrayList(u8) = .empty;
    try out.appendSlice(gpa, header);
    try out.append(gpa, '\n');
    var failed = false;
    const Manifest = struct { path: []const u8, entries: []const Entry };
    var inventory: std.ArrayList(Manifest) = .empty;
    for (manifests) |path| {
        for (kinds) |kind| if (matches(kind, path)) {
            const entries = try readManifest(io, gpa, cwd, kind, path, &failed);
            for (entries) |entry| if (areaFor(path, entry.name) == null) {
                try report(&failed, path, entry.line, "dependency has no project owner in areaFor", .{});
            };
            try inventory.append(gpa, .{ .path = path, .entries = entries });
            break;
        };
    }
    for (areas) |area| {
        try out.print(gpa, "## {s}\n\n{s}\n\n", .{ area.title, area.intro });
        for (inventory.items) |manifest| {
            var named = false;
            for (manifest.entries) |entry| {
                if (areaFor(manifest.path, entry.name) != area.area) continue;
                if (!named) try out.print(gpa, "Declared in [`{s}`](../{s}):\n\n", .{ manifest.path, manifest.path });
                named = true;
                try out.print(gpa, "- **{s}**: {s}\n", .{ entry.name, entry.purpose });
            }
            if (named) try out.append(gpa, '\n');
        }
    }
    try out.appendSlice(gpa, footer);
    if (failed) std.process.exit(1);

    if (check) {
        const committed = cwd.readFileAlloc(io, output_path, gpa, .limited(1 << 20)) catch "";
        if (!std.mem.eql(u8, committed, out.items)) {
            std.debug.print("gen-dependencies: {s} is stale. Run `zig build gen-dependencies` and commit it.\n", .{output_path});
            std.process.exit(1);
        }
        return;
    }
    try cwd.writeFile(io, .{ .sub_path = output_path, .data = out.items });
}

fn usage() noreturn {
    std.debug.print("usage: gen-dependencies write|check\n", .{});
    std.process.exit(2);
}

fn matches(kind: Kind, path: []const u8) bool {
    if (std.mem.endsWith(u8, kind.file, "/")) return std.mem.startsWith(u8, path, kind.file);
    if (std.mem.indexOfScalar(u8, kind.file, '/') != null) return std.mem.eql(u8, path, kind.file);
    return std.mem.eql(u8, std.fs.path.basename(path), kind.file);
}

/// Every manifest path in the tree, sorted so the page is stable.
fn findManifests(io: std.Io, gpa: std.mem.Allocator, cwd: std.Io.Dir) ![]const []const u8 {
    var dir = try cwd.openDir(io, ".", .{ .iterate = true });
    defer dir.close(io);
    var walker = try dir.walkSelectively(gpa);
    defer walker.deinit();
    var found: std.ArrayList([]const u8) = .empty;
    while (try walker.next(io)) |entry| {
        if (entry.kind == .directory) {
            for (skipped_dirs) |skip| {
                if (std.mem.eql(u8, entry.basename, skip)) break;
            } else try walker.enter(io, entry);
            continue;
        }
        if (entry.kind != .file) continue;
        for (kinds) |kind| if (matches(kind, entry.path)) {
            try found.append(gpa, try gpa.dupe(u8, entry.path));
            break;
        };
    }
    std.mem.sort([]const u8, found.items, {}, lessThan);
    return found.items;
}

fn lessThan(_: void, a: []const u8, b: []const u8) bool {
    return std.mem.lessThan(u8, a, b);
}

/// The entries of one manifest in file order. Sets `failed` and reports a
/// dependency with no comment, or a comment that names nothing declared.
fn readManifest(
    io: std.Io,
    gpa: std.mem.Allocator,
    cwd: std.Io.Dir,
    kind: Kind,
    path: []const u8,
    failed: *bool,
) ![]const Entry {
    const text = try cwd.readFileAlloc(io, path, gpa, .limited(1 << 20));
    var lines: std.ArrayList([]const u8) = .empty;
    var it = std.mem.splitScalar(u8, text, '\n');
    while (it.next()) |line| try lines.append(gpa, line);

    var entries: std.ArrayList(Entry) = .empty;
    for (lines.items, 0..) |line, i| {
        const body = commentText(line, kind.leader) orelse continue;
        if (!std.mem.startsWith(u8, body, "dep ")) continue;
        const sep = std.mem.indexOf(u8, body, ": ") orelse {
            try report(failed, path, i, "a `dep` comment needs `dep <name>: <purpose>`", .{});
            continue;
        };
        var purpose: std.ArrayList(u8) = .empty;
        try purpose.appendSlice(gpa, std.mem.trim(u8, body[sep + 2 ..], " "));
        var j = i + 1;
        while (j < lines.items.len) : (j += 1) {
            const more = commentText(lines.items[j], kind.leader) orelse break;
            if (!std.mem.startsWith(u8, more, "  ")) break;
            try purpose.append(gpa, ' ');
            try purpose.appendSlice(gpa, std.mem.trim(u8, more, " "));
        }
        if (!std.mem.endsWith(u8, purpose.items, ".")) try report(failed, path, i, "a `dep` purpose ends with a period", .{});
        try entries.append(gpa, .{ .name = std.mem.trim(u8, body[4..sep], " "), .purpose = purpose.items, .line = i });
    }

    // Every file under a directory kind fetches something, so one with no
    // `dep` comment would drop off the page unseen.
    if (std.mem.endsWith(u8, kind.file, "/") and entries.items.len == 0) {
        try report(failed, path, 0, "a file under `{s}` needs a `dep <name>: <purpose>` comment", .{kind.file});
    }
    const read = kind.declarations orelse return entries.items;
    var decls: std.ArrayList(Decl) = .empty;
    try read(gpa, lines.items, &decls);
    var seen = std.StringHashMap(void).init(gpa);
    for (decls.items) |decl| {
        if (kind.named and seen.contains(decl.name)) continue;
        try seen.put(decl.name, {});
        if (!commentedAbove(lines.items, kind, decl, entries.items)) {
            try report(failed, path, decl.line, "`{s}` needs a `dep {s}: <purpose>` comment directly above it", .{ decl.name, if (kind.named) decl.name else "<name>" });
        }
    }
    if (kind.named) for (entries.items) |entry| {
        if (!seen.contains(entry.name)) try report(failed, path, entry.line, "the `dep` comment names `{s}`, which this manifest does not declare", .{entry.name});
    };
    return entries.items;
}

fn report(failed: *bool, path: []const u8, line: usize, comptime fmt: []const u8, args: anytype) !void {
    failed.* = true;
    std.debug.print("gen-dependencies: {s}:{d}: " ++ fmt ++ "\n", .{ path, line + 1 } ++ args);
}

/// Whether the comment block directly above a declaration holds its entry.
fn commentedAbove(lines: []const []const u8, kind: Kind, decl: Decl, entries: []const Entry) bool {
    var top = decl.line;
    while (top > 0 and commentText(lines[top - 1], kind.leader) != null) top -= 1;
    for (entries) |entry| {
        if (entry.line < top or entry.line >= decl.line) continue;
        if (!kind.named or std.mem.eql(u8, entry.name, decl.name)) return true;
    }
    return false;
}

/// The text of a comment line after its leader and one space, or null.
fn commentText(line: []const u8, leader: []const u8) ?[]const u8 {
    const trimmed = std.mem.trimStart(u8, line, " \t");
    if (!std.mem.startsWith(u8, trimmed, leader)) return null;
    const rest = trimmed[leader.len..];
    return if (std.mem.startsWith(u8, rest, " ")) rest[1..] else rest;
}

fn cargoDeclarations(gpa: std.mem.Allocator, lines: []const []const u8, out: *std.ArrayList(Decl)) !void {
    var in_deps = false;
    for (lines, 0..) |line, i| {
        const trimmed = std.mem.trim(u8, line, " \t\r");
        if (std.mem.startsWith(u8, trimmed, "[")) {
            in_deps = std.mem.endsWith(u8, trimmed, "dependencies]");
            continue;
        }
        if (!in_deps or trimmed.len == 0 or trimmed[0] == '#') continue;
        const eq = std.mem.indexOfScalar(u8, trimmed, '=') orelse continue;
        var name = std.mem.trim(u8, trimmed[0..eq], " \"");
        if (std.mem.endsWith(u8, name, ".workspace")) continue;
        if (std.mem.indexOf(u8, trimmed, "path =") != null or std.mem.indexOf(u8, trimmed, "workspace = true") != null) continue;
        if (std.mem.indexOfScalar(u8, name, '.')) |dot| name = name[0..dot];
        try out.append(gpa, .{ .name = name, .line = i });
    }
}

fn denoDeclarations(gpa: std.mem.Allocator, lines: []const []const u8, out: *std.ArrayList(Decl)) !void {
    var in_imports = false;
    for (lines, 0..) |line, i| {
        const trimmed = std.mem.trim(u8, line, " \t\r");
        if (std.mem.startsWith(u8, trimmed, "\"imports\"")) {
            in_imports = true;
            continue;
        }
        if (!in_imports) continue;
        if (std.mem.startsWith(u8, trimmed, "}")) {
            in_imports = false;
            continue;
        }
        const colon = std.mem.indexOf(u8, trimmed, "\": \"") orelse continue;
        const value = trimmed[colon + 4 ..];
        const spec = if (std.mem.startsWith(u8, value, "npm:") or std.mem.startsWith(u8, value, "jsr:")) value[4..] else continue;
        const from: usize = if (std.mem.startsWith(u8, spec, "@")) 1 else 0;
        const end = std.mem.indexOfAnyPos(u8, spec, from, "@\"") orelse spec.len;
        try out.append(gpa, .{ .name = spec[0..end], .line = i });
    }
}

fn zonDeclarations(gpa: std.mem.Allocator, lines: []const []const u8, out: *std.ArrayList(Decl)) !void {
    var in_deps = false;
    for (lines, 0..) |line, i| {
        const trimmed = std.mem.trim(u8, line, " \t\r");
        if (std.mem.startsWith(u8, trimmed, ".dependencies")) {
            in_deps = true;
            continue;
        }
        if (!in_deps) continue;
        if (!std.mem.startsWith(u8, trimmed, ".") or !std.mem.endsWith(u8, trimmed, "= .{")) continue;
        const name = std.mem.trim(u8, trimmed[1 .. std.mem.indexOfScalar(u8, trimmed, '=') orelse continue], " ");
        var j = i + 1;
        while (j < lines.len) : (j += 1) {
            const inner = std.mem.trim(u8, lines[j], " \t\r");
            if (std.mem.startsWith(u8, inner, "}")) break;
            if (std.mem.startsWith(u8, inner, ".url")) {
                try out.append(gpa, .{ .name = name, .line = i });
                break;
            }
        }
    }
}

fn pythonDeclarations(gpa: std.mem.Allocator, lines: []const []const u8, out: *std.ArrayList(Decl)) !void {
    var section: []const u8 = "";
    var in_array = false;
    for (lines, 0..) |line, i| {
        const trimmed = std.mem.trim(u8, line, " \t\r");
        if (std.mem.startsWith(u8, trimmed, "[") and !in_array) {
            section = trimmed;
            continue;
        }
        if (trimmed.len == 0 or trimmed[0] == '#') continue;
        var rest = trimmed;
        if (!in_array) {
            const eq = std.mem.indexOfScalar(u8, trimmed, '=') orelse continue;
            const key = std.mem.trim(u8, trimmed[0..eq], " ");
            const grouped = std.mem.eql(u8, section, "[project.optional-dependencies]") or std.mem.eql(u8, section, "[dependency-groups]");
            if (!grouped and !std.mem.eql(u8, key, "dependencies")) continue;
            rest = std.mem.trim(u8, trimmed[eq + 1 ..], " ");
            if (!std.mem.startsWith(u8, rest, "[")) continue;
            in_array = true;
        }
        var at: usize = 0;
        while (std.mem.indexOfScalarPos(u8, rest, at, '"')) |open| {
            const close = std.mem.indexOfScalarPos(u8, rest, open + 1, '"') orelse break;
            const requirement = rest[open + 1 .. close];
            const end = std.mem.indexOfAny(u8, requirement, "<>=!~[; ") orelse requirement.len;
            try out.append(gpa, .{ .name = requirement[0..end], .line = i });
            at = close + 1;
        }
        if (std.mem.indexOfScalar(u8, rest, ']') != null) in_array = false;
    }
}

fn submoduleDeclarations(gpa: std.mem.Allocator, lines: []const []const u8, out: *std.ArrayList(Decl)) !void {
    for (lines, 0..) |line, i| {
        const trimmed = std.mem.trim(u8, line, " \t\r");
        if (!std.mem.startsWith(u8, trimmed, "[submodule \"")) continue;
        const name = trimmed["[submodule \"".len .. std.mem.lastIndexOfScalar(u8, trimmed, '"') orelse continue];
        try out.append(gpa, .{ .name = name, .line = i });
    }
}

test "deno specifiers name their package" {
    const gpa = std.testing.allocator;
    var decls: std.ArrayList(Decl) = .empty;
    defer decls.deinit(gpa);
    try denoDeclarations(gpa, &.{
        "  \"imports\": {",
        "    \"react/jsx-runtime\": \"npm:react@19.3.0/jsx-runtime\",",
        "    \"@types/react\": \"npm:@types/react@19.3.0\",",
        "    \"@glowcap/web\": \"../web/mod.ts\",",
