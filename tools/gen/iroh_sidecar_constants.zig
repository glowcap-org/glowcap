//! Generates Rust constants consumed by the native iroh sidecar.

const std = @import("std");

const iroh_policy = @import("iroh_policy");
const frame_stream = @import("frame_stream");
const Output = @import("output").Output;

pub const step_name = "gen-iroh-sidecar-constants";

pub const outputs = [_]Output{
    .{ .path = "transports/iroh/src/constants_gen.rs", .generate = generate },
};

fn generate(gpa: std.mem.Allocator) ![]u8 {
    const accept_queue_bound = comptime iroh_policy.accept_queue_bound;
    const read_chunk_bytes = comptime iroh_policy.read_chunk_bytes;
    const steady_outbound_bytes = comptime frame_stream.steady_outbound_bytes;
    if (accept_queue_bound == 0) @compileError("iroh sidecar accept queue cannot be empty");
    if (read_chunk_bytes == 0) @compileError("iroh sidecar read chunk cannot be empty");
    if (steady_outbound_bytes == 0) @compileError("iroh sidecar steady buffer cannot be empty");

    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    try out.print(gpa,
        \\//! GENERATED by `zig build gen-iroh-sidecar-constants` from
        \\//! src/net/transport/iroh/policy.zig and src/net/frame_stream.zig.
        \\//! Do not edit.
        \\//! `zig build gen-iroh-sidecar-constants-check` keeps this fresh.
        \\
        \\#![allow(dead_code)]
        \\
        \\pub(crate) const ACCEPT_QUEUE_BOUND: usize = {d};
        \\pub(crate) const READ_CHUNK_BYTES: usize = {d};
        \\pub(crate) const NB_STEADY_BYTES: usize = {d};
        \\
    , .{ accept_queue_bound, read_chunk_bytes, steady_outbound_bytes });
    return out.toOwnedSlice(gpa);
}
