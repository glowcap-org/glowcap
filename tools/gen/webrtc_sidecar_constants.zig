//! Generates Rust constants consumed by the native WebRTC sidecar.

const std = @import("std");

const webrtc = @import("webrtc");
const Output = @import("output").Output;

pub const step_name = "gen-webrtc-sidecar-constants";

pub const outputs = [_]Output{
    .{ .path = "transports/webrtc/src/constants_gen.rs", .generate = generate },
};

fn generate(gpa: std.mem.Allocator) ![]u8 {
    const packet_cap = comptime webrtc.max_packet_bytes;
    const signal_cap = comptime webrtc.max_signal_bytes;
    const ice_candidate_bytes = comptime webrtc.max_ice_candidate_bytes;
    const ice_servers = comptime webrtc.max_ice_servers;
    const ice_urls_per_server = comptime webrtc.max_ice_urls_per_server;
    const ice_url_bytes = comptime webrtc.max_ice_url_bytes;
    const ice_credential_bytes = comptime webrtc.max_ice_credential_bytes;
    const max_pending_ice_candidates = comptime webrtc.max_pending_ice_candidates;
    const pending_ice_candidate_queue_bytes = comptime webrtc.pending_ice_candidate_queue_bytes;
    const data_channel_queue_bytes = comptime webrtc.data_channel_queue_bytes;
    const sctp_receive_buffer_bytes = comptime webrtc.sctp_receive_buffer_bytes;
    if (packet_cap == 0) @compileError("webrtc sidecar requires a transport packet cap");
    if (signal_cap == 0) @compileError("webrtc sidecar requires a signaling cap");
    if (ice_candidate_bytes == 0) @compileError("webrtc sidecar requires an ICE candidate byte cap");
    if (ice_servers == 0) @compileError("webrtc sidecar requires at least one ICE server slot");
    if (ice_urls_per_server == 0) @compileError("webrtc sidecar requires at least one ICE URL slot");
    if (ice_url_bytes == 0) @compileError("webrtc sidecar requires an ICE URL byte cap");
    if (ice_credential_bytes == 0) @compileError("webrtc sidecar requires an ICE credential byte cap");
    if (max_pending_ice_candidates == 0) @compileError("webrtc sidecar requires an ICE candidate queue count");
    if (pending_ice_candidate_queue_bytes == 0) @compileError("webrtc sidecar requires an ICE candidate queue byte cap");
    if (data_channel_queue_bytes == 0) @compileError("webrtc sidecar requires a data-channel queue byte cap");
    if (sctp_receive_buffer_bytes == 0) @compileError("webrtc sidecar requires an SCTP receive buffer byte cap");

    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    try out.print(gpa,
        \\//! GENERATED by `zig build gen-webrtc-sidecar-constants` from
        \\//! src/net/transport/webrtc.zig. Do not edit.
        \\//! `zig build gen-webrtc-sidecar-constants-check` keeps this fresh.
        \\
        \\#![allow(dead_code)]
        \\
        \\pub(crate) const TRANSPORT_WEBRTC_MAX_PACKET_BYTES: usize = {d};
        \\pub(crate) const MAX_SIGNAL_BYTES: usize = {d};
        \\pub(crate) const MAX_ICE_CANDIDATE_BYTES: usize = {d};
        \\pub(crate) const MAX_ICE_SERVERS: usize = {d};
        \\pub(crate) const MAX_ICE_URLS_PER_SERVER: usize = {d};
        \\pub(crate) const MAX_ICE_URL_BYTES: usize = {d};
        \\pub(crate) const MAX_ICE_CREDENTIAL_BYTES: usize = {d};
        \\pub(crate) const MAX_PENDING_ICE_CANDIDATES: usize = {d};
        \\pub(crate) const PENDING_ICE_CANDIDATE_QUEUE_BYTES: usize = {d};
        \\pub(crate) const DATA_CHANNEL_QUEUE_BYTES: usize = {d};
        \\pub(crate) const SCTP_RECEIVE_BUFFER_BYTES: usize = {d};
        \\
    , .{
        packet_cap,
        signal_cap,
        ice_candidate_bytes,
        ice_servers,
        ice_urls_per_server,
        ice_url_bytes,
        ice_credential_bytes,
        max_pending_ice_candidates,
        pending_ice_candidate_queue_bytes,
        data_channel_queue_bytes,
        sctp_receive_buffer_bytes,
    });
    return out.toOwnedSlice(gpa);
}
