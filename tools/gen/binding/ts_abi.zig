//! Generates the two-file TypeScript mirror of the `libpancake_ocapn` and
//! `libpancake_driver` ABIs from the Zig source of truth.
//!
//! JavaScript FFI has no struct types, so the TypeScript binding reads C structs
//! through byte offsets. Every other binding declares fields symbolically
//! (ctypes, `define-cstruct`, `#[repr(C)]`); TypeScript alone would have to keep
//! hand-derived numbers, the one mirror a reviewer could not trust. This tool
//! removes that class: constant values come from the `c_abi` declarations and
//! layout numbers from `@sizeOf`/`@offsetOf`, so a struct or constant change in
//! Zig regenerates the mirror instead of silently invalidating it.
//!
//! The mirror splits by target dependence. The constant values are the same on
//! every target, so they own one home in the `@pancake/abi` package
//! (`bindings/ts/abi/constants.ts`), which both the native stack binding and the
//! wasm32 browser surface import. The struct sizes and field offsets are
//! target-specific, so they stay with the 64-bit consumer that reads them
//! (`bindings/ts/stack/internal/abi.ts`); the wasm32 surface reports its own
//! offsets instead (`pancake_wasm_abi_layout`). `zig build gen-ts-abi-check`
//! (part of `check`) holds both committed files against a fresh generation, the
//! same discipline as the C headers.

const std = @import("std");
const c = @import("c_abi");
const cd = @import("c_abi_driver");

pub const step_name = "gen-ts-abi";

/// One generated file: its path and the emitter that produces its full bytes.
/// The shared `tools/gen` emit/verify harness writes and staleness-checks each.
pub const Output = struct {
    path: []const u8,
    generate: *const fn (std.mem.Allocator) anyerror![]u8,
};

pub const outputs = [_]Output{
    .{ .path = "bindings/ts/abi/constants.ts", .generate = generateConstants },
    .{ .path = "bindings/ts/stack/internal/abi.ts", .generate = generateLayouts },
};

