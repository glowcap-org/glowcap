const constants_preamble =
    \\// GENERATED by `zig build gen-ts-abi` from src/c_abi and binding policy
    \\// Do not edit. `zig build gen-ts-abi-check` keeps this fresh.
    \\//
    \\// Target-independent constants for the FFI runtime and wasm32 browser
    \\// surface.
    \\
    \\
;

const layouts_preamble =
    \\// GENERATED by `zig build gen-ts-abi` from src/c_abi (the ocapn and
    \\// driver archives). Do not edit. `zig build gen-ts-abi-check` keeps this fresh.
    \\//
    \\// 64-bit struct sizes and field offsets for JavaScript FFI.
    \\
    \\
;

fn writeTsTransportConstName(
    out: *std.ArrayList(u8),
    gpa: std.mem.Allocator,
    known: model.transport.Known,
    suffix: []const u8,
) !void {
    try out.appendSlice(gpa, "TRANSPORT_");
    for (@tagName(known)) |ch| {
        try out.append(gpa, if (ch == '_') '_' else std.ascii.toUpper(ch));
    }
    try out.appendSlice(gpa, suffix);
}

/// One generated struct layout: the TS constant prefix and the extern struct.
/// Every field is emitted as `<PREFIX>_<FIELD>_OFF` plus a `<PREFIX>_SIZE`,
/// each with a doc naming the struct and field it pins.
fn emitLayout(
    out: *std.ArrayList(u8),
    gpa: std.mem.Allocator,
    comptime prefix: []const u8,
    comptime T: type,
    comptime note: []const u8,
) !void {
    comptime {
        var owners: usize = 0;
        for (wasm_manifest) |row| {
            if (row.ffi_mirror and std.mem.eql(u8, row.prefix, prefix)) owners += 1;
        }
        for (ffi_only_layouts) |native| {
            if (std.mem.eql(u8, native, prefix)) owners += 1;
        }
        if (owners != 1) @compileError(prefix ++ " must belong to exactly one Wasm or FFI-only layout manifest");
    }
    try out.print(gpa, "/** Byte size of {s} in the 64-bit FFI layout. */\nexport const {s}_SIZE = {d};\n", .{ note, prefix, @sizeOf(T) });
    inline for (@typeInfo(T).@"struct".field_names) |field_name| {
        // C snake_case field names become the same name upper-cased, so the
        // TypeScript reader names the field it is reading.
        comptime var upper: [field_name.len]u8 = undefined;
        comptime for (field_name, 0..) |ch, i| {
            upper[i] = std.ascii.toUpper(ch);
        };
        try out.print(gpa, "/** Byte offset of `{s}` in {s}. */\nexport const {s}_{s}_OFF = {d};\n", .{ field_name, note, prefix, upper, @offsetOf(T, field_name) });
    }
    try out.appendSlice(gpa, "\n");
}

/// The wasm layout manifest is the shared table in `c_abi_host`
/// (`wasm_layout_manifest`), the same authority the wasm module's
/// descriptor exporter walks, so the two mirrors cannot drift.
const wasm_manifest = cd.wasm_layout_manifest;

/// 64-bit mirror prefixes with no wasm manifest row, because the struct's
/// archive is never linked into the wasm32 module. Declared here, at the one
/// source both mirrors generate from, so the layout check can hold the
/// exemption instead of a hardcoded skip drifting in the checker.
const ffi_only_layouts = [_][]const u8{
    "DRIVER_OPTIONS",
    "DRIVER_FAILURE",
    "DRIVER_EVENT",
    "TRANSPORT_OPERATION_OPTIONS",
    "TRANSPORT_PROVIDER",
    "TCP_STREAM_OPTIONS",
    "TCP_CONFIG",
    "RELAY_CONFIG",
    "IROH_READY_EVENT",
    "WEBRTC_READY_EVENT",
    "IROH_CONFIG",
    "WEBRTC_CONFIG",
    "WEBRTC_STRING_VIEW",
    "WEBRTC_ICE_SERVER",
    "WEBRTC_SIGNALING",
};

/// The target-independent constants, emitted into the `@glowcap/abi` package.
fn generateConstants(gpa: std.mem.Allocator) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);

    try out.appendSlice(gpa, constants_preamble);
    try out.appendSlice(gpa, "// ── Constants (values mirror src/c_abi declarations) ─────────────────────\n\n");
    inline for (table.groups) |group| {
        inline for (group.entries) |entry| {
            try out.print(gpa, "/** {s} {s} */\nexport const {s} = {d};\n", .{ group.doc, entry.tail, entry.ts, entry.value });
        }
    }
    inline for (table.archive_fingerprints) |entry| {
        try out.print(
            gpa,
            "/** The C contract fingerprint of `{s}`. The loader compares it with the library's own before the first call and refuses a stale companion. */\nexport const {s} = {d}n;\n",
            .{ entry.archive, entry.ts, entry.value },
        );
    }
    try out.print(
        gpa,
        "/** Locator hint name carrying dial addresses for a transport whose designator is a key. */\nexport const HINT_DIRECT_ADDRESSES = \"{s}\";\n",
        .{model.transport.hint_direct_addresses},
    );
    try out.print(
        gpa,
        "/** Locator hint name carrying a pipe-separated list of complete peer URIs to try after this locator. The value is routing advice, and the exporter's locator stays the signed authority for a redeem. */\nexport const HINT_ALT_LOCATORS = \"{s}\";\n",
        .{model.transport.hint_alt_locators},
    );
    try out.print(
        gpa,
        "/** Locator hint name carrying the `id` transport's route bundle. */\nexport const HINT_VIA = \"{s}\";\n",
        .{model.transport.hint_via},
    );
    inline for (std.enums.values(model.transport.Known)) |known| {
        const designator: []const u8 = switch (known.metadata().designator_scheme) {
            .address => "a dial address",
            .key => "a peer key",
        };
        try out.print(gpa, "/** The transport symbol of `{s}` locators, whose designator is {s}. */\nexport const ", .{ known.metadata().symbol, designator });
        try writeTsTransportConstName(&out, gpa, known, "");
        try out.print(gpa, " = \"{s}\";\n", .{known.metadata().symbol});
        if (known.metadata().max_packet_bytes != 0) {
            try out.print(gpa, "/** Largest wire packet the `{s}` transport carries, in bytes. */\nexport const ", .{known.metadata().symbol});
            try writeTsTransportConstName(&out, gpa, known, "_MAX_PACKET_BYTES");
            try out.print(gpa, " = {d};\n", .{known.metadata().max_packet_bytes});
        }
    }

    try out.appendSlice(gpa,
        \\
        \\// ── Wasm layout-descriptor manifest (glowcap_wasm_abi_layout) ────────────
        \\/**
        \\ * Struct index i of the wasm32 module's layout descriptor is row i here,
        \\ * and the descriptor's offset words for that struct name its fields in
        \\ * declaration order. `ffiMirror` says whether the prefix also names
        \\ * 64-bit FFI constants. When it is false the prefix is vocabulary only the
        \\ * browser's byte-fed embedder uses. Field order is declaration order on
        \\ * every target, and only the offset numbers are target-specific.
        \\ */
        \\export const WASM_LAYOUT_STRUCTS = [
        \\
    );
    @setEvalBranchQuota(20_000);
    inline for (wasm_manifest) |row| {
        try out.print(gpa, "\t{{ prefix: \"{s}\", ffiMirror: {s}, fields: [", .{
            row.prefix,
            if (row.ffi_mirror) "true" else "false",
        });
        inline for (@typeInfo(row.T).@"struct".field_names, 0..) |field_name, i| {
            comptime var upper: [field_name.len]u8 = undefined;
            comptime for (field_name, 0..) |ch, j| {
                upper[j] = std.ascii.toUpper(ch);
            };
            if (i != 0) try out.appendSlice(gpa, ", ");
            try out.print(gpa, "\"{s}\"", .{upper});
        }
        try out.appendSlice(gpa, "] },\n");
    }
    try out.appendSlice(gpa, "] as const;\n");

    try out.appendSlice(gpa,
        \\
        \\/**
        \\ * Layout prefixes that exist only in FFI archives the wasm32 module never
        \\ * links (a browser has no iroh sidecar to link). A wasm marshaller must
        \\ * never read these. The layout check requires every other 64-bit prefix
        \\ * to have a manifest row above, and refuses a prefix listed here that
        \\ * gains one.
        \\ */
        \\export const FFI_ONLY_LAYOUT_PREFIXES = [
        \\
    );
    inline for (ffi_only_layouts) |prefix| {
        try out.print(gpa, "\t\"{s}\",\n", .{prefix});
    }
    try out.appendSlice(gpa, "] as const;\n");

    return out.toOwnedSlice(gpa);
}

/// The target-specific struct sizes and field offsets, emitted into the FFI
/// stack binding's 64-bit mirror.
fn generateLayouts(gpa: std.mem.Allocator) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);

    try out.appendSlice(gpa, layouts_preamble);
    try out.appendSlice(gpa, "// ── Struct layouts (@sizeOf/@offsetOf on the extern structs) ─────────────\n\n");

    try emitLayout(&out, gpa, "REF", c.GlowcapReference, "GlowcapReference");
    try emitLayout(&out, gpa, "ARG", c.GlowcapArgument, "GlowcapArgument");
    try emitLayout(&out, gpa, "FRAME", c.GlowcapFrame, "GlowcapFrame (borrowed)");
    try emitLayout(&out, gpa, "MANAGED_FRAME", c.GlowcapManagedFrame, "GlowcapManagedFrame (owned, self-releasing)");
    try emitLayout(&out, gpa, "LAST_ABORT", c.GlowcapLastAbort, "GlowcapLastAbort");
    try emitLayout(&out, gpa, "ALLOCATOR", c.GlowcapAllocator, "GlowcapAllocator (glowcap_context_new_with_allocator)");
    try emitLayout(&out, gpa, "FAILURE_REPORT", c.GlowcapFailureReport, "GlowcapFailureReport");
    try emitLayout(&out, gpa, "FAILURE_EVENT", c.GlowcapFailureEvent, "GlowcapFailureEvent");
    try emitLayout(&out, gpa, "HOST_ACTION", cd.GlowcapHostAction, "GlowcapHostAction (libglowcap_host, glowcap_host_next_action)");
    try emitLayout(&out, gpa, "HOST_PUMP_HOOKS", cd.GlowcapHostPumpHooks, "GlowcapHostPumpHooks (libglowcap_host, glowcap_host_pump_drain)");
    try emitLayout(&out, gpa, "PARTNER_IDENTITY", cd.GlowcapPartnerIdentity, "GlowcapPartnerIdentity (libglowcap_host, glowcap_host_session_partner_identity)");
    try emitLayout(&out, gpa, "TRACE_EVENT", cd.GlowcapTraceEvent, "GlowcapTraceEvent (libglowcap_host, glowcap_host_set_trace)");
    try emitLayout(&out, gpa, "DRIVER_OPTIONS", cdr.GlowcapDriverOptions, "GlowcapDriverOptions (libglowcap_driver, glowcap_driver_take_host)");
    try emitLayout(&out, gpa, "DRIVER_FAILURE", cdr.GlowcapDriverFailure, "GlowcapDriverFailure (libglowcap_driver deterministic barriers)");
    try emitLayout(&out, gpa, "CLOSE_OPTIONS", cd.GlowcapCloseOptions, "GlowcapCloseOptions (libglowcap_host and libglowcap_driver)");
    try emitLayout(&out, gpa, "SESSION_LIMIT_OPTIONS", cd.GlowcapSessionLimitOptions, "GlowcapSessionLimitOptions (libglowcap_host)");
    try emitLayout(&out, gpa, "DRIVER_EVENT", cdr.GlowcapDriverEvent, "GlowcapDriverEvent (libglowcap_driver, glowcap_driver_next_event)");
    try emitLayout(&out, gpa, "TRANSPORT_OPERATION_OPTIONS", cdr.GlowcapTransportOperationOptions, "GlowcapTransportOperationOptions (glowcap_driver_dial)");
    try emitLayout(&out, gpa, "LOCATOR_HINT_VIEW", cdr.GlowcapLocatorHintView, "GlowcapLocatorHintView (glowcap_transport_provider.h)");
    try emitLayout(&out, gpa, "LOCATOR_VIEW", cdr.GlowcapLocatorView, "GlowcapLocatorView (glowcap_transport_provider.h)");
    try emitLayout(&out, gpa, "TRANSPORT_PROVIDER", cdr.GlowcapTransportProvider, "GlowcapTransportProvider (glowcap_transport_provider.h, glowcap_driver_add_provider)");
    try emitLayout(&out, gpa, "TCP_STREAM_OPTIONS", ct.GlowcapTcpStreamOptions, "GlowcapTcpStreamOptions (libglowcap_net_transport_tcp)");
    try emitLayout(&out, gpa, "TCP_CONFIG", ct.GlowcapTcpConfig, "GlowcapTcpConfig (libglowcap_net_transport_tcp, glowcap_tcp_netlayer_new)");
    try emitLayout(&out, gpa, "RELAY_CONFIG", cr.GlowcapRelayConfig, "GlowcapRelayConfig (libglowcap_net_transport_relay, glowcap_relay_runtime_new)");
    try emitLayout(&out, gpa, "IROH_READY_EVENT", ci.GlowcapIrohReadyEvent, "GlowcapIrohReadyEvent (libglowcap_net_transport_iroh, glowcap_iroh_netlayer_drain_ready)");
    try emitLayout(&out, gpa, "WEBRTC_READY_EVENT", cw.GlowcapWebrtcReadyEvent, "GlowcapWebrtcReadyEvent (libglowcap_net_transport_webrtc, glowcap_webrtc_netlayer_drain_ready)");
    try emitLayout(&out, gpa, "IROH_CONFIG", ci.GlowcapIrohConfig, "GlowcapIrohConfig (libglowcap_net_transport_iroh, glowcap_iroh_netlayer_new)");
    try emitLayout(&out, gpa, "WEBRTC_CONFIG", cw.GlowcapWebrtcConfig, "GlowcapWebrtcConfig (libglowcap_net_transport_webrtc, glowcap_webrtc_netlayer_new)");
    try emitLayout(&out, gpa, "WEBRTC_STRING_VIEW", cw.GlowcapWebrtcStringView, "GlowcapWebrtcStringView (libglowcap_net_transport_webrtc, one borrowed ICE URL or credential)");
    try emitLayout(&out, gpa, "WEBRTC_ICE_SERVER", cw.GlowcapWebrtcIceServer, "GlowcapWebrtcIceServer (libglowcap_net_transport_webrtc, GlowcapWebrtcConfig.ice_servers)");
    try emitLayout(&out, gpa, "WEBRTC_SIGNALING", cw.GlowcapWebrtcSignaling, "GlowcapWebrtcSignaling (libglowcap_net_transport_webrtc, GlowcapWebrtcConfig.signaling)");

    std.debug.assert(std.mem.endsWith(u8, out.items, "\n\n"));
    out.items.len -= 1;
    return out.toOwnedSlice(gpa);
}

// ── The dlopen FFI tables (bindings/ts/runtime/internal/ffi/*.ts) ─────────────
//
// Reflected from each archive's annotated symbol inventory (`symbols.zig`
// beside the exports) plus each export's real Zig signature: the parameter
// and result classes come from the types, the out-buffer indexes and
// pointer-crossing overrides from the table. Both directions are held at
// compile time: a table row that names no export fails `@field`, and an
// export with neither a row nor an omitted-family match fails the walk.
