/// 64-bit mirror prefixes with no wasm manifest row, because the struct's
/// archive is never linked into the wasm32 module. Declared here, at the one
/// source both mirrors generate from, so the layout check can hold the
/// exemption instead of a hardcoded skip drifting in the checker.
const native_only_layouts = [_][]const u8{
    "IROH_READY_EVENT",
    "WEBRTC_READY_EVENT",
};

/// The target-independent constants, emitted into the `@pancake/abi` package.
fn generateConstants(gpa: std.mem.Allocator) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);

    try out.appendSlice(gpa, constants_preamble);
    try out.appendSlice(gpa, "// ── Constants (values mirror src/c_abi declarations) ─────────────────────\n\n");
    inline for (constants) |entry| {
        try out.print(gpa, "export const {s} = {d};\n", .{ entry.ts, entry.value });
    }
    inline for (big_constants) |entry| {
        try out.print(gpa, "export const {s} = {d}n;\n", .{ entry.ts, entry.value });
    }

    try out.appendSlice(gpa,
        \\
        \\// ── Wasm layout-descriptor manifest (pancake_wasm_abi_layout) ────────────
        \\// Struct index i of the wasm32 module's layout descriptor is row i here;
        \\// the descriptor's offset words for that struct name its fields, in
        \\// declaration order. The prefix matches the 64-bit mirror's constant
        \\// prefix, so `<prefix>_SIZE` / `<prefix>_<FIELD>_OFF` rebuild at wasm32
        \\// offsets mechanically. Field order is declaration order on every
        \\// target; only the offset numbers are target-specific.
        \\export const WASM_LAYOUT_STRUCTS = [
        \\
    );
    @setEvalBranchQuota(20_000);
    inline for (wasm_manifest) |row| {
        try out.print(gpa, "\t{{ prefix: \"{s}\", fields: [", .{row.prefix});
        inline for (@typeInfo(row.T).@"struct".fields, 0..) |field, i| {
            comptime var upper: [field.name.len]u8 = undefined;
            comptime for (field.name, 0..) |ch, j| {
                upper[j] = std.ascii.toUpper(ch);
            };
            if (i != 0) try out.appendSlice(gpa, ", ");
            try out.print(gpa, "\"{s}\"", .{upper});
        }
        try out.appendSlice(gpa, "] },\n");
    }
    try out.appendSlice(gpa, "] as const;\n");

    try out.appendSlice(gpa,
        \\
        \\// Layout prefixes that exist only in native archives the wasm32 module
        \\// never links (a browser has no iroh sidecar to link). A wasm
        \\// marshaller must never read these; the layout check requires every
        \\// other 64-bit prefix to have a manifest row above, and refuses a
        \\// prefix listed here that gains one.
        \\export const NATIVE_ONLY_LAYOUT_PREFIXES = [
        \\
    );
    inline for (native_only_layouts) |prefix| {
        try out.print(gpa, "\t\"{s}\",\n", .{prefix});
    }
    try out.appendSlice(gpa, "] as const;\n");

    return out.toOwnedSlice(gpa);
}

