/// One generated struct layout: the TS constant prefix and the extern struct.
/// Every field is emitted as `<PREFIX>_<FIELD>_OFF` plus a `<PREFIX>_SIZE`.
fn emitLayout(
    out: *std.ArrayList(u8),
    gpa: std.mem.Allocator,
    comptime prefix: []const u8,
    comptime T: type,
    comptime note: []const u8,
) !void {
    try out.print(gpa, "// {s}\n", .{note});
    try out.print(gpa, "export const {s}_SIZE = {d};\n", .{ prefix, @sizeOf(T) });
    inline for (@typeInfo(T).@"struct".fields) |field| {
        // C snake_case field names become the same name upper-cased, so the
        // TypeScript reader names the field it is reading.
        comptime var upper: [field.name.len]u8 = undefined;
        comptime for (field.name, 0..) |ch, i| {
            upper[i] = std.ascii.toUpper(ch);
        };
        try out.print(gpa, "export const {s}_{s}_OFF = {d};\n", .{ prefix, upper, @offsetOf(T, field.name) });
    }
    try out.appendSlice(gpa, "\n");
}

/// One row of the wasm layout-descriptor manifest: the struct's constant
/// prefix (matching the 64-bit mirror) and its extern type. Order here IS the
/// descriptor's canonical struct order (`layout_specs` in
/// `src/c_abi/wasm/mod.zig`); `zig build wasm-abi-layout-check` holds the two
/// in lockstep.
const ManifestRow = struct {
    prefix: []const u8,
    T: type,
};

const wasm_manifest = [_]ManifestRow{
    .{ .prefix = "MANAGED_FRAME", .T = c.PancakeManagedFrame },
    .{ .prefix = "REF", .T = c.PancakeReference },
    .{ .prefix = "ARG", .T = c.PancakeArgument },
    .{ .prefix = "FRAME", .T = c.PancakeFrame },
    .{ .prefix = "LAST_ABORT", .T = c.PancakeLastAbort },
    .{ .prefix = "ALLOCATOR", .T = c.PancakeAllocator },
    .{ .prefix = "HOST_ACTION", .T = cd.PancakeHostAction },
    .{ .prefix = "HOST_PUMP_HOOKS", .T = cd.PancakeHostPumpHooks },
    .{ .prefix = "DIAL_PLAN", .T = cd.PancakeDialPlan },
    .{ .prefix = "ACCEPT_PLAN", .T = cd.PancakeAcceptPlan },
    .{ .prefix = "PENDING_DIAL", .T = cd.PancakePendingDial },
};

/// The target-independent constants, emitted into the `@pancake/abi` package.
fn generateConstants(gpa: std.mem.Allocator) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);

    try out.appendSlice(gpa, constants_preamble);
    try out.appendSlice(gpa, "// ── Constants (values mirror src/c_abi declarations) ─────────────────────\n\n");
    inline for (constants) |entry| {
        try out.print(gpa, "export const {s} = {d};\n", .{ entry.ts, entry.value });
    }
    inline for (big_constants) |entry| {
        try out.print(gpa, "export const {s} = {d}n;\n", .{ entry.ts, entry.value });
    }

    try out.appendSlice(gpa,
        \\
        \\// ── Wasm layout-descriptor manifest (pancake_wasm_abi_layout) ────────────
        \\// Struct index i of the wasm32 module's layout descriptor is row i here;
        \\// the descriptor's offset words for that struct name its fields, in
        \\// declaration order. The prefix matches the 64-bit mirror's constant
        \\// prefix, so `<prefix>_SIZE` / `<prefix>_<FIELD>_OFF` rebuild at wasm32
        \\// offsets mechanically. Field order is declaration order on every
        \\// target; only the offset numbers are target-specific.
        \\export const WASM_LAYOUT_STRUCTS = [
        \\
    );
    @setEvalBranchQuota(20_000);
    inline for (wasm_manifest) |row| {
        try out.print(gpa, "\t{{ prefix: \"{s}\", fields: [", .{row.prefix});
        inline for (@typeInfo(row.T).@"struct".fields, 0..) |field, i| {
            comptime var upper: [field.name.len]u8 = undefined;
            comptime for (field.name, 0..) |ch, j| {
                upper[j] = std.ascii.toUpper(ch);
            };
            if (i != 0) try out.appendSlice(gpa, ", ");
            try out.print(gpa, "\"{s}\"", .{upper});
        }
        try out.appendSlice(gpa, "] },\n");
    }
    try out.appendSlice(gpa, "] as const;\n");

    return out.toOwnedSlice(gpa);
}

/// The target-specific struct sizes and field offsets, emitted into the native
/// stack binding's 64-bit mirror.
fn generateLayouts(gpa: std.mem.Allocator) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);

    try out.appendSlice(gpa, layouts_preamble);
    try out.appendSlice(gpa, "// ── Struct layouts (@sizeOf/@offsetOf on the extern structs) ─────────────\n\n");

    try emitLayout(&out, gpa, "REF", c.PancakeReference, "PancakeReference");
    try emitLayout(&out, gpa, "ARG", c.PancakeArgument, "PancakeArgument");
    try emitLayout(&out, gpa, "FRAME", c.PancakeFrame, "PancakeFrame (borrowed)");
    try emitLayout(&out, gpa, "MANAGED_FRAME", c.PancakeManagedFrame, "PancakeManagedFrame (owned, self-releasing)");
    try emitLayout(&out, gpa, "LAST_ABORT", c.PancakeLastAbort, "PancakeLastAbort");
    try emitLayout(&out, gpa, "ALLOCATOR", c.PancakeAllocator, "PancakeAllocator (pancake_context_new_with_allocator)");
    try emitLayout(&out, gpa, "HOST_ACTION", cd.PancakeHostAction, "PancakeHostAction (libpancake_driver, pancake_host_next_action)");
    try emitLayout(&out, gpa, "HOST_PUMP_HOOKS", cd.PancakeHostPumpHooks, "PancakeHostPumpHooks (libpancake_driver, pancake_host_pump_drain)");
    try emitLayout(&out, gpa, "DIAL_PLAN", cd.PancakeDialPlan, "PancakeDialPlan (libpancake_driver, pancake_host_plan_dial)");
    try emitLayout(&out, gpa, "ACCEPT_PLAN", cd.PancakeAcceptPlan, "PancakeAcceptPlan (libpancake_driver, pancake_host_plan_accept)");
    try emitLayout(&out, gpa, "PENDING_DIAL", cd.PancakePendingDial, "PancakePendingDial (libpancake_driver, pancake_host_pending_dial)");

    return out.toOwnedSlice(gpa);
}
