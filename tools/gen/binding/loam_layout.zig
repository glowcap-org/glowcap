//! Reflect Loam C layouts and callback types into the optional Rust consumer.
const std = @import("std");
const c = @import("c_abi_loam");
const storage = @import("c_abi_loam_lmdb");
const shared = @import("c_abi_shared");
const Output = @import("output").Output;
const baseName = @import("reflect").baseName;
pub const step_name = "gen-binding-loam-layout";
pub const outputs = [_]Output{.{ .path = "bindings/rust/src/sys/loam_gen.rs", .generate = generate }};
fn spelling(comptime T: type) []const u8 {
    inline for (.{ "GlowcapLoamRequirementFn", "GlowcapLoamInvokeFn", "GlowcapLoamForwardFn", "GlowcapLoamReferencesFn", "GlowcapLoamEntropyFn", "GlowcapLoamKvFn" }) |name| {
        const Callback = @field(c, name);
        if (T == Callback) return name;
        if (T == ?Callback) return "Option<" ++ name ++ ">";
    }
    return switch (T) {
        u8 => "u8",
        u16 => "u16",
        u32 => "u32",
        u64 => "u64",
        i32 => "i32",
        usize => "usize",
        void => "()",
        anyopaque => "c_void",
        else => switch (@typeInfo(T)) {
            .optional => |info| spelling(info.child),
            .array => |info| std.fmt.comptimePrint("[{s}; {d}]", .{ spelling(info.child), info.len }),
            .pointer => |info| (if (info.attrs.@"const") "*const " else "*mut ") ++ spelling(info.child),
            .@"opaque", .@"struct" => baseName(T),
            else => @compileError("unsupported Loam layout type " ++ @typeName(T)),
        },
    };
}
fn generate(gpa: std.mem.Allocator) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    try out.appendSlice(gpa,
        \\// GENERATED by zig build gen-binding-loam-layout. Do not edit.
        \\use crate::sys::{GlowcapArgument, GlowcapReference};
        \\use core::ffi::c_void;
        \\
    );
    inline for (.{ "GlowcapLoamStore", "GlowcapLoamAttachment", "GlowcapLoamCall", "GlowcapLoamReferences", "GlowcapLoamPageHandle", "GlowcapLoamWork", "GlowcapLoamLmdb", "GlowcapLoamContinuationReservation", "GlowcapLoamPendingContinuation", "GlowcapLoamContinuation", "GlowcapLoamEffectExecution" }) |name| {
        if (comptime std.mem.eql(u8, name, "GlowcapLoamLmdb")) try out.appendSlice(gpa, "#[cfg(not(target_arch = \"wasm32\"))]\n");
        try out.print(gpa, "pub enum {s} {{}}\n", .{name});
    }
    inline for (.{ "GlowcapLoamRequirementFn", "GlowcapLoamInvokeFn", "GlowcapLoamForwardFn", "GlowcapLoamReferencesFn", "GlowcapLoamEntropyFn", "GlowcapLoamKvFn" }) |name| {
        const info = @typeInfo(@typeInfo(@field(c, name)).pointer.child).@"fn";
        var signature: std.ArrayList(u8) = .empty;
        defer signature.deinit(gpa);
        try signature.appendSlice(gpa, "unsafe extern \"C\" fn(");
        inline for (info.param_types, 0..) |param, i| {
            if (i != 0) try signature.appendSlice(gpa, ", ");
            try signature.appendSlice(gpa, comptime spelling(param.?));
        }
        try signature.print(gpa, ") -> {s};", .{comptime spelling(info.return_type.?)});
        // Keep generated callback aliases canonical under the repository's
        // 120-column rustfmt policy, just as the extern generator does.
        const separator = if ("pub type ".len + name.len + " = ".len + signature.items.len > 120) " =\n\t" else " = ";
        try out.print(gpa, "pub type {s}{s}{s}\n", .{ name, separator, signature.items });
    }
    inline for (c.contract_layouts) |layout| {
        const name = baseName(layout.Type);
        try out.print(gpa, "#[repr(C)]\n#[derive(Clone, Copy)]\npub struct {s} {{\n", .{name});
        inline for (@typeInfo(layout.Type).@"struct".field_names, @typeInfo(layout.Type).@"struct".field_types) |name_field, Type| try out.print(gpa, "\tpub {s}{s}: {s},\n", .{ if (std.mem.eql(u8, name_field, "use")) "r#" else "", name_field, comptime spelling(Type) });
        try out.appendSlice(gpa, "}\n");
        const size = try std.fmt.allocPrint(gpa, "core::mem::size_of::<{s}>()", .{name});
        defer gpa.free(size);
        const host_size = try std.fmt.allocPrint(gpa, "{d}", .{@sizeOf(layout.Type)});
        defer gpa.free(host_size);
        const wasm_size = try std.fmt.allocPrint(gpa, "crate::sys::layouts_gen::{s}_SIZE", .{layout.stem});
        defer gpa.free(wasm_size);
        try assertions(gpa, &out, size, host_size, wasm_size);
        inline for (@typeInfo(layout.Type).@"struct".field_names) |name_field| {
            const upper = comptime blk: {
                var chars: [name_field.len]u8 = undefined;
                for (name_field, 0..) |ch, i| chars[i] = std.ascii.toUpper(ch);
                break :blk chars;
            };
            const offset = try std.fmt.allocPrint(gpa, "core::mem::offset_of!({s}, {s}{s})", .{ name, if (std.mem.eql(u8, name_field, "use")) "r#" else "", name_field });
            defer gpa.free(offset);
            const host_offset = try std.fmt.allocPrint(gpa, "{d}", .{@offsetOf(layout.Type, name_field)});
            defer gpa.free(host_offset);
            const wasm_offset = try std.fmt.allocPrint(gpa, "crate::sys::layouts_gen::{s}_{s}_OFF", .{ layout.stem, upper });
            defer gpa.free(wasm_offset);
            try assertions(gpa, &out, offset, host_offset, wasm_offset);
        }
    }
    try out.appendSlice(gpa, "#[cfg(target_arch = \"wasm32\")]\npub use crate::sys::layouts_gen::LOAM_ARCHIVE_FINGERPRINT;\n#[cfg(not(target_arch = \"wasm32\"))]\n");
    try out.print(gpa, "pub const LOAM_ARCHIVE_FINGERPRINT: u64 = {d};\n#[cfg(not(target_arch = \"wasm32\"))]\npub const LOAM_LMDB_ARCHIVE_FINGERPRINT: u64 = {d};\n", .{ c.GLOWCAP_LOAM_ARCHIVE_FINGERPRINT, storage.GLOWCAP_LOAM_LMDB_ARCHIVE_FINGERPRINT });
    inline for (.{ "GLOWCAP_LOAM_ERR_RECOVERY_REQUIRED", "GLOWCAP_LOAM_ERR_STALE_COMPLETION", "GLOWCAP_LOAM_ERR_DENIED", "GLOWCAP_LOAM_ERR_UNCHANGED", "GLOWCAP_LOAM_ERR_APPLICATION" }) |name| try out.print(gpa, "pub const {s}: i32 = {d};\n", .{ name, @field(c, name) });
    try out.print(gpa, "pub const GLOWCAP_LOAM_MAX_URI_BYTES: usize = {d};\n", .{c.GLOWCAP_LOAM_MAX_URI_BYTES});
    try out.print(gpa, "#[cfg(target_arch = \"wasm32\")]\npub const GLOWCAP_LOAM_METADATA_SIZE: usize = {d};\n", .{c.GLOWCAP_LOAM_METADATA_SIZE});
    _ = shared;
    return out.toOwnedSlice(gpa);
}

fn assertions(gpa: std.mem.Allocator, out: *std.ArrayList(u8), left: []const u8, host: []const u8, wasm: []const u8) !void {
    try out.appendSlice(gpa, "#[cfg(not(target_arch = \"wasm32\"))]\n");
    try assertion(gpa, out, left, host);
    try out.appendSlice(gpa, "#[cfg(target_arch = \"wasm32\")]\n");
    try assertion(gpa, out, left, wasm);
}
/// Emit the repository's canonical 120-column Rust assertion shape.
fn assertion(gpa: std.mem.Allocator, out: *std.ArrayList(u8), left: []const u8, right: []const u8) !void {
    if ("const _: () = assert!(".len + left.len + " == ".len + right.len + ");".len <= 120) {
        try out.print(gpa, "const _: () = assert!({s} == {s});\n", .{ left, right });
    } else if ("    assert!(".len + left.len + " == ".len + right.len + ");".len <= 120) {
        try out.print(gpa, "const _: () =\n\tassert!({s} == {s});\n", .{ left, right });
    } else if ("    ".len + left.len + " == ".len + right.len < 120) {
        try out.print(gpa, "const _: () = assert!(\n\t{s} == {s}\n);\n", .{ left, right });
    } else {
        try out.print(gpa, "const _: () = assert!(\n\t{s}\n\t\t== {s}\n);\n", .{ left, right });
    }
}
