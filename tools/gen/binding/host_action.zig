//! Generates the four binding HostAction mirrors — kind constants, typed
//! HostAction, and decode — from `src/c_abi/host` (`PANCAKE_HOST_ACTION_*`,
//! `PancakeHostAction`). Same authority pattern as `tools/gen/binding/ts_abi.zig`: a
//! Zig declaration rename is a compile error here, and
//! `zig build gen-binding-host-action-check` (part of `check`) holds each
//! committed file against a fresh generation.
//!
//! One `arms` table drives every language's types, decode, and the exhaustive
//! `dispatch*` skeleton. Executor arm *bodies* stay hand-written in each
//! binding's `action` module; a new kind fails generate/check rather than
//! silently missing in five hand-rolled switches.

const std = @import("std");
const cd = @import("c_abi_host");

const Output = @import("output").Output;

pub const step_name = "gen-binding-host-action";

pub const outputs = [_]Output{
    .{ .path = "bindings/ts/runtime/internal/host_action.ts", .generate = generateTs },
    .{ .path = "bindings/python/pancake/_host_action_gen.py", .generate = generatePython },
    .{ .path = "bindings/rust/src/host_action_gen.rs", .generate = generateRust },
    .{ .path = "bindings/racket/private/host-action-gen.rkt", .generate = generateRacket },
};

/// Decode shape shared across languages.
const Shape = enum {
    none,
    session,
    close,
    ticket,
    settle,
    fail,
};

const Arm = struct {
    /// Trailing name after `PANCAKE_HOST_ACTION_` / `HOST_ACTION_`.
    name: []const u8,
    value: u32,
    /// Rust / Python class name (`NeedGiftId`).
    variant: []const u8,
    /// Racket drain symbol (`need-gift-id`).
    racket: []const u8,
    shape: Shape,
};

const arms = [_]Arm{
    .{ .name = "DIAL", .value = cd.PANCAKE_HOST_ACTION_DIAL, .variant = "Dial", .racket = "dial", .shape = .ticket },
    .{ .name = "FLUSH", .value = cd.PANCAKE_HOST_ACTION_FLUSH, .variant = "Flush", .racket = "flush", .shape = .session },
    .{ .name = "NEED_GIFT_ID", .value = cd.PANCAKE_HOST_ACTION_NEED_GIFT_ID, .variant = "NeedGiftId", .racket = "need-gift-id", .shape = .ticket },
    .{ .name = "SETTLE", .value = cd.PANCAKE_HOST_ACTION_SETTLE, .variant = "Settle", .racket = "settle", .shape = .settle },
    .{ .name = "FAIL", .value = cd.PANCAKE_HOST_ACTION_FAIL, .variant = "Fail", .racket = "fail", .shape = .fail },
    .{ .name = "CLOSE", .value = cd.PANCAKE_HOST_ACTION_CLOSE, .variant = "Close", .racket = "close", .shape = .close },
    .{ .name = "RESUME", .value = cd.PANCAKE_HOST_ACTION_RESUME, .variant = "Resume", .racket = "resume", .shape = .none },
    .{ .name = "CANCEL_DIAL", .value = cd.PANCAKE_HOST_ACTION_CANCEL_DIAL, .variant = "CancelDial", .racket = "cancel-dial", .shape = .ticket },
};

comptime {
    if (arms[0].value != cd.PANCAKE_HOST_ACTION_DIAL) @compileError("arms DIAL value drift");
    if (arms[1].value != cd.PANCAKE_HOST_ACTION_FLUSH) @compileError("arms FLUSH value drift");
    if (arms[2].value != cd.PANCAKE_HOST_ACTION_NEED_GIFT_ID) @compileError("arms NEED_GIFT_ID value drift");
    if (arms[3].value != cd.PANCAKE_HOST_ACTION_SETTLE) @compileError("arms SETTLE value drift");
    if (arms[4].value != cd.PANCAKE_HOST_ACTION_FAIL) @compileError("arms FAIL value drift");
    if (arms[5].value != cd.PANCAKE_HOST_ACTION_CLOSE) @compileError("arms CLOSE value drift");
    if (arms[6].value != cd.PANCAKE_HOST_ACTION_RESUME) @compileError("arms RESUME value drift");
    if (arms[7].value != cd.PANCAKE_HOST_ACTION_CANCEL_DIAL) @compileError("arms CANCEL_DIAL value drift");
}

fn writeUpperKebab(out: *std.ArrayList(u8), gpa: std.mem.Allocator, name: []const u8) !void {
    for (name) |c| {
        try out.append(gpa, if (c == '_') '-' else c);
    }
}

fn tline(out: *std.ArrayList(u8), gpa: std.mem.Allocator, indent: usize, text: []const u8) !void {
    var i: usize = 0;
    while (i < indent) : (i += 1) try out.append(gpa, '\t');
    try out.appendSlice(gpa, text);
    try out.append(gpa, '\n');
}

fn generateTs(gpa: std.mem.Allocator) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    // Struct offsets come from the active layout `L` (64-bit mirror or the
    // wasm32 descriptor); the kind constants and INVALID_ARGUMENT are
    // target-independent and live in the @pancake/abi package. Imports are
    // lexical source order, independent of the protocol arm order used below;
    // coupling those two made a correct generated inventory fail `deno fmt`.
    const const_imports = [_][]const u8{
        "HOST_ACTION_CANCEL_DIAL",
        "HOST_ACTION_CLOSE",
        "HOST_ACTION_DIAL",
        "HOST_ACTION_FAIL",
        "HOST_ACTION_FLUSH",
        "HOST_ACTION_NEED_GIFT_ID",
        "HOST_ACTION_RESUME",
        "HOST_ACTION_SETTLE",
        "INVALID_ARGUMENT",
    };
    try out.appendSlice(gpa,
        \\// GENERATED by `zig build gen-binding-host-action` from src/c_abi/host
        \\// — do not edit.
        \\// `zig build gen-binding-host-action-check` (part of `check`) fails when
        \\// this is stale.
        \\//
        \\// Typed HostAction + decode for the TypeScript binding. Kind constant
        \\// values live in `@pancake/abi`; struct offsets come from the active
        \\// layout `L` (the 64-bit mirror, or the wasm32 descriptor under the
        \\// browser adapter). This file owns the discriminant union and the
        \\// layout walk that copies borrowed views out before the next
        \\// `pancake_host_next_action` frees them.
        \\
        \\import { L } from "./layout.ts";
        \\import {
        \\
    );
    for (const_imports) |name| {
        try out.append(gpa, '\t');
        try out.appendSlice(gpa, name);
        try out.appendSlice(gpa, ",\n");
    }
    try out.appendSlice(gpa,
        \\} from "@pancake/abi";
        \\import type { Ptr } from "./ffi/runtime.ts";
        \\import { readBytes } from "./seam.ts";
        \\import { readArg } from "../codec.ts";
        \\import { PancakeError } from "../errors.ts";
        \\import type { Argument } from "../value.ts";
        \\
        \\const utf8Decoder = new TextDecoder();
        \\
        \\/** One popped embedder action, a discriminated union over the action
        \\ * kind so each arm carries exactly the fields the C struct fills for
        \\ * it. Every borrowed view is copied out (and a SETTLE's value lifted)
        \\ * before the next `pancake_host_next_action` call can free them. */
        \\export type HostAction =
        \\
    );
    inline for (arms, 0..) |arm, i| {
        const last = i + 1 == arms.len;
        try emitTsUnionMember(&out, gpa, arm, last);
    }
    try out.append(gpa, '\n');
    try out.appendSlice(gpa,
        \\/** Decode a filled `PancakeHostAction` buffer into an owned HostAction. */
        \\export function decodeHostAction(dv: DataView): HostAction {
        \\
    );
    try tline(&out, gpa, 1, "const kind = dv.getUint32(L.HOST_ACTION_KIND_OFF, true);");
    try tline(&out, gpa, 1, "const ticket = dv.getBigUint64(L.HOST_ACTION_TICKET_OFF, true);");
    try tline(&out, gpa, 1, "const view = (off: number, lenOff: number): string =>");
    try tline(&out, gpa, 2, "utf8Decoder.decode(");
    try tline(&out, gpa, 3, "readBytes(L.getPtr(dv, off), L.getUsize(dv, lenOff)),");
    try tline(&out, gpa, 2, ");");
    try tline(&out, gpa, 1, "switch (kind) {");
    inline for (arms) |arm| {
        try emitTsDecodeCase(&out, gpa, arm);
    }
    try tline(&out, gpa, 2, "default:");
    try tline(&out, gpa, 3, "throw new PancakeError(");
    try tline(&out, gpa, 4, "INVALID_ARGUMENT,");
    try tline(&out, gpa, 4, "`unknown host action kind ${kind}`,");
    try tline(&out, gpa, 3, ");");
    try tline(&out, gpa, 1, "}");
    try out.appendSlice(gpa, "}\n\n");
    try out.appendSlice(gpa,
        \\/** Exhaustive dispatch over `HostAction`: a new kind fails compile.
        \\ * Bindings supply the per-arm I/O; this switch is the generated inventory. */
        \\export type HostActionHandlers = {
        \\
    );
    inline for (arms) |arm| {
        const method = try tsHandlerName(gpa, arm);
        defer gpa.free(method);
        try emitTsHandlerSignature(&out, gpa, method, arm.name);
    }
    try out.appendSlice(gpa, "};\n\nexport async function dispatchHostAction(\n");
    try tline(&out, gpa, 1, "action: HostAction,");
    try tline(&out, gpa, 1, "handlers: HostActionHandlers,");
    try out.appendSlice(gpa, "): Promise<void> {\n");
    try tline(&out, gpa, 1, "switch (action.kind) {");
    inline for (arms) |arm| {
        const method = try tsHandlerName(gpa, arm);
        defer gpa.free(method);
        try out.append(gpa, '\t');
        try out.append(gpa, '\t');
        try out.print(gpa, "case HOST_ACTION_{s}:\n", .{arm.name});
        try out.append(gpa, '\t');
        try out.append(gpa, '\t');
        try out.append(gpa, '\t');
        try out.print(gpa, "await handlers.{s}(action);\n", .{method});
        try tline(&out, gpa, 3, "return;");
    }
    try tline(&out, gpa, 2, "default: {");
    try tline(&out, gpa, 3, "const _exhaustive: never = action;");
    try tline(&out, gpa, 3, "void _exhaustive;");
    try tline(&out, gpa, 3, "throw new PancakeError(INVALID_ARGUMENT, \"unknown host action\");");
    try tline(&out, gpa, 2, "}");
    try tline(&out, gpa, 1, "}");
    try out.appendSlice(gpa, "}\n");
    return out.toOwnedSlice(gpa);
}

fn tsHandlerName(gpa: std.mem.Allocator, arm: Arm) ![]u8 {
    // DIAL → dial, NEED_GIFT_ID → needGiftId
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    var upper_next = false;
    for (arm.name, 0..) |c, i| {
        if (c == '_') {
            upper_next = true;
            continue;
        }
        if (i == 0) {
            try out.append(gpa, std.ascii.toLower(c));
        } else if (upper_next) {
            try out.append(gpa, std.ascii.toUpper(c));
            upper_next = false;
        } else {
            try out.append(gpa, std.ascii.toLower(c));
        }
    }
    return out.toOwnedSlice(gpa);
}

/// Emit one `HostActionHandlers` member. `deno fmt` wraps a member whose
/// single-line form is wider than its 120-column print width, where the one
/// leading tab renders as the four-column indent width. The generator wraps at
/// the same boundary so its raw output is already `deno fmt`-clean — the check
/// compares bytes, and there is no formatter pass between generate and commit.
fn emitTsHandlerSignature(out: *std.ArrayList(u8), gpa: std.mem.Allocator, method: []const u8, name: []const u8) !void {
    const single = try std.fmt.allocPrint(
        gpa,
        "\t{s}: (action: Extract<HostAction, {{ kind: typeof HOST_ACTION_{s} }}>) => void | Promise<void>;",
        .{ method, name },
    );
    defer gpa.free(single);
    // The leading '\t' renders as four columns; the rest is one column each.
    const print_width = single.len - 1 + 4;
    if (print_width <= 120) {
        try out.appendSlice(gpa, single);
        try out.append(gpa, '\n');
        return;
    }
    try out.print(gpa, "\t{s}: (\n", .{method});
    try out.print(gpa, "\t\taction: Extract<HostAction, {{ kind: typeof HOST_ACTION_{s} }}>,\n", .{name});
    try out.appendSlice(gpa, "\t) => void | Promise<void>;\n");
}

fn emitTsUnionMember(out: *std.ArrayList(u8), gpa: std.mem.Allocator, arm: Arm, last: bool) !void {
    switch (arm.shape) {
        .none => {
            try out.append(gpa, '\t');
            try out.print(gpa, "| {{ kind: typeof HOST_ACTION_{s} }}", .{arm.name});
            try out.appendSlice(gpa, if (last) ";\n" else "\n");
        },
        .session => {
            try out.append(gpa, '\t');
            try out.print(gpa, "| {{ kind: typeof HOST_ACTION_{s}; session: Ptr }}", .{arm.name});
            try out.appendSlice(gpa, if (last) ";\n" else "\n");
        },
        .close => {
            try out.append(gpa, '\t');
            try out.print(gpa, "| {{ kind: typeof HOST_ACTION_{s}; session: Ptr; result: number }}", .{arm.name});
            try out.appendSlice(gpa, if (last) ";\n" else "\n");
        },
        .ticket => {
            try out.append(gpa, '\t');
            try out.print(gpa, "| {{ kind: typeof HOST_ACTION_{s}; ticket: bigint }}", .{arm.name});
            try out.appendSlice(gpa, if (last) ";\n" else "\n");
        },
        .settle => {
            try out.append(gpa, '\t');
            try out.print(gpa, "| {{ kind: typeof HOST_ACTION_{s}; ticket: bigint; value: Argument }}", .{arm.name});
            try out.appendSlice(gpa, if (last) ";\n" else "\n");
        },
        .fail => {
            try out.append(gpa, '\t');
            try out.print(gpa, "| {{ kind: typeof HOST_ACTION_{s}; ticket: bigint; result: number; message: string }}", .{arm.name});
            try out.appendSlice(gpa, if (last) ";\n" else "\n");
        },
    }
}

fn emitTsDecodeCase(out: *std.ArrayList(u8), gpa: std.mem.Allocator, arm: Arm) !void {
    try out.append(gpa, '\t');
    try out.append(gpa, '\t');
    try out.print(gpa, "case HOST_ACTION_{s}:\n", .{arm.name});
    switch (arm.shape) {
        .none => try tline(out, gpa, 3, "return { kind };"),
        .session => try tline(out, gpa, 3, "return { kind, session: L.getPtr(dv, L.HOST_ACTION_SESSION_OFF) };"),
        .close => {
            try tline(out, gpa, 3, "return {");
            try tline(out, gpa, 4, "kind,");
            try tline(out, gpa, 4, "session: L.getPtr(dv, L.HOST_ACTION_SESSION_OFF),");
            try tline(out, gpa, 4, "result: dv.getInt32(L.HOST_ACTION_RESULT_OFF, true),");
            try tline(out, gpa, 3, "};");
        },
        .ticket => try tline(out, gpa, 3, "return { kind, ticket };"),
        .settle => try tline(out, gpa, 3, "return { kind, ticket, value: readArg(dv, L.HOST_ACTION_VALUE_OFF) };"),
        .fail => {
            try tline(out, gpa, 3, "return {");
            try tline(out, gpa, 4, "kind,");
            try tline(out, gpa, 4, "ticket,");
            try tline(out, gpa, 4, "result: dv.getInt32(L.HOST_ACTION_RESULT_OFF, true),");
            try tline(out, gpa, 4, "message: view(L.HOST_ACTION_MESSAGE_OFF, L.HOST_ACTION_MESSAGE_LEN_OFF),");
            try tline(out, gpa, 3, "};");
        },
    }
}

fn generatePython(gpa: std.mem.Allocator) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    try out.appendSlice(gpa,
        \\# GENERATED by `zig build gen-binding-host-action` from src/c_abi/host
        \\# — do not edit.
        \\# `zig build gen-binding-host-action-check` (part of `check`) fails when
        \\# this is stale.
        \\#
        \\# Kind constants, HostAction union, and decode for the Python binding.
        \\# Executor arms stay in `_action.py`.
        \\
        \\from __future__ import annotations
        \\
        \\import ctypes
        \\from dataclasses import dataclass
        \\from typing import Union
        \\
        \\
        \\# PancakeHostAction.kind — mirrors PANCAKE_HOST_ACTION_* in pancake_host.h.
        \\
    );
    inline for (arms) |arm| {
        try out.print(gpa, "HOST_ACTION_{s} = {d}\n", .{ arm.name, arm.value });
    }
    try out.appendSlice(gpa, "\n\n");
    inline for (arms) |arm| {
        try emitPyClass(&out, gpa, arm);
    }
    try out.appendSlice(gpa, "HostAction = Union[");
    inline for (arms, 0..) |arm, i| {
        if (i != 0) try out.appendSlice(gpa, ", ");
        try out.appendSlice(gpa, arm.variant);
    }
    try out.appendSlice(gpa,
        \\]
        \\
        \\
        \\def _view(ptr, length) -> str:
        \\    # The bytes originate in a partner-authored give, so decode
        \\    # leniently rather than let hostile bytes raise mid-drain.
        \\    return ctypes.string_at(ptr, length).decode(errors="replace") if ptr and length else ""
        \\
        \\
        \\def decode(a) -> HostAction:
        \\    """Decode a filled ``PancakeHostAction`` ctypes struct into an
        \\    owned ``HostAction`` variant. Lazily imports ``_arg_from_c`` so
        \\    this module stays importable without a codec cycle.
        \\    """
        \\    from ._codec import _arg_from_c
        \\
        \\    kind = a.kind
        \\
    );
    inline for (arms) |arm| {
        try emitPyDecodeArm(&out, gpa, arm);
    }
    try out.appendSlice(gpa,
        \\    raise RuntimeError(f"unknown host action kind: {kind}")
        \\
        \\
        \\async def dispatch(action: HostAction, handlers) -> None:
        \\    """Exhaustive dispatch: handlers expose one coroutine/callable per arm
        \\    (`dial`, `flush`, `need_gift_id`, `settle`, `fail`, `close`, `resume`).
        \\    An eighth
        \\    kind fails here rather than silently missing in `_action.py`.
        \\    """
        \\    match action:
        \\
    );
    inline for (arms) |arm| {
        const method = try snakeHandlerName(gpa, arm);
        defer gpa.free(method);
        try out.print(gpa, "        case {s}():\n", .{arm.variant});
        try out.print(gpa, "            await handlers.{s}(action)\n", .{method});
    }
    try out.appendSlice(gpa,
        \\        case _:
        \\            raise RuntimeError(f"unknown host action: {action!r}")
        \\
    );
    return out.toOwnedSlice(gpa);
}

fn snakeHandlerName(gpa: std.mem.Allocator, arm: Arm) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    for (arm.name) |c| {
        try out.append(gpa, if (c == '_') '_' else std.ascii.toLower(c));
    }
    return out.toOwnedSlice(gpa);
}

fn emitPyClass(out: *std.ArrayList(u8), gpa: std.mem.Allocator, arm: Arm) !void {
    try out.print(gpa, "@dataclass(frozen=True)\nclass {s}:\n", .{arm.variant});
    switch (arm.shape) {
        .none => try out.appendSlice(gpa,
            \\    pass
            \\
            \\
        ),
        .session => try out.appendSlice(gpa,
            \\    session_ptr: int
            \\
            \\
        ),
        .close => try out.appendSlice(gpa,
            \\    session_ptr: int
            \\    result: int
            \\
            \\
        ),
        .ticket => try out.appendSlice(gpa,
            \\    ticket: int
            \\
            \\
        ),
        .settle => try out.appendSlice(gpa,
            \\    ticket: int
            \\    value: object
            \\
            \\
        ),
        .fail => try out.appendSlice(gpa,
            \\    ticket: int
            \\    result: int
            \\    message: str
            \\
            \\
        ),
    }
    // PEP 8: two blank lines between top-level class definitions. The trailing
    // empty multiline lines above already contribute one; this adds the second.
    try out.append(gpa, '\n');
}

fn emitPyDecodeArm(out: *std.ArrayList(u8), gpa: std.mem.Allocator, arm: Arm) !void {
    try out.print(gpa, "    if kind == HOST_ACTION_{s}:\n", .{arm.name});
    switch (arm.shape) {
        .none => try out.print(gpa,
            \\        return {s}()
            \\
        , .{arm.variant}),
        .session => try out.print(gpa,
            \\        return {s}(session_ptr=a.session or 0)
            \\
        , .{arm.variant}),
        .close => try out.print(gpa,
            \\        return {s}(session_ptr=a.session or 0, result=a.result)
            \\
        , .{arm.variant}),
        .ticket => try out.print(gpa,
            \\        return {s}(ticket=a.ticket)
            \\
        , .{arm.variant}),
        .settle => try out.print(gpa,
            \\        return {s}(ticket=a.ticket, value=_arg_from_c(a.value))
            \\
        , .{arm.variant}),
        .fail => try out.print(gpa,
            \\        return {s}(ticket=a.ticket, result=a.result, message=_view(a.message, a.message_len))
            \\
        , .{arm.variant}),
    }
}

fn generateRust(gpa: std.mem.Allocator) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    try out.appendSlice(gpa,
        \\//! GENERATED by `zig build gen-binding-host-action` from src/c_abi/host
        \\//! — do not edit.
        \\//! `zig build gen-binding-host-action-check` (part of `check`) fails when
        \\//! this is stale.
        \\//!
        \\//! Kind constants, `HostAction`, and decode for the Rust binding.
        \\//! Executor arms stay in `action.rs`.
        \\
        \\// The generator owns these bytes; a formatter version bump must not
        \\// drift them out from under `gen-binding-host-action-check`.
        \\#![cfg_attr(rustfmt, rustfmt::skip)]
        \\
        \\use core::ffi::c_uint;
        \\
        \\use crate::sys::host as ffi;
        \\use crate::{arg_from_sys, Argument};
        \\
        \\/// `PancakeHostAction.kind` — mirrors `PANCAKE_HOST_ACTION_*` in
        \\/// `pancake_host.h`.
        \\
    );
    inline for (arms) |arm| {
        try out.print(gpa, "pub const HOST_ACTION_{s}: c_uint = {d};\n", .{ arm.name, arm.value });
    }
    try out.appendSlice(gpa,
        \\
        \\/// One popped embedder action, every borrowed view lifted to owned
        \\/// Rust values (a SETTLE's `PancakeArgument` included) before the next
        \\/// `pancake_host_next_action` call can free them.
        \\pub enum HostAction {
        \\
    );
    inline for (arms) |arm| {
        try emitRustVariant(&out, gpa, arm);
    }
    try out.appendSlice(gpa, "}\n\n");
    try out.appendSlice(gpa,
        \\/// Whether `kind` names a generated host action. Check this before
        \\/// decoding data received across the C boundary.
        \\pub fn is_known_kind(kind: c_uint) -> bool {
        \\    matches!(kind,
    );
    for (arms, 0..) |arm, index| {
        if (index != 0) try out.appendSlice(gpa, " | ");
        try out.print(gpa, "HOST_ACTION_{s}", .{arm.name});
    }
    try out.appendSlice(gpa, ")\n}\n\n");
    try out.appendSlice(gpa,
        \\/// Decode a filled `PancakeHostAction` into an owned `HostAction`.
        \\/// The caller must first prove `is_known_kind(raw.kind)`.
        \\pub fn decode(raw: &ffi::PancakeHostAction) -> HostAction {
        \\
    );
    try tline(&out, gpa, 1, "let view = |ptr: *const u8, len: usize| -> String {");
    try tline(&out, gpa, 2, "if ptr.is_null() || len == 0 {");
    try tline(&out, gpa, 3, "String::new()");
    try tline(&out, gpa, 2, "} else {");
    try tline(&out, gpa, 3, "// The bytes originate in a partner-authored give, so decode");
    try tline(&out, gpa, 3, "// leniently rather than let hostile bytes fault mid-drain.");
    try tline(&out, gpa, 3, "String::from_utf8_lossy(unsafe { core::slice::from_raw_parts(ptr, len) }).into_owned()");
    try tline(&out, gpa, 2, "}");
    try tline(&out, gpa, 1, "};");
    try tline(&out, gpa, 1, "match raw.kind {");
    inline for (arms) |arm| {
        try emitRustDecodeArm(&out, gpa, arm);
    }
    try tline(&out, gpa, 2, "kind => unreachable!(\"unknown host action kind {kind}\"),");
    try tline(&out, gpa, 1, "}");
    try out.appendSlice(gpa, "}\n\n");
    try out.appendSlice(gpa,
        \\/// Exhaustive dispatch over `HostAction`. Handlers expose one async fn
        \\/// per arm; a new kind fails to compile here.
        \\pub async fn dispatch<H>(action: HostAction, handlers: &H) -> crate::Result<()>
        \\where
        \\    H: HostActionHandlers,
        \\{
        \\    match action {
        \\
    );
    inline for (arms) |arm| {
        const method = try snakeHandlerName(gpa, arm);
        defer gpa.free(method);
        if (arm.shape == .none)
            try out.print(gpa, "        HostAction::{s} => handlers.{s}(action).await,\n", .{ arm.variant, method })
        else
            try out.print(gpa, "        HostAction::{s} {{ .. }} => handlers.{s}(action).await,\n", .{ arm.variant, method });
    }
    try out.appendSlice(gpa,
        \\    }
        \\}
        \\
        \\/// Per-arm I/O the binding supplies to [`dispatch`].
        \\pub trait HostActionHandlers {
        \\
    );
    inline for (arms) |arm| {
        const method = try snakeHandlerName(gpa, arm);
        defer gpa.free(method);
        try out.print(gpa, "    fn {s}(&self, action: HostAction) -> impl std::future::Future<Output = crate::Result<()>> + '_;\n", .{method});
    }
    try out.appendSlice(gpa, "}\n");
    return out.toOwnedSlice(gpa);
}

fn emitRustVariant(out: *std.ArrayList(u8), gpa: std.mem.Allocator, arm: Arm) !void {
    if (arm.shape == .none) {
        try out.print(gpa, "\t{s},\n", .{arm.variant});
        return;
    }
    try out.append(gpa, '\t');
    try out.print(gpa, "{s} {{\n", .{arm.variant});
    switch (arm.shape) {
        .none => unreachable,
        .session => try tline(out, gpa, 2, "session: usize,"),
        .close => {
            try tline(out, gpa, 2, "session: usize,");
            try tline(out, gpa, 2, "result: i32,");
        },
        .ticket => try tline(out, gpa, 2, "ticket: u64,"),
        .settle => {
            try tline(out, gpa, 2, "ticket: u64,");
            try tline(out, gpa, 2, "value: Argument,");
        },
        .fail => {
            try tline(out, gpa, 2, "ticket: u64,");
            try tline(out, gpa, 2, "result: i32,");
            try tline(out, gpa, 2, "message: String,");
        },
    }
    try tline(out, gpa, 1, "},");
}

fn emitRustDecodeArm(out: *std.ArrayList(u8), gpa: std.mem.Allocator, arm: Arm) !void {
    // Single-field ticket arms stay one-line so rustfmt and gen-check agree.
    if (arm.shape == .none) {
        try out.print(gpa, "\t\tHOST_ACTION_{s} => HostAction::{s},\n", .{ arm.name, arm.variant });
        return;
    }
    if (arm.shape == .ticket) {
        try out.append(gpa, '\t');
        try out.append(gpa, '\t');
        try out.print(gpa, "HOST_ACTION_{s} => HostAction::{s} {{ ticket: raw.ticket }},\n", .{ arm.name, arm.variant });
        return;
    }
    try out.append(gpa, '\t');
    try out.append(gpa, '\t');
    try out.print(gpa, "HOST_ACTION_{s} => HostAction::{s} {{\n", .{ arm.name, arm.variant });
    switch (arm.shape) {
        .none => unreachable,
        .session => try tline(out, gpa, 3, "session: raw.session as usize,"),
        .close => {
            try tline(out, gpa, 3, "session: raw.session as usize,");
            try tline(out, gpa, 3, "result: raw.result,");
        },
        .ticket => unreachable,
        .settle => {
            try tline(out, gpa, 3, "ticket: raw.ticket,");
            try tline(out, gpa, 3, "value: unsafe { arg_from_sys(&raw.value) },");
        },
        .fail => {
            try tline(out, gpa, 3, "ticket: raw.ticket,");
            try tline(out, gpa, 3, "result: raw.result,");
            try tline(out, gpa, 3, "message: view(raw.message, raw.message_len),");
        },
    }
    try tline(out, gpa, 2, "},");
}

fn generateRacket(gpa: std.mem.Allocator) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    try out.appendSlice(gpa,
        \\#lang racket/base
        \\;; GENERATED by `zig build gen-binding-host-action` from src/c_abi/host
        \\;; — do not edit.
        \\;; `zig build gen-binding-host-action-check` (part of `check`) fails when
        \\;; this is stale.
        \\;;
        \\;; Kind constants + decode for the Racket binding. Executor arms stay
        \\;; in `action.rkt`. Does not require `codec.rkt` (that would cycle
        \\;; through `constants.rkt`); the caller passes `arg<-c`.
        \\
        \\(require ffi/unsafe
        \\         "ffi-shared.rkt"
        \\         "ffi-host.rkt")
        \\
        \\(provide
    );
    inline for (arms) |arm| {
        try out.appendSlice(gpa, "         HOST-ACTION-");
        try writeUpperKebab(&out, gpa, arm.name);
        try out.appendSlice(gpa, "\n");
    }
    try out.appendSlice(gpa,
        \\         host-decode-action!
        \\         host-dispatch-action!)
        \\
        \\;; PancakeHostAction.kind — mirrors PANCAKE_HOST_ACTION_* in pancake_host.h.
        \\
    );
    inline for (arms) |arm| {
        try out.appendSlice(gpa, "(define HOST-ACTION-");
        try writeUpperKebab(&out, gpa, arm.name);
        try out.print(gpa, " {d})\n", .{arm.value});
    }
    try out.appendSlice(gpa,
        \\
        \\;; Decode a filled PancakeHostAction cstruct into the list form the
        \\;; drain switch matches: `(list 'dial …)`, `(list 'flush …)`, …
        \\;; `arg<-c` is passed by the caller (from codec.rkt) so this module
        \\;; stays require-acyclic with constants.rkt.
        \\(define (host-decode-action! a arg<-c)
        \\  (define kind (PancakeHostAction-kind a))
        \\  (define (view->string ptr len) (bytes->string/utf-8 (bytes<-c ptr len) #\uFFFD))
        \\  (cond
        \\
    );
    inline for (arms) |arm| {
        try emitRacketDecodeArm(&out, gpa, arm);
    }
    try out.appendSlice(gpa,
        \\    [else (error 'pancake "unknown host action kind: ~a" kind)]))
        \\
        \\;; Exhaustive dispatch over a decoded action list. `handlers` is a
        \\;; hash of racket symbols (`'dial`, `'flush`, …) to thunks of
        \\;; `(lambda (a) …)`. A missing arm fails loud — the inventory lives
        \\;; here so `action.rkt` cannot silently drop a new kind.
        \\(define (host-dispatch-action! a handlers)
        \\  (define tag (car a))
        \\  (define fn (hash-ref handlers tag #f))
        \\  (unless fn
        \\    (error 'pancake "host-dispatch-action!: missing handler for ~a" tag))
        \\  (fn a))
        \\
    );
    return out.toOwnedSlice(gpa);
}

fn emitRacketDecodeArm(out: *std.ArrayList(u8), gpa: std.mem.Allocator, arm: Arm) !void {
    try out.appendSlice(gpa, "    [(= kind HOST-ACTION-");
    try writeUpperKebab(out, gpa, arm.name);
    try out.appendSlice(gpa, ")\n");
    switch (arm.shape) {
        .none => try out.print(gpa,
            \\     (list '{s})]
            \\
        , .{arm.racket}),
        .session => try out.print(gpa,
            \\     (list '{s} (PancakeHostAction-session a))]
            \\
        , .{arm.racket}),
        .close => try out.print(gpa,
            \\     (list '{s} (PancakeHostAction-session a) (PancakeHostAction-result a))]
            \\
        , .{arm.racket}),
        .ticket => try out.print(gpa,
            \\     (list '{s} (PancakeHostAction-ticket a))]
            \\
        , .{arm.racket}),
        .settle => try out.print(gpa,
            \\     ;; `arg<-c` copies every byte payload into fresh Racket values, so the
            \\     ;; outcome outlives the popped action's until-next-pop lifetime.
            \\     (list '{s} (PancakeHostAction-ticket a) (arg<-c (PancakeHostAction-value a)))]
            \\
        , .{arm.racket}),
        .fail => try out.print(gpa,
            \\     (list '{s} (PancakeHostAction-ticket a) (PancakeHostAction-result a)
            \\           (view->string (PancakeHostAction-message a) (PancakeHostAction-message-len a)))]
            \\
        , .{arm.racket}),
    }
}
