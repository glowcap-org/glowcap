//! The Python, Rust, and Racket emitters of the host-action mirror; the arm
//! table, the shared writers, and the TypeScript emitter stay with the
//! output list in `host_action.zig`.

const std = @import("std");
const ha = @import("host_action.zig");

pub fn generatePython(gpa: std.mem.Allocator) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    try out.appendSlice(gpa,
        \\# GENERATED by `zig build gen-binding-host-action` from src/c_abi/host
        \\# — do not edit.
        \\# `zig build gen-binding-host-action-check` (part of `check`) fails when
        \\# this is stale.
        \\#
        \\# Kind constants, HostAction union, and decode for the Python binding.
        \\# Executor arms stay in `_action.py`.
        \\
        \\from __future__ import annotations
        \\
        \\import ctypes
        \\from dataclasses import dataclass
        \\from typing import Union
        \\
        \\
        \\# GlowcapHostAction.kind — mirrors GLOWCAP_HOST_ACTION_* in glowcap_host.h.
        \\
    );
    inline for (ha.arms) |arm| {
        try out.print(gpa, "HOST_ACTION_{s} = {d}\n", .{ arm.name, arm.value });
    }
    try out.appendSlice(gpa, "\n\n");
    inline for (ha.arms) |arm| {
        try emitPyClass(&out, gpa, arm);
    }
    try out.appendSlice(gpa, "HostAction = Union[");
    inline for (ha.arms, 0..) |arm, i| {
        if (i != 0) try out.appendSlice(gpa, ", ");
        try out.appendSlice(gpa, arm.variant);
    }
    try out.appendSlice(gpa,
        \\]
        \\
        \\
        \\def _view(ptr, length) -> str:
        \\    # The bytes originate in a partner-authored give, so decode
        \\    # leniently rather than let untrusted bytes raise mid-drain.
        \\    return ctypes.string_at(ptr, length).decode(errors="replace") if ptr and length else ""
        \\
        \\
        \\def decode(a) -> HostAction:
        \\    """Decode a filled ``GlowcapHostAction`` ctypes struct into an
        \\    owned ``HostAction`` variant. Lazily imports ``_arg_from_c`` so
        \\    this module stays importable without a codec cycle.
        \\    """
        \\    from ._abi_value import _arg_from_c
        \\
        \\    kind = a.kind
        \\
    );
    inline for (ha.arms) |arm| {
        try emitPyDecodeArm(&out, gpa, arm);
    }
    try out.appendSlice(gpa,
        \\    raise RuntimeError(f"unknown host action kind: {kind}")
        \\
        \\
        \\async def dispatch(action: HostAction, handlers) -> None:
        \\    """Exhaustive dispatch: handlers expose one coroutine/callable per arm
        \\    (`dial`, `flush`, `need_gift_id`, `settle`, `fail`, `close`, `resume`).
        \\    An eighth
        \\    kind fails here rather than silently missing in `_action.py`.
        \\    """
        \\    match action:
        \\
    );
    inline for (ha.arms) |arm| {
        const method = try snakeHandlerName(gpa, arm);
        defer gpa.free(method);
        try out.print(gpa, "        case {s}():\n", .{arm.variant});
        try out.print(gpa, "            await handlers.{s}(action)\n", .{method});
    }
    try out.appendSlice(gpa,
        \\        case _:
        \\            raise RuntimeError(f"unknown host action: {action!r}")
        \\
    );
    return out.toOwnedSlice(gpa);
}

fn snakeHandlerName(gpa: std.mem.Allocator, arm: ha.Arm) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    for (arm.name) |c| {
        try out.append(gpa, if (c == '_') '_' else std.ascii.toLower(c));
    }
    return out.toOwnedSlice(gpa);
}

fn emitPyClass(out: *std.ArrayList(u8), gpa: std.mem.Allocator, arm: ha.Arm) !void {
    try out.print(gpa, "@dataclass(frozen=True)\nclass {s}:\n", .{arm.variant});
    switch (arm.shape) {
        .none => try out.appendSlice(gpa,
            \\    pass
            \\
            \\
        ),
        .session => try out.appendSlice(gpa,
            \\    session_ptr: int
            \\
            \\
        ),
        .close => try out.appendSlice(gpa,
            \\    session_ptr: int
            \\    result: int
            \\
            \\
        ),
        .ticket => try out.appendSlice(gpa,
            \\    ticket: int
            \\
            \\
        ),
        .dial_attempt => try out.appendSlice(gpa,
            \\    ticket: int
            \\    route_index: int
            \\
            \\
        ),
        .settle => try out.appendSlice(gpa,
            \\    ticket: int
            \\    value: object
            \\
            \\
        ),
        .fail => try out.appendSlice(gpa,
            \\    ticket: int
            \\    result: int
            \\    message: str
            \\
            \\
        ),
    }
    // PEP 8: two blank lines between top-level class definitions. The trailing
    // empty multiline lines above already contribute one; this adds the second.
    try out.append(gpa, '\n');
}

fn emitPyDecodeArm(out: *std.ArrayList(u8), gpa: std.mem.Allocator, arm: ha.Arm) !void {
    try out.print(gpa, "    if kind == HOST_ACTION_{s}:\n", .{arm.name});
    switch (arm.shape) {
        .none => try out.print(gpa,
            \\        return {s}()
            \\
        , .{arm.variant}),
        .session => try out.print(gpa,
            \\        return {s}(session_ptr=a.session or 0)
            \\
        , .{arm.variant}),
        .close => try out.print(gpa,
            \\        return {s}(session_ptr=a.session or 0, result=a.result)
            \\
        , .{arm.variant}),
        .ticket => try out.print(gpa,
            \\        return {s}(ticket=a.ticket)
            \\
        , .{arm.variant}),
        .dial_attempt => try out.print(gpa,
            \\        return {s}(ticket=a.ticket, route_index=a.route_index)
            \\
        , .{arm.variant}),
        .settle => try out.print(gpa,
            \\        return {s}(ticket=a.ticket, value=_arg_from_c(a.value))
            \\
        , .{arm.variant}),
        .fail => try out.print(gpa,
            \\        return {s}(ticket=a.ticket, result=a.result, message=_view(a.message, a.message_len))
            \\
        , .{arm.variant}),
    }
}

pub fn generateRust(gpa: std.mem.Allocator) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    try out.appendSlice(gpa,
        \\//! GENERATED by `zig build gen-binding-host-action` from src/c_abi/host
        \\//! — do not edit.
        \\//! `zig build gen-binding-host-action-check` (part of `check`) fails when
        \\//! this is stale.
        \\//!
        \\//! Kind constants, `HostAction`, and decode for the Rust binding.
        \\//! Executor arms stay in `action.rs`.
        \\
        \\// The generator owns these bytes; a formatter version bump must not
        \\// drift them out from under `gen-binding-host-action-check`.
        \\#![cfg_attr(rustfmt, rustfmt::skip)]
        \\
        \\use core::ffi::c_uint;
        \\
        \\use crate::sys::host as ffi;
        \\use crate::{arg_from_sys, Argument, Error, Result};
        \\
        \\/// `GlowcapHostAction.kind` — mirrors `GLOWCAP_HOST_ACTION_*` in
        \\/// `glowcap_host.h`.
        \\
    );
    inline for (ha.arms) |arm| {
        try out.print(gpa, "pub const HOST_ACTION_{s}: c_uint = {d};\n", .{ arm.name, arm.value });
    }
    try out.appendSlice(gpa,
        \\
        \\/// One popped embedder action, every borrowed view lifted to owned
        \\/// Rust values (a SETTLE's `GlowcapArgument` included) before the next
        \\/// `glowcap_host_next_action` call can free them.
        \\pub enum HostAction {
        \\
    );
    inline for (ha.arms) |arm| {
        try emitRustVariant(&out, gpa, arm);
    }
    try out.appendSlice(gpa, "}\n\n");
    try out.appendSlice(gpa,
        \\/// Decode a filled `GlowcapHostAction` into an owned `HostAction`.
        \\/// An unknown ABI discriminant is a returned internal failure, never a
        \\/// process panic.
        \\pub fn decode(raw: &ffi::GlowcapHostAction) -> Result<HostAction> {
        \\
    );
    try ha.tline(&out, gpa, 1, "let view = |ptr: *const u8, len: usize| -> String {");
    try ha.tline(&out, gpa, 2, "if ptr.is_null() || len == 0 {");
    try ha.tline(&out, gpa, 3, "String::new()");
    try ha.tline(&out, gpa, 2, "} else {");
    try ha.tline(&out, gpa, 3, "// The bytes originate in a partner-authored give, so decode");
    try ha.tline(&out, gpa, 3, "// leniently rather than let untrusted bytes fault mid-drain.");
    try ha.tline(&out, gpa, 3, "String::from_utf8_lossy(unsafe { core::slice::from_raw_parts(ptr, len) }).into_owned()");
    try ha.tline(&out, gpa, 2, "}");
    try ha.tline(&out, gpa, 1, "};");
    try ha.tline(&out, gpa, 1, "Ok(match raw.kind {");
    inline for (ha.arms) |arm| {
        try emitRustDecodeArm(&out, gpa, arm);
    }
    try ha.tline(&out, gpa, 2, "kind => return Err(Error::with_detail(");
    try ha.tline(&out, gpa, 3, "crate::sys::ERR_INTERNAL,");
    try ha.tline(&out, gpa, 3, "format!(\"glowcap ABI returned unknown host action kind {kind}\"),");
    try ha.tline(&out, gpa, 2, ")),");
    try ha.tline(&out, gpa, 1, "})");
    try out.appendSlice(gpa, "}\n\n");
    try out.appendSlice(gpa,
        \\/// Exhaustive dispatch over `HostAction`. Handlers expose one async fn
        \\/// per arm; a new kind fails to compile here.
        \\pub async fn dispatch<H>(action: HostAction, handlers: &H) -> crate::Result<()>
        \\where
        \\    H: HostActionHandlers,
        \\{
        \\    match action {
        \\
    );
    inline for (ha.arms) |arm| {
        const method = try snakeHandlerName(gpa, arm);
        defer gpa.free(method);
        switch (arm.shape) {
            .none => try out.print(gpa, "        HostAction::{s} => handlers.{s}().await,\n", .{ arm.variant, method }),
            .session => try out.print(gpa, "        HostAction::{s} {{ session }} => handlers.{s}(session).await,\n", .{ arm.variant, method }),
            .close => try out.print(gpa, "        HostAction::{s} {{ session, result }} => handlers.{s}(session, result).await,\n", .{ arm.variant, method }),
            .ticket => try out.print(gpa, "        HostAction::{s} {{ ticket }} => handlers.{s}(ticket).await,\n", .{ arm.variant, method }),
            .dial_attempt => try out.print(gpa, "        HostAction::{s} {{ ticket, route_index }} => handlers.{s}(ticket, route_index).await,\n", .{ arm.variant, method }),
            .settle => try out.print(gpa, "        HostAction::{s} {{ ticket, value }} => handlers.{s}(ticket, value).await,\n", .{ arm.variant, method }),
            .fail => try out.print(gpa, "        HostAction::{s} {{ ticket, result, message }} => handlers.{s}(ticket, result, message).await,\n", .{ arm.variant, method }),
        }
    }
    try out.appendSlice(gpa,
        \\    }
        \\}
        \\
        \\/// Per-arm I/O the binding supplies to [`dispatch`].
        \\pub trait HostActionHandlers {
        \\
    );
    inline for (ha.arms) |arm| {
        const method = try snakeHandlerName(gpa, arm);
        defer gpa.free(method);
        const parameters = switch (arm.shape) {
            .none => "",
            .session => ", session: usize",
            .close => ", session: usize, result: i32",
            .ticket => ", ticket: u64",
            .dial_attempt => ", ticket: u64, route_index: usize",
            .settle => ", ticket: u64, value: Argument",
            .fail => ", ticket: u64, result: i32, message: String",
        };
        try out.print(gpa, "    fn {s}(&self{s}) -> impl std::future::Future<Output = crate::Result<()>> + '_;\n", .{ method, parameters });
    }
    try out.appendSlice(gpa, "}\n");
    return out.toOwnedSlice(gpa);
}

fn emitRustVariant(out: *std.ArrayList(u8), gpa: std.mem.Allocator, arm: ha.Arm) !void {
    if (arm.shape == .none) {
        try out.print(gpa, "\t{s},\n", .{arm.variant});
        return;
    }
    try out.append(gpa, '\t');
    try out.print(gpa, "{s} {{\n", .{arm.variant});
    switch (arm.shape) {
        .none => unreachable,
        .session => try ha.tline(out, gpa, 2, "session: usize,"),
        .close => {
            try ha.tline(out, gpa, 2, "session: usize,");
            try ha.tline(out, gpa, 2, "result: i32,");
        },
        .ticket => try ha.tline(out, gpa, 2, "ticket: u64,"),
        .dial_attempt => {
            try ha.tline(out, gpa, 2, "ticket: u64,");
            try ha.tline(out, gpa, 2, "route_index: usize,");
        },
        .settle => {
            try ha.tline(out, gpa, 2, "ticket: u64,");
            try ha.tline(out, gpa, 2, "value: Argument,");
        },
        .fail => {
            try ha.tline(out, gpa, 2, "ticket: u64,");
            try ha.tline(out, gpa, 2, "result: i32,");
            try ha.tline(out, gpa, 2, "message: String,");
        },
    }
    try ha.tline(out, gpa, 1, "},");
}

fn emitRustDecodeArm(out: *std.ArrayList(u8), gpa: std.mem.Allocator, arm: ha.Arm) !void {
    // Single-field ticket ha.arms stay one-line so rustfmt and gen-check agree.
    if (arm.shape == .none) {
        try out.print(gpa, "\t\tHOST_ACTION_{s} => HostAction::{s},\n", .{ arm.name, arm.variant });
        return;
    }
    if (arm.shape == .ticket) {
        try out.append(gpa, '\t');
        try out.append(gpa, '\t');
        try out.print(gpa, "HOST_ACTION_{s} => HostAction::{s} {{ ticket: raw.ticket }},\n", .{ arm.name, arm.variant });
        return;
    }
    try out.append(gpa, '\t');
    try out.append(gpa, '\t');
    try out.print(gpa, "HOST_ACTION_{s} => HostAction::{s} {{\n", .{ arm.name, arm.variant });
    switch (arm.shape) {
        .none => unreachable,
        .session => try ha.tline(out, gpa, 3, "session: raw.session as usize,"),
        .close => {
            try ha.tline(out, gpa, 3, "session: raw.session as usize,");
            try ha.tline(out, gpa, 3, "result: raw.result,");
        },
        .ticket => unreachable,
        .dial_attempt => {
            try ha.tline(out, gpa, 3, "ticket: raw.ticket,");
            try ha.tline(out, gpa, 3, "route_index: raw.route_index,");
        },
        .settle => {
            try ha.tline(out, gpa, 3, "ticket: raw.ticket,");
            try ha.tline(out, gpa, 3, "value: unsafe { arg_from_sys(&raw.value) }?,");
        },
        .fail => {
            try ha.tline(out, gpa, 3, "ticket: raw.ticket,");
            try ha.tline(out, gpa, 3, "result: raw.result,");
            try ha.tline(out, gpa, 3, "message: view(raw.message, raw.message_len),");
        },
    }
    try ha.tline(out, gpa, 2, "},");
}

pub fn generateRacket(gpa: std.mem.Allocator) ![]u8 {
    var out: std.ArrayList(u8) = .empty;
    errdefer out.deinit(gpa);
    try out.appendSlice(gpa,
        \\#lang racket/base
        \\;; GENERATED by `zig build gen-binding-host-action` from src/c_abi/host
        \\;; — do not edit.
        \\;; `zig build gen-binding-host-action-check` (part of `check`) fails when
        \\;; this is stale.
        \\;;
        \\;; Kind constants + decode for the Racket binding. Executor arms stay
        \\;; in `action.rkt`. Does not require `abi-value.rkt` (that would cycle
        \\;; through `constants.rkt`); the caller passes `arg<-c`.
        \\
        \\(require ffi/unsafe
        \\         "constants.rkt"
        \\         "ffi-shared.rkt"
        \\         "ffi-host.rkt"
        \\         "errors.rkt")
        \\
        \\(provide
    );
    inline for (ha.arms) |arm| {
        try out.appendSlice(gpa, "         HOST-ACTION-");
        try ha.writeUpperKebab(&out, gpa, arm.name);
        try out.appendSlice(gpa, "\n");
    }
    try out.appendSlice(gpa,
        \\         host-decode-action!
        \\         host-dispatch-action!)
        \\
        \\;; GlowcapHostAction.kind — mirrors GLOWCAP_HOST_ACTION_* in glowcap_host.h.
        \\
    );
    inline for (ha.arms) |arm| {
        try out.appendSlice(gpa, "(define HOST-ACTION-");
        try ha.writeUpperKebab(&out, gpa, arm.name);
        try out.print(gpa, " {d})\n", .{arm.value});
    }
    try out.appendSlice(gpa,
        \\
        \\;; Decode a filled GlowcapHostAction cstruct into the list form the
        \\;; drain switch matches: `(list 'dial …)`, `(list 'flush …)`, …
        \\;; `arg<-c` is passed by the caller (from `abi-value.rkt`) so this module
        \\;; stays require-acyclic with constants.rkt.
        \\(define (host-decode-action! a arg<-c)
        \\  (define kind (GlowcapHostAction-kind a))
        \\  (define (view->string ptr len) (bytes->string/utf-8 (bytes<-c ptr len) #\uFFFD))
        \\  (cond
        \\
    );
    inline for (ha.arms) |arm| {
        try emitRacketDecodeArm(&out, gpa, arm);
    }
    try out.appendSlice(gpa,
        \\    [else (raise-glowcap 'glowcap ERR-INTERNAL
        \\                         "ABI returned unknown host action kind: ~a" kind)]))
        \\
        \\;; Exhaustive dispatch over a decoded action list. `handlers` is a
        \\;; hash of racket symbols (`'dial`, `'flush`, …) to thunks of
        \\;; `(lambda (a) …)`. A missing arm fails loud — the inventory lives
        \\;; here so `action.rkt` cannot silently drop a new kind.
        \\(define (host-dispatch-action! a handlers)
        \\  (define tag (car a))
        \\  (define fn (hash-ref handlers tag #f))
        \\  (unless fn
        \\    (error 'glowcap "host-dispatch-action!: missing handler for ~a" tag))
        \\  (fn a))
        \\
    );
    return out.toOwnedSlice(gpa);
}

fn emitRacketDecodeArm(out: *std.ArrayList(u8), gpa: std.mem.Allocator, arm: ha.Arm) !void {
    try out.appendSlice(gpa, "    [(= kind HOST-ACTION-");
    try ha.writeUpperKebab(out, gpa, arm.name);
    try out.appendSlice(gpa, ")\n");
    switch (arm.shape) {
        .none => try out.print(gpa,
            \\     (list '{s})]
            \\
        , .{arm.racket}),
        .session => try out.print(gpa,
            \\     (list '{s} (GlowcapHostAction-session a))]
            \\
        , .{arm.racket}),
        .close => try out.print(gpa,
            \\     (list '{s} (GlowcapHostAction-session a) (GlowcapHostAction-result a))]
            \\
        , .{arm.racket}),
        .ticket => try out.print(gpa,
            \\     (list '{s} (GlowcapHostAction-ticket a))]
            \\
        , .{arm.racket}),
        .dial_attempt => try out.print(gpa,
            \\     (list '{s} (GlowcapHostAction-ticket a) (GlowcapHostAction-route-index a))]
            \\
        , .{arm.racket}),
        .settle => try out.print(gpa,
            \\     ;; `arg<-c` copies every byte payload into fresh Racket values, so the
            \\     ;; outcome outlives the popped action's until-next-pop lifetime.
            \\     (list '{s} (GlowcapHostAction-ticket a) (arg<-c (GlowcapHostAction-value a)))]
            \\
        , .{arm.racket}),
        .fail => try out.print(gpa,
            \\     (list '{s} (GlowcapHostAction-ticket a) (GlowcapHostAction-result a)
            \\           (view->string (GlowcapHostAction-message a) (GlowcapHostAction-message-len a)))]
            \\
        , .{arm.racket}),
    }
}
