// Regenerate the still mark from the shader, or prove the committed files
// still agree with it.
//
//     deno run --allow-all tools/gen/mark/main.ts write
//     deno run --allow-all tools/gen/mark/main.ts check
//
// The build reaches this through `zig build gen-mark` and `zig build
// gen-mark-check`. Both need the pinned headless Chromium, because the one
// authority for the mark's shape is the shader that draws it, and running the
// shader means running a browser with a GPU adapter. The render is
// bit-reproducible under SwiftShader, so the check can render fresh and
// compare byte for byte rather than trusting a stored capture.
//
// What it writes, all from one trace:
//
//   site/assets/mark.svg              the artwork, in the night tones
//   site/assets/favicon.svg           the same drawing squared up
//   site/assets/glowcap-icon-256.png  the square raster
//   site/assets/mark-lit.svg          the same mushroom, glowing
//   site/assets/glowcap-lit-256.png   the square raster of that one
//   ui/tokens.css                     four masks, the line drawing, the tones
//   ui/mark.css                       where the drawing sits in its box

import { Capture } from "./capture.ts";
import { coreColour, type LayerName, read, trace } from "./trace.ts";
import { bands } from "./line.ts";
import { light } from "./light.ts";
import {
	faviconSvg,
	litSvg,
	type LitTones,
	markSvg,
	pairsBlock,
	placementBlock,
	tokensBlock,
	type Tones,
} from "./emit.ts";

/** How wide the mark's 24-unit box is drawn. Everything downstream works in
 * box units, so this only sets how finely the contours are sampled. */
const SIZE = 512;

/** The port the page and its bundle are served on. Loopback only, and open
 * just for the run. */
const PORT = 8791;

/** How far a fitted curve may stray from the contour it was cut from, in box
 * units of the 24 the mark fills. The silhouette and the line bands sit near
 * 0.05, and the shade layer near 0.09: it is the one cut through a soft
 * gradient rather than across a flat step, so it is smoothed hardest and its
 * anchors run furthest. The budget is here so a change to the shader that the
 * fit cannot follow fails loudly instead of quietly rounding a corner off. */
const FIT_BUDGET = 0.12;

/** How much brighter than the unlit frame a pixel may be and still count as
 * the body rather than the light. The lamps lift their own cores by about
 * three quarters and their spill falls away from there, so this sits low
 * enough that a tone measured under it is the flesh's own. */
const SPILL = 0.06;

const root = new URL("../../../", import.meta.url).pathname;

const TOKENS_BEGIN = `	/* GENERATED by \`zig build gen-mark\`: five drawings traced off the shader,
	   and the light theme's four measured tones. Change the shader and run
	   that step. Do not edit the values below by hand. */`;
const PLACEMENT_BEGIN = `	/* GENERATED by \`zig build gen-mark\`: the drawing's share of a 24-unit
	   box, grown the way the shader grows it. */`;
const PAIRS_BEGIN = `		/* GENERATED by \`zig build gen-mark\`: the same four tones as pairs. */`;
const END = "/* END GENERATED */";

/** Replace the lines between a begin marker and the next end marker, keeping
 * both markers. A marker that has gone missing is a refusal rather than a
 * silent no-op: the file is generated in part, and a generator that cannot
 * find its own region must not write the file at all. */
function spliced(text: string, begin: string, body: string, path: string): string {
	const at = text.indexOf(begin);
	if (at < 0) {
		throw new Error(`${path}: the generated region's opening marker is gone; restore it or re-derive the file`);
	}
	const from = at + begin.length;
	const to = text.indexOf(END, from);
	if (to < 0) throw new Error(`${path}: the generated region has no closing \`${END}\``);
	const lineStart = text.lastIndexOf("\n", to) + 1;
	return text.slice(0, from) + "\n" + body + "\n" + text.slice(lineStart);
}

type Output = { path: string; bytes: Uint8Array };

const utf8 = new TextEncoder();

async function build(): Promise<Output[]> {
	const capture = await Capture.open(PORT);
	try {
		const night = await capture.frames("dark", ["unlit", "cap", "lit"], SIZE);
		const day = await capture.frames("light", ["unlit"], SIZE);
		const mark = read(night.frames[0], night.view);
		const cap = read(night.frames[1], night.view);
		const glowing = read(night.frames[2], night.view);
		const lit = read(day.frames[0], day.view);

		const drawing = trace(mark);
		const line = bands(mark, cap);
		const worst = Math.max(line.maxDev, ...drawing.layers.map((layer) => layer.maxDev));
		console.log(`fit, in box units of the 24 the mark fills (budget ${FIT_BUDGET})`);
		for (const layer of drawing.layers) {
			console.log(
				`  ${layer.name.padEnd(11)} ${String(layer.loops).padStart(2)} loop(s)` +
					`  ${String(layer.anchors).padStart(3)} anchors  worst ${layer.maxDev.toFixed(3)}  ${layer.fill}`,
			);
		}
		console.log(`  ${"line bands".padEnd(11)}                        worst ${line.maxDev.toFixed(3)}`);
		if (worst > FIT_BUDGET) {
			throw new Error(
				`the fit strays ${worst.toFixed(3)} box units from the render, past the ${FIT_BUDGET} budget; ` +
					"the shader's shape has moved somewhere the current anchor spacing cannot follow",
			);
		}

		// One geometry, two sets of tones. Both renders are the same pose on
		// the same grid, so a pixel belongs to the same layer in both:
		// classify with the render the geometry was cut from, then read the
		// other render's color over that class.
		const names: LayerName[] = ["silhouette", "flesh", "shade", "windows"];
		const dayTones: Tones = {};
		for (const name of names) dayTones[name] = coreColour(mark, lit, name);
		console.log("tones, measured off the render's core pixels");
		for (const name of names) {
			const dark = drawing.layers.find((layer) => layer.name === name)!.fill;
			console.log(`  ${name.padEnd(11)} light ${dayTones[name]}   dark ${dark}`);
		}

		// The lit reading. The lamps are found by asking the lit render what it
		// added to the unlit one, and the body's own tones are measured with
		// everything the light touched left out, so the flesh under the brim
		// does not come back teal.
		const lamps = light(glowing, mark);
		const touched = (i: number) => lamps.lift[i] > SPILL;
		const litTones: LitTones = {
			rim: coreColour(mark, glowing, "silhouette", touched),
			flesh: coreColour(mark, glowing, "flesh", touched),
			shade: coreColour(mark, glowing, "shade", touched),
		};
		console.log(
			`light: ${lamps.lamps} lamps, worst fit ${lamps.maxDev.toFixed(3)}, emitting ${lamps.core}`,
		);
		console.log(`  body under it   rim ${litTones.rim}   flesh ${litTones.flesh}   shade ${litTones.shade}`);
		if (lamps.maxDev > FIT_BUDGET) {
			throw new Error(
				`the lamps' fit strays ${lamps.maxDev.toFixed(3)} box units, past the ${FIT_BUDGET} budget`,
			);
		}

		const favicon = faviconSvg(drawing);
		const icon = await capture.rasterise(favicon, 256);
		const glow = litSvg(drawing, lamps, litTones);
		const glowIcon = await capture.rasterise(glow, 256);

		const tokensPath = "ui/tokens.css";
		let tokens = await Deno.readTextFile(root + tokensPath);
		tokens = spliced(tokens, TOKENS_BEGIN, tokensBlock(drawing, line, dayTones), tokensPath);
		tokens = spliced(tokens, PAIRS_BEGIN, pairsBlock(drawing, dayTones), tokensPath);

		const cssPath = "ui/mark.css";
		const css = spliced(
			await Deno.readTextFile(root + cssPath),
			PLACEMENT_BEGIN,
			placementBlock(drawing),
			cssPath,
		);

		return [
			{ path: "site/assets/mark.svg", bytes: utf8.encode(markSvg(drawing)) },
			{ path: "site/assets/favicon.svg", bytes: utf8.encode(favicon) },
			{ path: "site/assets/glowcap-icon-256.png", bytes: icon },
			{ path: "site/assets/mark-lit.svg", bytes: utf8.encode(glow) },
			{ path: "site/assets/glowcap-lit-256.png", bytes: glowIcon },
			{ path: tokensPath, bytes: utf8.encode(tokens) },
			{ path: cssPath, bytes: utf8.encode(css) },
		];
	} finally {
		await capture.close();
	}
}

const same = (a: Uint8Array, b: Uint8Array) => a.length === b.length && a.every((byte, i) => byte === b[i]);

async function main(): Promise<number> {
	const mode = Deno.args[0];
	if (mode !== "write" && mode !== "check") {
		console.error("usage: main.ts write|check");
		return 2;
	}
	const outputs = await build();
	if (mode === "write") {
		for (const out of outputs) {
			await Deno.writeFile(root + out.path, out.bytes);
			console.log("wrote", out.path);
		}
		return 0;
	}
	const stale: string[] = [];
	for (const out of outputs) {
		// A file that is not there is stale, and any other refusal to read it
		// belongs to the caller: reporting it as staleness would send someone
		// to regenerate an asset over a permission or an I/O fault.
		let had: Uint8Array | null = null;
		try {
			had = await Deno.readFile(root + out.path);
		} catch (error) {
			if (!(error instanceof Deno.errors.NotFound)) throw error;
		}
		if (had == null || !same(had, out.bytes)) stale.push(out.path);
	}
	if (stale.length === 0) {
		console.log("every generated mark asset matches a fresh trace of the shader");
		return 0;
	}
	console.error("\nstale, and no longer what the shader draws:");
	for (const path of stale) console.error("  " + path);
	console.error("\nrun `zig build gen-mark` and commit what it writes.");
	return 1;
}

Deno.exit(await main());
