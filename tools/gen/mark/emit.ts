// One trace, several framings. This module turns the fitted paths and the
// measured tones into the exact text and bytes each place needs, and nothing
// here decides geometry: it only frames what trace.ts and line.ts found.
//
// The four generated surfaces are the artwork, the favicon cut from it, the
// square raster the places that take no SVG read, and the mark's block in
// ui/tokens.css. A fifth is the placement in ui/mark.css, which is arithmetic
// on the frame rather than a picture, and drifts the moment the frame moves.

import type { View } from "./capture.ts";
import type { Trace } from "./trace.ts";
import type { Bands } from "./line.ts";

/** How much larger the mushroom stands than the box it is given. The live
 * shader mark grows by this about the box's center (GROW in
 * apps/rooms/web/ui/mark/live.ts), so anything that has to sit where the
 * shader sits grows the same way. */
const GROW = 1.2;

/** The tones one theme paints the four layers in, keyed by layer. */
export type Tones = Record<string, string>;

const frame = (box: View) => `${box.x} ${box.y} ${box.w} ${box.h}`;

const paths = (trace: Trace) =>
	trace.layers.map((layer) => `\t<path fill="${layer.fill}" fill-rule="evenodd" d="${layer.d}"/>`).join("\n");

/** The artwork. This is the standard still asset, and everything else that
 * needs the mushroom as a picture is cut from the same trace. */
export function markSvg(trace: Trace): string {
	const box = trace.viewBox;
	return `<!-- GENERATED by \`zig build gen-mark\`. Do not edit by hand.

     The glowcap mark, as artwork. This file is the standard still asset:
     anything else that needs the mushroom as a picture is cut from it.

     It was traced from the shader mark, whose geometry lives in
     apps/rooms/web/ui/mark/field.ts, in its settled pose with the lamps
     at zero. The render is a cel drawing rather than a shaded one, so these
     four flat tones are its own structure and not a reduction of it. The
     tones are measured from the render's core pixels rather than picked by
     eye, and the coordinates are the shader's own box units.

     Regenerated from that same trace, in the same run: favicon.svg, the
     square glowcap-icon-256.png the touch icon and the social card read,
     mark-lit.svg and its own square raster for the README, the mark's masks
     and line drawing in ui/tokens.css, and the placement in ui/mark.css. The
     tones here are the ones the shader paints at night; the tokens carry a
     second set measured off the same mushroom on cream, so they are four
     masks and four colors rather than a copy of this file. Change the
     shader, then run \`zig build gen-mark\`. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${frame(box)}" width="${box.w.toFixed(1)}" height="${
		box.h.toFixed(1)
	}" role="img" aria-label="The glowcap mark">
${paths(trace)}
</svg>
`;
}

/** The drawing squared up with `pad` units of air on its long side. A square
 * is what a tab and a README both hand the mark, and a mushroom that touches
 * the edges of one reads as a smudge. */
function squared(trace: Trace, pad: number): View {
	const side = Math.max(trace.viewBox.w, trace.viewBox.h) + pad * 2;
	return {
		x: Number((trace.viewBox.x - (side - trace.viewBox.w) / 2).toFixed(2)),
		y: Number((trace.viewBox.y - (side - trace.viewBox.h) / 2).toFixed(2)),
		w: Number(side.toFixed(2)),
		h: Number(side.toFixed(2)),
	};
}

export function faviconSvg(trace: Trace): string {
	const box = squared(trace, 1.4);
	return `<!-- GENERATED by \`zig build gen-mark\`. Do not edit by hand.
     The glowcap favicon: mark.svg squared up, with air for the tab. Traced
     from the shader mark in its settled, unlit pose. Coordinates are the
     shader's own box units, and the tones are measured from the render. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${
		frame(box)
	}" width="64" height="64" role="img" aria-label="The glowcap mark">
${paths(trace)}
</svg>
`;
}

/** How the still mark stands in for a light it cannot have. An SVG has no
 * emission and no bloom pass, so the glow is three passes of the same lamp
 * geometry: a wide soft wash for the light that spreads through the cap, a
 * tight bright one for the bloom right at each lamp, and the lamp itself on
 * top. The wash and the tight pass are clipped to the mushroom, which is what
 * makes this an inner glow rather than a halo. Only a low unclipped pass
 * carries the little that reaches past the brim. The wide radius is the
 * shader's own halo, a twentieth of the frame's height, so the light spreads
 * the same distance in both readings. */
const GLOW = {
	wash: 3,
	washOpacity: 0.55,
	bloom: 0.5,
	bloomOpacity: 0.8,
	spillOpacity: 0.5,
	/** The rim's own bloom, the one thing here that leaves the mushroom. It is
	 * the warm edge the shader puts around the whole silhouette. */
	rim: 0.7,
	rimOpacity: 0.42,
};

/** The body's tones under its own light, measured with the lamps and their
 * spill left out, so each is the flesh's color rather than the light's. */
export type LitTones = { rim: string; flesh: string; shade: string };

/** The lit still mark: the same mushroom, glowing. It is the README's mark,
 * and the one reading of the still mark that carries light at all. */
export function litSvg(trace: Trace, lamps: { d: string; core: string }, tones: LitTones): string {
	const box = squared(trace, 3.2);
	const by = (name: string) => trace.layers.find((layer) => layer.name === name)!.d;
	const blur = (id: string, deviation: number) =>
		`<filter id="${id}" x="-60%" y="-60%" width="220%" height="220%">` +
		`<feGaussianBlur stdDeviation="${deviation}"/></filter>`;
	const lamp = (opacity: number, filter: string) =>
		`\t<path fill="${lamps.core}" fill-rule="evenodd" opacity="${opacity}" filter="url(#${filter})" d="${lamps.d}"/>`;
	return `<!-- GENERATED by \`zig build gen-mark\`. Do not edit by hand.
     The glowcap mark, lit. Same mushroom and same trace as mark.svg, in the
     pose the shader settles into with its lamps on: the windows and the line
     under the brim are where the light is, found by asking the lit render
     what it added to the unlit one, and its color is measured there. The
     glow is Gaussian blurs of that same geometry, clipped to the mushroom, so
     it reads as light inside a thing rather than a halo around one. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${
		frame(box)
	}" width="256" height="256" role="img" aria-label="The glowcap mark, lit">
	<defs>
		${blur("mark-wash", GLOW.wash)}
		${blur("mark-bloom", GLOW.bloom)}
		${blur("mark-rim", GLOW.rim)}
		<clipPath id="mark-body"><path d="${by("silhouette")}"/></clipPath>
	</defs>
	<path fill="${tones.rim}" opacity="${GLOW.rimOpacity}" filter="url(#mark-rim)" d="${by("silhouette")}"/>
	<path fill="${tones.rim}" fill-rule="evenodd" d="${by("silhouette")}"/>
	<path fill="${tones.flesh}" fill-rule="evenodd" d="${by("flesh")}"/>
	<path fill="${tones.shade}" fill-rule="evenodd" d="${by("shade")}"/>
	<g clip-path="url(#mark-body)">
	${lamp(GLOW.washOpacity, "mark-wash")}
	${lamp(GLOW.bloomOpacity, "mark-bloom")}
	</g>
${lamp(GLOW.spillOpacity, "mark-bloom")}
	<path fill="${lamps.core}" fill-rule="evenodd" d="${lamps.d}"/>
</svg>
`;
}

// The mask values are encoded the way the neighboring tokens in tokens.css
// are: the angle brackets, the attribute quotes, and the hashes, and nothing
// else, so the value stays something a reader can follow.
const encode = (svg: string) => svg.replace(/</g, "%3C").replace(/>/g, "%3E").replace(/"/g, "%27").replace(/#/g, "%23");
const uri = (svg: string) => `url("data:image/svg+xml,${encode(svg)}")`;

/** The four masks and the one line drawing, plus the light theme's tones. This
 * is the body of the generated region in ui/tokens.css. */
export function tokensBlock(trace: Trace, bands: Bands, light: Tones): string {
	const box = frame(trace.viewBox);
	const mask = (d: string) =>
		uri(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${box}"><path fill-rule="evenodd" d="${d}"/></svg>`);

	// The line drawing keeps a little more air than the filled one, because a
	// band's outer edge is the silhouette itself and a frame cut to the
	// silhouette clips it.
	const bleed = 0.15;
	const lineBox = frame({
		x: Number((trace.viewBox.x - bleed).toFixed(2)),
		y: Number((trace.viewBox.y - bleed).toFixed(2)),
		w: Number((trace.viewBox.w + bleed * 2).toFixed(2)),
		h: Number((trace.viewBox.h + bleed * 2).toFixed(2)),
	});
	const windows = trace.layers.find((layer) => layer.name === "windows")!.d;
	const line = uri(
		`<svg xmlns="http://www.w3.org/2000/svg" viewBox="${lineBox}">` +
			`<path fill="#000" fill-rule="evenodd" d="${bands.full}"/>` +
			`<path fill="#000" fill-rule="evenodd" d="${bands.cap}"/>` +
			`<path fill="#000" fill-rule="evenodd" d="${windows}"/>` +
			`</svg>`,
	);

	return [
		`\t--mark-silhouette: ${mask(trace.layers[0].d)};`,
		`\t--mark-flesh: ${mask(trace.layers[1].d)};`,
		`\t--mark-shade: ${mask(trace.layers[2].d)};`,
		`\t--mark-windows: ${mask(trace.layers[3].d)};`,
		`\t--mark-line: ${line};`,
		``,
		`\t--mark-rim: ${light.silhouette};`,
		`\t--mark-body: ${light.flesh};`,
		`\t--mark-shadow: ${light.shade};`,
		`\t--mark-window: ${light.windows};`,
	].join("\n");
}

/** The same four tones as theme pairs, for the guarded block where every other
 * two-valued token in the file is written that way. */
export function pairsBlock(trace: Trace, light: Tones): string {
	const dark = (name: string) => trace.layers.find((layer) => layer.name === name)!.fill;
	return [
		`\t\t--mark-rim: light-dark(${light.silhouette}, ${dark("silhouette")});`,
		`\t\t--mark-body: light-dark(${light.flesh}, ${dark("flesh")});`,
		`\t\t--mark-shadow: light-dark(${light.shade}, ${dark("shade")});`,
		`\t\t--mark-window: light-dark(${light.windows}, ${dark("windows")});`,
	].join("\n");
}

/** Where the drawing sits inside a 24-unit box once the shader's growth is
 * applied, as percentages of that box. The lockup places its pieces with
 * these, so the still mark and the shader mark occupy the same pixels whenever
 * one replaces the other. */
export function placementBlock(trace: Trace): string {
	const grown = (v: number) => 12 + (v - 12) * GROW;
	const pct = (v: number) => {
		const n = Number(((v / 24) * 100).toFixed(4));
		return `${n}%`;
	};
	return [
		`\tleft: ${pct(grown(trace.viewBox.x))};`,
		`\ttop: ${pct(grown(trace.viewBox.y))};`,
		`\twidth: ${pct(trace.viewBox.w * GROW)};`,
		`\theight: ${pct(trace.viewBox.h * GROW)};`,
	].join("\n");
}
