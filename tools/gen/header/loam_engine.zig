//! The one emitter for the Loam engine companion headers (ADR-0061). Every
//! companion exports the same symbol family with the same crossing contracts,
//! so that prose is written here once. An engine states only what is its own:
//! how `open` finds or makes a store, what `release` ends, whether engine calls
//! are serialized, and how `collect` names the storage owner.
const std = @import("std");
const header_emit = @import("header_emit.zig");

/// What one engine companion says about itself.
pub const Engine = struct {
    /// The Zig module the header reflects, such as `c_abi_loam_lmdb`.
    module_name: []const u8,
    /// The lower-case infix of its symbol family: `glowcap_loam_<symbol>_*`.
    symbol: []const u8,
    /// The upper-case infix of its macros: `GLOWCAP_LOAM_<macro>_H`.
    macro: []const u8,
    /// The opaque storage owner type the header declares.
    typedef: []const u8,
    /// How `collect` names the storage owner.
    owner: []const u8,
    /// The parameter names of `open`, in declaration order.
    open_params: []const []const u8,
    /// How `open` finds or makes a store and what each `create` value does.
    open_doc: []const u8,
    /// What `release` closes once the owner is quiescent.
    release_doc: []const u8,
    /// A sentence `work_run` adds about how engine calls are scheduled, or
    /// empty when the engine needs none.
    work_run_note: []const u8 = "",
};

/// The consumed-with-failure half of every engine's release contract.
const release_consumed_doc = " Once the Store is released the handle is consumed. A failing engine close still frees it and preserves the engine's failure code in the release result. Never retry a consumed result.";

/// The header generator for `engine`, reflecting `c_module`.
pub fn Header(comptime engine: Engine, comptime c_module: type) type {
    return struct {
        pub const step_name = "gen-header-loam-" ++ engine.symbol;
        pub const header_path = "include/glowcap_loam_" ++ engine.symbol ++ ".h";
        const prefix = "glowcap_loam_" ++ engine.symbol ++ "_";
        const names = [_][]const u8{
            prefix ++ "clear_last_error",
            prefix ++ "recover",
            prefix ++ "open",
            prefix ++ "release",
            prefix ++ "work_run",
            prefix ++ "restore",
            prefix ++ "commit",
            prefix ++ "collect",
            prefix ++ "last_error",
            prefix ++ "archive_fingerprint",
        };
        const Spec = struct {
            pub const c = c_module;
            pub const emitted_fns = &names;
            pub fn special(comptime _: type) ?[]const u8 {
                return null;
            }
        };
        const E = header_emit.Emit(Spec);
        comptime {
            E.guardFns(engine.module_name, prefix);
        }

        pub fn generate(gpa: std.mem.Allocator) ![]u8 {
            var b: header_emit.Buf = .empty;
            errdefer b.deinit(gpa);
            try b.appendSlice(gpa, "/* GENERATED by zig build " ++ step_name ++ ". Do not edit. */\n" ++
                "#ifndef GLOWCAP_LOAM_" ++ engine.macro ++ "_H\n" ++
                "#define GLOWCAP_LOAM_" ++ engine.macro ++ "_H\n" ++
                "#include \"glowcap_loam.h\"\n" ++
                "#ifdef __cplusplus\n" ++
                "extern \"C\" {\n" ++
                "#endif\n");
            try b.appendSlice(gpa, "typedef struct " ++ engine.typedef ++ " " ++ engine.typedef ++ ";\n");
            try E.emitConst(&b, gpa, "GLOWCAP_LOAM_" ++ engine.macro ++ "_ARCHIVE_FINGERPRINT");
            try E.emitFn(&b, gpa, prefix ++ "open", engine.open_params, engine.open_doc);
            try E.emitFn(&b, gpa, prefix ++ "release", &.{"raw"}, engine.release_doc ++ release_consumed_doc);
            try E.emitFn(&b, gpa, prefix ++ "work_run", &.{ "raw", "work_handle" }, "Execute one storage effect on the storage executor without touching Host state." ++ engine.work_run_note ++ " Join before portable work_complete or work_release. Repeated execution, foreign Store work, and completed work refuse. Operational results remain on the work handle.");
            try E.emitFn(&b, gpa, prefix ++ "restore", &.{ "raw", "attachment", "object", "out_ref" }, "Privileged restoration reads and validates a persisted rooted endpoint, then returns one held capability occurrence on the supplied Host attachment. A record that is not resident returns GLOWCAP_LOAM_ERR_STALE_COMPLETION while one of the Store's commits is in flight. Retry after that work completes. Serialized object names never invoke. Release the occurrence through the existing Host reference release.");
            try E.emitFn(&b, gpa, prefix ++ "commit", &.{"raw"}, "Submit privileged unattached staging through the same Store write/install contract. Committed output installs once; unchanged aborts and returns UNCHANGED with its storage cause in last_error; an unknown outcome leaves recovery required. Execute outside Host turns.");
            try E.emitFn(&b, gpa, prefix ++ "collect", &.{ "raw", "work_limit" }, "Run one bounded collection batch of work_limit steps on the " ++ engine.owner ++ " and commit it like commit. Returns OK when the batch commits and UNCHANGED when it is refused or aborted, with the cause in last_error. Poll glowcap_loam_store_collecting on the paired Store for whether a cycle remains.");
            try E.emitFn(&b, gpa, prefix ++ "last_error", &.{ "buf", "len" }, "Copy the immediate storage companion error into caller storage. Returns bytes copied.");
            try E.emitFn(&b, gpa, prefix ++ "archive_fingerprint", &.{}, "Return this archive's reflected callable and layout fingerprint before the first ordinary call.");
            try E.emitFn(&b, gpa, prefix ++ "recover", &.{"raw"}, "Resolve an indeterminate unattached creation after its commit worker has terminated. Committed installs once; proven absence returns UNCHANGED and frees staging. No receipt is inspected while a worker may still commit.");
            try E.emitFn(&b, gpa, prefix ++ "clear_last_error", &.{}, "Clear this archive's thread-local diagnostic slot.");
            try E.assertAllEmitted(&b, step_name);
            try b.appendSlice(gpa, "#ifdef __cplusplus\n}\n#endif\n#endif\n");
            return b.toOwnedSlice(gpa);
        }
    };
}
