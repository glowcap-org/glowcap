// Generate Rust layout expectations from the actual wasm32 C ABI descriptor.
// The native generator supplies names and field order from archive contracts;
// the linked target supplies sizes, offsets and callable fingerprints.
import { fnv1a32 } from "../../bindings/ts/runtime/internal/layout.ts";

type Row = { prefix: string; stem: string; fields: string[] };
type Exports = {
	memory: WebAssembly.Memory;
	glowcap_wasm_alloc(length: number): number;
	glowcap_wasm_free(pointer: number, length: number): void;
	glowcap_wasm_loam_abi_layout(pointer: number, capacity: number): number;
	glowcap_wasm_loam_archive_fingerprint(): bigint;
	glowcap_wasm_abi_layout(pointer: number, capacity: number): number;
	glowcap_ocapn_archive_fingerprint(): bigint;
	glowcap_host_archive_fingerprint(): bigint;
};
const rows: Row[] = JSON.parse(
	await Deno.readTextFile(new URL("../../bindings/rust/wasm-layouts.json", import.meta.url)),
);
const source = new URL("../../zig-out/wasm/glowcap_host.wasm", import.meta.url);
const { instance } = await WebAssembly.instantiate(await Deno.readFile(source), {
	env: { glowcap_behavior_trampoline: () => 0, glowcap_hosted_free_trampoline: () => {} },
});
const ex = instance.exports as unknown as Exports;
const layouts = new Map<number, { size: number; offsets: number[] }>();
for (const descriptor of [ex.glowcap_wasm_abi_layout, ex.glowcap_wasm_loam_abi_layout]) {
	const count = descriptor(0, 0);
	if (!Number.isSafeInteger(count) || count <= 0 || count > 65536) throw new Error("invalid Wasm descriptor size");
	const pointer = ex.glowcap_wasm_alloc(count * 4);
	if (!pointer) throw new Error("cannot allocate the Wasm layout descriptor");
	try {
		if (descriptor(pointer, count) !== count) throw new Error("Wasm descriptor size changed");
		const data = new DataView(ex.memory.buffer, pointer, count * 4);
		let cursor = 0;
		const word = () => data.getUint32(cursor++ * 4, true);
		while (cursor < count) {
			const hash = word();
			const size = word();
			const fields = word();
			if (size === 0 || fields > count - cursor || layouts.has(hash)) throw new Error("invalid Wasm layout row");
			const offsets = Array.from({ length: fields }, word);
			if (offsets.some((offset) => offset >= size)) throw new Error("Wasm field exceeds its struct");
			layouts.set(hash, { size, offsets });
		}
	} finally {
		ex.glowcap_wasm_free(pointer, count * 4);
	}
}
let output = `//! GENERATED by zig build gen-rust-wasm-layouts; do not edit.
//! Actual wasm32 C ABI layouts and fingerprints, paired with archive-owned names.
#![allow(dead_code)]

`;
const stems = new Set<string>();
for (const row of rows) {
	if (stems.has(row.stem)) throw new Error(`duplicate Rust layout ${row.stem}`);
	stems.add(row.stem);
	const layout = layouts.get(fnv1a32(row.prefix));
	if (!layout || layout.offsets.length !== row.fields.length) {
		throw new Error(`Wasm layout shape changed: ${row.prefix}`);
	}
	output += `pub const ${row.stem}_SIZE: usize = ${layout.size};\n`;
	row.fields.forEach((field, index) =>
		output += `pub const ${row.stem}_${field}_OFF: usize = ${layout.offsets[index]};\n`
	);
}
for (
	const [name, fingerprint] of [
		["OCAPN", ex.glowcap_ocapn_archive_fingerprint()],
		["HOST", ex.glowcap_host_archive_fingerprint()],
		["LOAM", ex.glowcap_wasm_loam_archive_fingerprint()],
	] as const
) {
	output += `pub const ${name}_ARCHIVE_FINGERPRINT: u64 = ${BigInt.asUintN(64, fingerprint)};\n`;
}
const destination = new URL("../../bindings/rust/src/sys/wasm_layouts_gen.rs", import.meta.url);
if (Deno.args.length === 1 && Deno.args[0] === "--check") {
	if (await Deno.readTextFile(destination) !== output) {
		throw new Error("Rust Wasm layouts are stale; run zig build gen-rust-wasm-layouts");
	}
} else if (Deno.args.length === 0) {
	await Deno.writeTextFile(destination, output);
} else {
	throw new Error("rust_layouts.ts accepts only --check");
}
