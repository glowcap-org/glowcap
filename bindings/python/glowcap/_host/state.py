"""Type-only contract shared by the private Host mixins."""

from __future__ import annotations

import asyncio
import ctypes
from typing import (
    Any,
    Awaitable,
    Callable,
    Coroutine,
    Optional,
    Protocol,
    TYPE_CHECKING,
)

from .._gc import HostGc
from .._errors import GlowcapError
from .finalizer import _HostFinalizerState
from .vows import VowTable

if TYPE_CHECKING:
    from .._context import Context
    from .._loop import DriverLoop
    from .._session import Session
    from .._transport import Connector
    from .._trampoline import _BehaviorEntry
    from .._value import Ref
    from .._lifecycle import PendingWork


class HostState(Protocol):
    _driver_loop: Optional[DriverLoop]
    _raw: Optional[ctypes.c_void_p]
    _release_started: bool
    _finalizer: Any
    _finalizer_state: Optional[_HostFinalizerState]
    _context: Optional[Context]
    _diagnostic_id: int
    _loop: Optional[asyncio.AbstractEventLoop]
    _trace_refresh_pending: bool
    _seed: bytes
    _gc: HostGc
    _sessions: dict[int, Session]
    _vows: VowTable
    _behavior_tasks: set[asyncio.Task[Any]]
    _terminal_failures: list[BaseException]
    _terminal_failure_count: int
    _action_drains: set[asyncio.Task[Any]]
    _close_activity: asyncio.Event
    _dial_tasks: dict[tuple[int, int], asyncio.Task[Any]]
    _release_task: Optional[asyncio.Task[Any]]
    _giftables: dict[str, int]
    _hosted: dict[int, int]
    _displaced_giftables: list[int]
    _behavior_entries: dict[int, _BehaviorEntry]
    _connectors: dict[str, Connector]

    @property
    def raw(self) -> ctypes.c_void_p: ...

    @property
    def raw_or_none(self) -> Optional[ctypes.c_void_p]: ...

    @property
    def driver_loop(self) -> Optional[DriverLoop]: ...

    @property
    def gc(self) -> HostGc: ...

    @property
    def terminal_failures(self) -> tuple[BaseException, ...]: ...

    def _assert_owner(self) -> None: ...
    def _on_owner_thread(self) -> bool: ...
    def _on_owner_loop(self) -> bool: ...
    def _schedule_cleanup(self, run: Callable[[], None]) -> bool: ...
    def schedule_on_loop(self, run: Callable[[], None]) -> bool: ...
    def signal_close_activity(self) -> None: ...
    def arm_close_activity(self) -> None: ...
    def schedule_kick(self) -> None: ...
    def kick_actions(self) -> Awaitable[None]: ...
    def _join_action_drains(self) -> Awaitable[None]: ...
    def _join_behavior_tasks(self) -> Awaitable[None]: ...
    def _own_action_drain(self, task: asyncio.Task[Any]) -> None: ...
    def _own_behavior_task(self, task: asyncio.Task[Any]) -> None: ...
    def _record_terminal_failure(self, error: BaseException) -> None: ...
    def _driver_failed(self, error: GlowcapError) -> None: ...
    def _settle_resolver(self, resolver: int, value: Any) -> None: ...
    def _break_resolver(self, resolver: int, message: str) -> None: ...
    def park_release(self, release: Callable[[], None]) -> None: ...
    def drain_parked_releases(self) -> None: ...
    def vow_minted(self, vow: int, *, track_gc: bool = False) -> None: ...
    def await_vow(self, vow: int) -> asyncio.Future[Any]: ...
    def settle_vow(self, vow: int, ok: bool, payload: Any) -> None: ...
    def abandon_vow(self, vow: int) -> None: ...
    def get_session(self, ptr: int) -> Optional[Session]: ...
    def start_dial_task(
        self,
        ticket: int,
        route_index: int,
        run: Callable[[], Coroutine[Any, Any, None]],
    ) -> None: ...
    def cancel_dial_task(self, ticket: int, route_index: int) -> Awaitable[None]: ...
    def designator(self) -> str: ...
    def register_session(self, ptr: int, session: Session) -> None: ...
    def unregister_session(self, ptr: int) -> None: ...
    def exporter_for(self, ref: Ref) -> Optional[Session]: ...
    def _register_behavior(self, entry: _BehaviorEntry) -> int: ...
    def _unregister_behavior(self, ctx: int) -> None: ...
    def close(
        self,
        pending: PendingWork = ...,
        *,
        grace: object = ...,
    ) -> Awaitable[None]: ...


if TYPE_CHECKING:
    HostMixinBase = HostState
else:

    class HostMixinBase:
        pass
