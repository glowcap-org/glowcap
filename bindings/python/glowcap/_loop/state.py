"""Type-only contract shared by the private DriverLoop mixins."""

from __future__ import annotations

import asyncio
import ctypes
from typing import TYPE_CHECKING, Any, Protocol

from .._errors import GlowcapError
from .._listener import ListenerLike, ListenerOwner
from .._locator import Locator

if TYPE_CHECKING:
    from .._driver.release import _DriverReleaseOwner
    from .._driver_event import LoopEvent
    from .._ffi_host import _CloseOptions
    from .._host import Host


class DriverLoopState(Protocol):
    _h: ctypes.c_void_p
    _host: ctypes.c_void_p
    _aio: asyncio.AbstractEventLoop | None
    _fd: int | None
    _stepping: bool
    _pending_dials: dict[int, asyncio.Future[int]]
    _progress_timer: asyncio.TimerHandle | None
    _completions: dict[int, asyncio.Future[bool]]
    _accepts: dict[int, asyncio.Queue[int | object]]
    _listeners: dict[int, ListenerOwner]
    _listener_waiters: dict[int, asyncio.Future[None]]
    _closing_listeners: set[int]
    _listener_close_waiters: dict[int, asyncio.Future[None]]
    _unclaimed_sessions: dict[int, tuple[bool, GlowcapError | None]]
    _session_closes: dict[int, asyncio.Future[None]]
    _wrapper: Host | None
    _seed_material: bytes | None
    _codec: str
    _released: bool
    _release_attempted: bool
    _terminal_failure: GlowcapError | None
    _terminal_failures: list[BaseException]
    _terminal_failure_count: int
    _closing: bool
    _close_task: asyncio.Task[None] | None
    _close_error: BaseException | None
    _started: bool
    _closed_event: asyncio.Event
    _loop_activity: asyncio.Event
    _session_close_tasks: set[asyncio.Task[None]]
    _release_owner: _DriverReleaseOwner

    @property
    def host(self) -> ctypes.c_void_p: ...

    @property
    def terminal_failures(self) -> tuple[BaseException, ...]: ...

    def _started_loop(self) -> asyncio.AbstractEventLoop: ...
    def schedule_step(self) -> None: ...
    def _step_background(self) -> None: ...
    def _fail_background(self, error: BaseException) -> None: ...
    def step_now(self) -> None: ...
    def step(self, timeout_ms: int) -> None: ...
    def _step_ffi(self, timeout_ms: int) -> bool: ...
    def _pop_events(self) -> list[LoopEvent]: ...
    def _dispatch_many(self, events: list[LoopEvent]) -> None: ...
    def _dispatch(self, event: LoopEvent) -> None: ...
    def _ffi_session_release(self, ptr: ctypes.c_void_p) -> None: ...
    def _signal_loop_activity(self) -> None: ...
    def _arm_loop_activity(self) -> None: ...
    def _step_wait_ms(self) -> int: ...
    def _wait_step_wake(self) -> Any: ...
    def _finish_listener_close(self, listener: int, failure: GlowcapError | None = None) -> None: ...
    def _release_unclaimed(self, listener: int) -> None: ...
    def _listener_id(self, listener: ListenerLike) -> int: ...
    def _finish_session_close(self, session: int) -> None: ...
    def _drive_session_close(self, session: int, future: asyncio.Future[None]) -> Any: ...
    def _retire_ffi_release(self, release_error: BaseException | None) -> None: ...
    def _record_terminal_failure(self, error: BaseException) -> None: ...
    def connect_session(self, locator: Locator | str) -> Any: ...
    def adopt_session(self, ptr: int) -> Any: ...
    def wrapper_host(self) -> Host: ...
    def session_release(self, session: int) -> None: ...
    def claim_reference_exporter(self, reference: Any) -> int | None: ...
    def close_session(self, session: ctypes.c_void_p, options: _CloseOptions) -> Any: ...
    def dial(self, locator: Locator | str) -> Any: ...
    def _begin_dial(self, locator: Locator, future: asyncio.Future[int]) -> None: ...
    def _rearm_progress_timer(self) -> None: ...
    def accept(self, listener: int) -> Any: ...
    def try_accept(self, listener: ListenerLike) -> int | None: ...
    def listen(self, transport: str | bytes, designator: str | bytes) -> ListenerOwner: ...
    def listener_locator(self, listener: ListenerLike) -> Locator: ...
    def close_listener(self, listener: ListenerLike) -> None: ...
    def wait_listener_closed(self, listener: ListenerLike) -> Any: ...
    def _advance_closing_listeners(self) -> None: ...
    def wait_listener(self, listener: ListenerLike) -> Any: ...
    def completion(self, vow: int) -> asyncio.Future[bool]: ...
    def accept_session(self, listener: ListenerLike) -> Any: ...
    def request_close(self) -> None: ...
    def close(self, options: _CloseOptions | None = None) -> None: ...
    def wait_closed(self) -> Any: ...
    def _adopt_host_finalizer_state(self, state: Any) -> None: ...
    def _install_provider(self, prepare: Any) -> None: ...
    def _retain_until_teardown(self, value: object) -> None: ...
    def _has_transport(self, transport: str | bytes) -> bool: ...


if TYPE_CHECKING:
    DriverLoopMixinBase = DriverLoopState
else:

    class DriverLoopMixinBase:
        pass
