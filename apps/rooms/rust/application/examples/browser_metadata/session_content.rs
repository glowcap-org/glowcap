//! Read-only metadata for the session content contract.
use super::write_property;
use rooms_application::{
	content::{
		permissions::Permission,
		session::{self, custody, local, records, requirements, workspace},
	},
	session::{
		checkpoint::commands,
		command::{Effect, Route},
		verbs::Method,
	},
};
use serde_json::json;
use std::fmt::Write;
use std::{
	io::Write as _,
	process::{Command, Stdio},
};

fn canonical_typescript(text: String) -> Result<String, String> {
	// Formatting participates in generation and comparison. Manual formatting
	// of the generated mirror must not make --check disagree with its owner.
	let mut formatter = Command::new("deno")
		.args(["fmt", "--ext=ts", "-"])
		.current_dir(concat!(env!("CARGO_MANIFEST_DIR"), "/../../../.."))
		.stdin(Stdio::piped())
		.stdout(Stdio::piped())
		.stderr(Stdio::piped())
		.spawn()
		.map_err(|e| format!("starting the pinned Deno formatter failed: {e}"))?;
	formatter
		.stdin
		.take()
		.ok_or("the Deno formatter has no standard input")?
		.write_all(text.as_bytes())
		.map_err(|e| format!("writing to the Deno formatter failed: {e}"))?;
	let result = formatter
		.wait_with_output()
		.map_err(|e| format!("waiting for the Deno formatter failed: {e}"))?;
	if !result.status.success() {
		return Err(format!("Deno formatter: {}", String::from_utf8_lossy(&result.stderr)));
	}
	String::from_utf8(result.stdout).map_err(|e| format!("the Deno formatter wrote invalid UTF-8: {e}"))
}

pub fn generate() -> Result<String, String> {
	let mut output = String::from("// Generated by rooms-application/examples/browser_metadata.rs. Do not edit.\n");
	output.push_str("export const ROOMS_PERMISSIONS = {\n");
	for &permission in Permission::ALL {
		let _ = writeln!(output, "\t{}: {{", json!(permission.name()));
		write_property(&mut output, "key", json!(permission.key()));
		write_property(&mut output, "prerequisite", json!(permission.prerequisite()));
		output.push_str("\t},\n");
	}
	output.push_str("} as const;\nexport type RoomsPermission = keyof typeof ROOMS_PERMISSIONS;\n");
	output.push_str("export const SESSION_CONTENT = {\n\tdeclaration: {\n");
	write_property(&mut output, "version", session::VERSION);
	write_property(
		&mut output,
		"policyIdentity",
		json!(rooms_application::content::permissions::IDENTITY),
	);
	write_property(&mut output, "permissions", json!(session::SUPPORTED));
	write_property(&mut output, "custodyRoles", json!(custody::Role::ALL));
	write_property(
		&mut output,
		"operationsInterfaces",
		json!(rooms_application::session::operations::mutation::Kind::ALL),
	);
	write_property(
		&mut output,
		"localCommands",
		json!(
			commands::Command::ALL
				.iter()
				.copied()
				.map(Route::Checkpoint)
				.chain(commands::results::Command::ALL.iter().copied().map(Route::Result))
				.filter(|&route| local::recognizes(route))
				.map(|route| match route {
					Route::Checkpoint(command) => json!(command),
					Route::Result(command) => json!(command),
					Route::Effect(_) => unreachable!("local command catalog"),
				})
				.collect::<Vec<_>>()
		),
	);
	write_property(
		&mut output,
		"recordSchemas",
		json!(
			records::SCHEMAS
				.iter()
				.map(|schema| json!({
					"id": format!("{:016x}", schema.id), "version": schema.version,
					"maxPayload": schema.max_payload, "maxEdges": schema.max_edges,
				}))
				.collect::<Vec<_>>()
		),
	);
	write_property(
		&mut output,
		"fieldKey",
		json!("32 lowercase hex digits: nonzero slot and generation"),
	);
	output.push_str("\t},\n\tlimits: {\n");
	for (name, value) in [
		("recordPageBytes", records::PAGE_BYTES),
		("recordPages", records::MAX_PAGES),
		("recordFieldsPerPage", records::FIELDS_PER_PAGE),
		("fieldsPerRole", custody::MAX_FIELDS_PER_ROLE),
		("custodyFields", custody::MAX_CUSTODY_FIELDS),
		("effects", custody::MAX_EFFECTS),
		("resultFields", custody::MAX_RESULT_FIELDS),
		("targetFields", custody::MAX_TARGET_FIELDS),
		("authorityBytes", custody::MAX_AUTHORITY_BYTES),
		("directories", workspace::MAX_DIRECTORIES),
		("conversations", workspace::MAX_CONVERSATIONS),
		("invitations", workspace::MAX_INVITATIONS),
	] {
		write_property(&mut output, name, value);
	}
	output.push_str("\t},\n\tgroups: {\n");
	for &group in session::Group::ALL {
		write_property(&mut output, &json!(group).to_string(), json!(group.fields()));
	}
	output.push_str("\t},\n\tgroupLabels: {\n");
	for &group in session::Group::ALL {
		write_property(&mut output, &json!(group).to_string(), json!(group.label()));
	}
	output.push_str("\t},\n\tpresets: {\n");
	for &preset in session::Preset::ALL {
		let _ = writeln!(output, "\t\t{}: {{", json!(preset));
		for (name, value) in [
			("group", json!(preset.group())),
			("label", json!(preset.label())),
			("description", json!(preset.description())),
			("values", json!(preset.values())),
		] {
			// The containing preset has one extra indentation level.
			let mut property = String::new();
			write_property(&mut property, name, value);
			for line in property.lines() {
				let _ = writeln!(output, "\t{line}");
			}
		}
		output.push_str("\t\t},\n");
	}
	output.push_str("\t},\n} as const;\n");
	output.push_str("export const SESSION_METHOD_REQUIREMENTS = {\n");
	for &method in Method::ALL {
		write_property(
			&mut output,
			&json!(method.name()).to_string(),
			json!(requirements::method(method)),
		);
	}
	output.push_str("} as const;\nexport const SESSION_COMMAND_REQUIREMENTS = {\n");
	for route in commands::Command::ALL
		.iter()
		.copied()
		.map(Route::Checkpoint)
		.chain(commands::results::Command::ALL.iter().copied().map(Route::Result))
		.chain(Effect::ALL.iter().copied().map(Route::Effect))
	{
		let name = match route {
			Route::Checkpoint(c) => json!(c),
			Route::Result(c) => json!(c),
			Route::Effect(c) => json!(c),
		};
		let requirement = requirements::command(route);
		write_property(&mut output, &name.to_string(), json!(requirement));
	}
	output.push_str("} as const;\n");
	canonical_typescript(output)
}
