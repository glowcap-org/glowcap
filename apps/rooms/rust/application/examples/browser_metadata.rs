//! Generate the browser's read-only mirror from its Rust application owners.
use rooms_application::{archive, bridge, direct, directory, failure, files, grants, room, server, session, signaling};
use serde_json::json;
use std::{fmt::Write, path::Path};
#[path = "browser_metadata/session_content.rs"]
mod session_content;

fn write_property(output: &mut String, name: &str, value: impl std::fmt::Display) {
	let value = value.to_string();
	let line = format!("\t\t{name}: {value},");
	if line.chars().count() <= 116 {
		let _ = writeln!(output, "{line}");
	} else {
		let _ = writeln!(output, "\t\t{name}:");
		let _ = writeln!(output, "\t\t\t{value},");
	}
}

fn read(path: &Path) -> Result<String, String> {
	std::fs::read_to_string(path).map_err(|e| format!("reading {} failed: {e}", path.display()))
}
fn write(path: &Path, text: impl AsRef<[u8]>) -> Result<(), String> {
	std::fs::write(path, text).map_err(|e| format!("writing {} failed: {e}", path.display()))
}

fn main() -> Result<(), String> {
	let path = Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/../../lib/application_data.ts"));
	let ui_path = Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/../../web/ui/application_data.ts"));
	let failures_path = Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/../../lib/failure_data.ts"));
	let content_path = Path::new(concat!(
		env!("CARGO_MANIFEST_DIR"),
		"/../../lib/session_content_data.ts"
	));
	let content = session_content::generate()?;
	let mut text = String::from("// Generated by rooms-application/examples/browser_metadata.rs. Do not edit.\n");
	let file_limits = files::FileLimits::default();
	for (name, value) in [
		("MAX_NICK", room::inbox::MAX_NICK),
		("MAX_ROOM", server::rooms::MAX_ROOM),
		("ROOM_ID_BYTES", server::links::ENTROPY_BYTES),
		("MAX_DURABLE_ROOM", server::document::MAX_DURABLE_ROOM),
		("MAX_LINE", room::line::MAX_LINE_BYTES),
		("MAX_AWAY", room::membership::MAX_AWAY),
		("MAX_MESSAGE_FILES", room::line::MAX_MESSAGE_FILES),
		("MAX_ROOM_MESSAGE_BACKLOG", room::inbox::queue::MAX_MESSAGES),
		("MAX_TOPIC", server::rooms::MAX_TOPIC),
		("MAX_FORM_FIELDS", bridge::MAX_FIELDS),
		("MAX_FORM_ACTIONS", bridge::MAX_ACTIONS),
		("MAX_FORM_JSON", bridge::MAX_JSON),
		("MAX_FORM_SCOPE", bridge::MAX_FORM_SCOPE),
		("MAX_FORM_TITLE", bridge::MAX_FORM_TITLE),
		("MAX_FORM_SAID", bridge::MAX_FORM_SAID),
		("MAX_FORM_LABEL", bridge::MAX_FORM_LABEL),
		("MAX_FORM_HINT", bridge::MAX_FORM_HINT),
		("MAX_FORM_VALUE", bridge::MAX_FORM_VALUE),
		("MAX_GATEWAY_JSON", bridge::gateway::MAX_GATEWAY_JSON),
		("MAX_SEAT_PREFIX", room::inbox::metadata::MAX_SEAT_PREFIX),
		("MAX_SEAT_BADGE", room::inbox::metadata::MAX_SEAT_BADGE),
		("MAX_SEAT_SAID", room::inbox::metadata::MAX_SEAT_SAID),
		("MAX_ROOM_FEATURES", room::carries::MAX_FEATURES),
		("MAX_ROOM_FEATURE", room::carries::MAX_FEATURE_BYTES),
		("MAX_NAME_VOUCHERS", server::directory::MAX_NAME_VOUCHERS),
		("NAME_VOUCHER_BYTES", server::directory::NAME_VOUCHER_BYTES),
		("MAX_ROSTER_SEEN", session::snapshot::views::MAX_MEMBERS),
		("MAX_ROOM_MEMBERS", server::rooms::MAX_ROOM_MEMBERS),
		("MAX_ROOM_OFFLINE", server::rooms::MAX_ROOM_OFFLINE),
		("MAX_SESSION_DIRECTORY_ROWS", session::directory::MAX_ROWS),
		("MAX_DIRECTORY_DISCOVERY_ROWS", directory::MAX_ROWS),
		("MAX_DIRECTORY_CURSOR", directory::Cursor::MAX_TEXT),
		("MAX_ROOM_LINKS", server::document::MAX_ROOM_LINKS),
		(
			"MAX_TROUBLE_SOURCE_BYTES",
			server::operations::journal::MAX_SOURCE_BYTES,
		),
		(
			"MAX_TROUBLE_REASON_BYTES",
			server::operations::journal::MAX_REASON_BYTES,
		),
		("MAX_OPERATOR_PAGE", server::operations::operator::MAX_PAGE as usize),
		("MAX_OPERATOR_QUERY", server::operations::operator::MAX_QUERY),
		(
			"MAX_OPERATOR_RETIRE_BATCH",
			server::operations::operator::MAX_RETIRE_BATCH as usize,
		),
		("MAX_OPERATIONS_ROWS", server::operations::MAX_OPERATIONS_ROWS),
		(
			"MAX_OPERATOR_MEMBERS_PER_ROOM",
			server::operations::operator::MAX_MEMBERS_PER_ROOM,
		),
		("MAX_ROOMS_PER_CREATOR", server::rooms::MAX_ROOMS_PER_CREATOR),
		("MAX_ROOM_INVITATIONS", server::rooms::MAX_ROOM_INVITATIONS),
		("MAX_PEERED_ROOMS", server::peering::MAX_PEERED_ROOMS),
		(
			"MAX_PEERED_ROOMS_PER_SOURCE",
			server::peering::MAX_PEERED_ROOMS_PER_SOURCE,
		),
		(
			"PEERED_ROOM_READY_TIMEOUT_MS",
			server::peering::READY_TIMEOUT_MS as usize,
		),
		("BLOB_CHUNK", files::CHUNK_BYTES),
		("MAX_ATTACHMENT_BYTES", files::MAX_FILE_BYTES),
		("MAX_FILE_NAME", files::MAX_FILE_NAME_UNITS),
		("MAX_MIME", files::MAX_MIME_UNITS),
		("MAX_IMAGE_DIM", files::MAX_IMAGE_DIMENSION as usize),
		("MAX_ROOM_ATTACHMENT_BYTES", file_limits.room_bytes),
		("MAX_ROOM_ATTACHMENTS", file_limits.room_files),
		("MAX_ARCHIVE_PENDING_ATTACHMENT_BYTES", archive::blobs::MAX_STAGED_BYTES),
		("MAX_ARCHIVE_CONVERSATION_BYTES", archive::MAX_CONVERSATION_BYTES),
		("MAX_SERVER_ATTACHMENT_BYTES", file_limits.held_bytes),
		("MAX_SERVER_PENDING_BYTES", file_limits.pending_bytes),
		("UPLOAD_IDLE_MS", files::UPLOAD_IDLE_MS as usize),
		("MAX_BLOB_READERS", files::MAX_BLOB_READERS),
		("MAX_DM_INBOXES", server::directory::MAX_DM_INBOXES),
		(
			"DIRECT_REQUEST_COALESCE_MS",
			server::directory::DIRECT_REQUEST_COALESCE_MS as usize,
		),
		(
			"DIRECT_CONVERSATION_ROUTE_TIMEOUT_MS",
			direct::RECIPROCAL_ROUTE_TIMEOUT_MS as usize,
		),
		("REQUEST_TIMEOUT_MS", room::authority::REQUEST_TIMEOUT_MS as usize),
		("MAX_SIGNAL_EXCHANGES", signaling::MAX_EXCHANGES),
		("MAX_SIGNAL_CANDIDATE", signaling::MAX_CANDIDATE),
		("MAX_SIGNAL_ID", signaling::MAX_ID),
		("SIGNAL_EXCHANGE_TIMEOUT_MS", signaling::TIMEOUT_MS as usize),
		("MAX_ACTIVE_SESSION_GRANTS", grants::MAX_ACTIVE_GRANTS),
		("MAX_LIFETIME_SESSION_GRANTS", grants::MAX_LIFETIME_GRANTS),
		("MAX_SESSION_GRANT_LABEL", grants::MAX_GRANT_LABEL_UNITS),
		("MAX_SESSION_GRANT_NOTE", grants::MAX_GRANT_NOTE_UNITS),
		("MAX_ACTIVE_ARCHIVE_SHARES", archive::shares::MAX_ACTIVE),
		("MAX_LIFETIME_ARCHIVE_SHARES", archive::shares::MAX_LIFETIME),
	] {
		let _ = writeln!(text, "export const {name} = {value};");
	}
	let mentions = room::inbox::ROOM_MENTIONS
		.iter()
		.map(|name| json!(name).to_string())
		.collect::<Vec<_>>()
		.join(", ");
	let _ = writeln!(text, "export const ROOM_MENTIONS: readonly string[] = [{mentions}];");
	text.push_str("export const BOOT_CAPS = {\n");
	for cap in server::operations::BOOT_CAPABILITIES {
		let mut words = cap.flag.trim_start_matches("--").split('-');
		let mut key = words.next().unwrap_or_default().to_string();
		for word in words {
			let mut chars = word.chars();
			key.extend(chars.next().into_iter().flat_map(char::to_uppercase));
			key.extend(chars);
		}
		let _ = writeln!(text, "\t{key}: {{");
		for (name, value) in [
			("id", cap.id),
			("flag", cap.flag),
			("env", cap.env),
			("file", cap.file),
			("token", cap.token),
			(
				"label",
				cap.flag
					.strip_prefix("--")
					.ok_or_else(|| format!("boot capability flag {} lacks its -- prefix", cap.flag))?,
			),
		] {
			let _ = writeln!(text, "\t\t{name}: {},", json!(value));
		}
		text.push_str("\t},\n");
	}
	text.push_str("} as const;\n");
	text.push_str("export const ALL_BOOT_CAPS = Object.values(BOOT_CAPS);\n");
	text.push_str("export type OperationsCapability = (typeof ALL_BOOT_CAPS)[number][\"id\"];\n");
	text.push_str(
		"export const OPERATIONS_CAPABILITIES: readonly OperationsCapability[] = ALL_BOOT_CAPS.map((cap) => cap.id);\n",
	);
	let ui = format!(
		"// Generated by rooms-application/examples/browser_metadata.rs. Do not edit.\nexport * from \"../../lib/application_data.ts\";\nexport const DRAFT_SAVE_DEBOUNCE_MS = {};\n",
		session::controller::drafts::SAVE_DEBOUNCE_MS
	);
	let mut failures = String::from("// Generated by rooms-application/examples/browser_metadata.rs. Do not edit.\n");
	let _ = writeln!(
		failures,
		"export const MAX_RETRY_DELAY_MS = {};",
		rooms_application::admission::MAX_RETRY_DELAY_MS
	);
	failures.push_str("export const ADMISSION_SCOPES = [\n");
	for class in rooms_application::admission::CLASSES {
		let _ = writeln!(failures, "\t\"{}\",", class.name());
	}
	failures.push_str("] as const;\n");
	failures.push_str("export const ADMISSION_OWNERS = [\n");
	for owner in rooms_application::admission::OWNERS {
		let _ = writeln!(failures, "\t\"{}\",", owner.name());
	}
	failures.push_str("] as const;\n");
	for definition in failure::DEFINITIONS {
		let constant = definition.code.wire().replace('-', "_").to_uppercase();
		let _ = writeln!(failures, "export const {constant} = {};", json!(definition.code.wire()));
	}
	failures.push_str("export const ROOMS_FAILURES = {\n");
	for definition in failure::DEFINITIONS {
		let _ = writeln!(failures, "\t{}: {{", json!(definition.code.wire()));
		write_property(&mut failures, "subject", json!(definition.subject));
		write_property(&mut failures, "retry", json!(definition.retry.wire()));
		write_property(&mut failures, "summary", json!(definition.summary));
		write_property(&mut failures, "action", json!(definition.action));
		failures.push_str("\t},\n");
	}
	failures.push_str("} as const;\n");
	failures.push_str("export type RoomsErrorCode = keyof typeof ROOMS_FAILURES;\n");
	failures.push_str("export type RoomsFailureRetry = (typeof ROOMS_FAILURES)[RoomsErrorCode][\"retry\"];\n");
	failures.push_str(
		"export const ROOMS_ERROR_CODES: readonly RoomsErrorCode[] = Object.keys(ROOMS_FAILURES) as RoomsErrorCode[];\n",
	);
	if std::env::args().skip(1).any(|arg| arg == "--check") {
		assert_eq!(read(content_path)?, content, "regenerate browser metadata");
		assert_eq!(
			read(path)?,
			text,
			"run cargo run -p rooms-application --example browser_metadata to regenerate browser metadata"
		);
		assert_eq!(
			read(ui_path)?,
			ui,
			"run cargo run -p rooms-application --example browser_metadata to regenerate browser metadata"
		);
		assert_eq!(
			read(failures_path)?,
			failures,
			"run cargo run -p rooms-application --example browser_metadata to regenerate browser metadata"
		);
	} else {
		write(content_path, content)?;
		write(path, text)?;
		write(ui_path, ui)?;
		write(failures_path, failures)?;
	}
	Ok(())
}
