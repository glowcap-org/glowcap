//! Generate the browser's read-only mirror from its Rust application owners.
use rooms_application::{directory, grants, room, server};
use serde_json::json;
use std::{fmt::Write, path::Path};

fn main() {
	let path = Path::new(concat!(env!("CARGO_MANIFEST_DIR"), "/../../web/ui/application_data.ts"));
	let mut text = String::from("// Generated by rooms-application/examples/browser_metadata.rs. Do not edit.\n");
	for (name, value) in [
		("MAX_NICK", room::inbox::MAX_NICK),
		("MAX_ROOM", server::rooms::MAX_ROOM),
		("MAX_LINE", room::line::MAX_LINE_BYTES),
		("MAX_AWAY", room::membership::MAX_AWAY),
		("MAX_MESSAGE_FILES", room::line::MAX_MESSAGE_FILES),
		("MAX_DIRECTORY_DISCOVERY_ROWS", directory::MAX_ROWS),
		("MAX_SESSION_GRANT_LABEL", grants::MAX_GRANT_LABEL_UNITS),
		("MAX_SESSION_GRANT_NOTE", grants::MAX_GRANT_NOTE_UNITS),
	] {
		writeln!(text, "export const {name} = {value};").unwrap();
	}
	let mentions = room::inbox::ROOM_MENTIONS
		.iter()
		.map(|name| json!(name).to_string())
		.collect::<Vec<_>>()
		.join(", ");
	writeln!(text, "export const ROOM_MENTIONS: readonly string[] = [{mentions}];").unwrap();
	text.push_str("export const ALL_BOOT_CAPS = [\n");
	for cap in server::operations::BOOT_CAPABILITIES {
		text.push_str("\t{\n");
		for (name, value) in [
			("id", cap.id),
			("flag", cap.flag),
			("env", cap.env),
			("file", cap.file),
			("token", cap.token),
			("label", cap.flag.strip_prefix("--").unwrap()),
		] {
			writeln!(text, "\t\t{name}: {},", json!(value)).unwrap();
		}
		text.push_str("\t},\n");
	}
	text.push_str("] as const;\n");
	text.push_str("export type OperationsCapability = (typeof ALL_BOOT_CAPS)[number][\"id\"];\n");
	text.push_str(
		"export const OPERATIONS_CAPABILITIES: readonly OperationsCapability[] = ALL_BOOT_CAPS.map((cap) => cap.id);\n",
	);
	if std::env::args().skip(1).any(|arg| arg == "--check") {
		assert_eq!(
			std::fs::read_to_string(path).expect("generated browser metadata"),
			text,
			"run cargo run -p rooms-application --example browser_metadata to regenerate browser metadata"
		);
	} else {
		std::fs::write(path, text).unwrap();
	}
}
