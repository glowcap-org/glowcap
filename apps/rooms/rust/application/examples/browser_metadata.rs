fn write_property(output: &mut String, name: &str, value: impl std::fmt::Display) {
	let value = value.to_string();
	let line = format!("\t\t{name}: {value},");
	if line.chars().count() <= 116 {
		let _ = writeln!(output, "{line}");
	} else {
		let _ = writeln!(output, "\t\t{name}:");
		let _ = writeln!(output, "\t\t\t{value},");
	}
}

fn read(path: &Path) -> Result<String, String> {
	std::fs::read_to_string(path).map_err(|e| format!("reading {} failed: {e}", path.display()))
}
fn write(path: &Path, text: impl AsRef<[u8]>) -> Result<(), String> {
	std::fs::write(path, text).map_err(|e| format!("writing {} failed: {e}", path.display()))
}

